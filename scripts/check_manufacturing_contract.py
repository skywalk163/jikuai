# 汇总
# ---------------------------------------------------------------------------

def 校验(块根: pathlib.Path, 评测集路径: pathlib.Path,
        语义层路径: pathlib.Path, 数据集目录: pathlib.Path) -> tuple:
    """跑四条断言，返回 (问题列表, 通过说明列表, 跳过说明列表)。"""
    问题, 通过, 跳过 = [], [], []

    条1问题, 条1过 = 校验预置异常(评测集路径)
    问题 += ["[断言1 预置异常] " + 条 for 条 in 条1问题]
    if 条1过:
        通过.append("[断言1 预置异常] " + 条1过)

    块表 = 收集块(块根)
    if not 块表:
        问题.append("[断言2/3 块库] %s/%s 下一个块都没扫到（块根 %s）——"
                    "制造域块库缺失，第 2、3 条无从检查，不当通过"
                    % (块根.name, 领域名, 块根))
    else:
        条2问题, 条2过 = 校验口径关键词(块表)
        问题 += ["[断言2 口径关键词] " + 条 for 条 in 条2问题]
        if 条2过:
            通过.append("[断言2 口径关键词] " + 条2过)

        条3问题, 条3过 = 校验分歧点(块表)
        问题 += ["[断言3 三处分歧点] " + 条 for 条 in 条3问题]
        if 条3过:
            通过.append("[断言3 三处分歧点] " + 条3过)

    条4问题, 条4过, 条4跳 = 校验语义层(语义层路径, 数据集目录)
    问题 += ["[断言4 语义层↔表头] " + 条 for 条 in 条4问题]
    if 条4过:
        通过.append("[断言4 语义层↔表头] " + 条4过)
    if 条4跳:
        跳过.append("[断言4 语义层↔表头] " + 条4跳)

    return 问题, 通过, 跳过


def main(argv: list | None = None) -> int:
    p = argparse.ArgumentParser(
        prog="check_manufacturing_contract",
        description="G22 · 制造域口径契约门禁（ADR-40 §6，四条断言）")
    p.add_argument("--块根", default=None,
                   help="块库根目录，默认 src/jikuai/stdlib/blocks")
    p.add_argument("--评测集", default=None,
                   help="默认 tools/ai-bridge/评测集-chatbi.json")
    p.add_argument("--语义层", default=None,
                   help="默认 <块根>/制造/语义层.json")
    p.add_argument("--数据集", default=None,
                   help="默认 赛题/chatbi/数据集；不在场则显式跳过第 4 条")
    p.add_argument("--quiet", action="store_true",
                   help="只打一行结论且全部输出走 stderr（供 check_stdlib_contract 串用）")
    args = p.parse_args(argv)

    块根 = pathlib.Path(getattr(args, "块根") or 默认块根)
    评测集路径 = pathlib.Path(getattr(args, "评测集") or 默认评测集)
    语义层路径 = pathlib.Path(getattr(args, "语义层")
                             or (块根 / 领域名 / 语义层文件名))
    数据集目录 = pathlib.Path(getattr(args, "数据集") or 默认数据集)

    if not 块根.is_dir():
        print("  [错误] 块根目录不存在：%s" % 块根, file=sys.stderr)
        return 2

    出 = sys.stderr if args.quiet else sys.stdout
    if not args.quiet:
        print("G22 · 制造域口径契约门禁（ADR-40 §6 · 块根 %s）" % 块根)

    try:
        问题, 通过, 跳过 = 校验(块根, 评测集路径, 语义层路径, 数据集目录)
    except (ValueError, OSError, KeyError, TypeError) as e:
        # 同 G16/G17：新门禁**不**学 G13+ 的 except→跳过。解析不了就是它自己坏了。
        print("错误：G22 制造域口径契约门禁自身解析失败：%s: %s"
              % (type(e).__name__, e), file=sys.stderr)
        return 1

    if not args.quiet:
        for 条 in 通过:
            print("  [通过] %s" % 条)

    # 跳过说明**任何模式下都打**：静默跳过与通过无法区分，正是本门禁要防的病。
    for 条 in 跳过:
        print("  [跳过] %s" % 条, file=出)

    if 问题:
        print("错误：G22 制造域口径契约门禁失败（%d 条）" % len(问题),
              file=sys.stderr)
        for 条 in 问题:
            print("  [失败] %s" % 条, file=sys.stderr)
        print("  修复：口径正本是 docs/ADR-40-制造域数据模型.md §5/§6。"
              "要改口径先改 ADR-40，再改块与本门禁的冻结表，"
              "顺序反了等于让代码悄悄取代文档当真源。", file=sys.stderr)
        return 1

    print("G22 制造域口径契约：通过（断言 1 预置异常 %d/%d · 断言 2 %d 块口径关键词 · "
          "断言 3 三处分歧点 · 断言 4 %s）"
          % (len(预置异常表), len(预置异常表), len(收集块(块根)),
             "跳过（数据集缺失）" if 跳过 else "语义层↔表头零偏差"),
          file=出)
    return 0


if __name__ == "__main__":
    sys.exit(main())
