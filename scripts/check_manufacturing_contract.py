# 断言 4：语义层 ↔ 真实 CSV 表头
# ---------------------------------------------------------------------------

def 校验语义层(语义层路径: pathlib.Path, 数据集目录: pathlib.Path) -> tuple:
    """返回 (问题列表, 通过说明, 跳过说明)。

    数据集不在场时 **显式 skip**：返回 (空问题, None, 跳过说明)。
    """
    if not 语义层路径.is_file():
        return (["语义层不存在：%s" % 语义层路径], None, None)
    数据 = 读json(语义层路径)
    条目 = 数据.get("条目")
    if not isinstance(条目, list) or not 条目:
        return (["%s 里没有 `条目` 列表——语义层结构变了，本门禁拒绝静默通过"
                 % 语义层路径.name], None, None)

    if not 数据集目录.is_dir():
        return ([], None,
                "因数据集缺失跳过第 4 条（语义层 ↔ 真实 CSV 表头）："
                "%s 不在场。`赛题/` 不进 wheel/sdist（ADR-40 §7 已实证），"
                "拿不到数据集就**不能**假装这一条通过" % 数据集目录)

    # 表头缓存：8 张表被 40 多条业务词反复引用，别读 40 遍
    表头缓存 = {}
    问题 = []
    映射数 = 0

    def 查一处(表名, 列名, 出处):
        nonlocal 映射数
        映射数 += 1
        表名 = (表名 or "").strip()
        列名 = (列名 or "").strip()
        if not 表名 or not 列名:
            问题.append("%s：`表`/`字段` 有空值（表=%r 字段=%r）"
                        % (出处, 表名, 列名))
            return
        if 表名 not in 表头缓存:
            路径 = 数据集目录 / (表名 + ".csv")
            表头缓存[表名] = 读表头(路径) if 路径.is_file() else None
        表头 = 表头缓存[表名]
        if 表头 is None:
            问题.append("%s：指向的表 %s.csv 在数据集里不存在" % (出处, 表名))
            return
        if 列名 not in 表头:
            问题.append("%s：%s.csv 里没有列 %r（真实表头 %s）"
                        % (出处, 表名, 列名, 表头))

    for 条 in 条目:
        业务词 = (条.get("业务词") or "?").strip()
        查一处(条.get("表"), 条.get("字段"), "语义层「%s」" % 业务词)
        分母 = 条.get("分母")
        if isinstance(分母, dict):
            查一处(分母.get("表"), 分母.get("字段"),
                  "语义层「%s」的 分母" % 业务词)

    if 问题:
        return (问题, None, None)
    return ([], "语义层 %d 条业务词 / %d 处 表.字段 映射与真实 CSV 表头零偏差"
                "（%d 张表，utf-8-sig）"
                % (len(条目), 映射数, len(表头缓存)), None)


