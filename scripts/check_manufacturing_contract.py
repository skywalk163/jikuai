"""G22 · 制造域口径契约门禁（v0.26.0 W144 · ADR-40 §6）。

四条断言（ADR-40 §6 的三条 + W139 并入的第四条）：

1. **`tools/ai-bridge/评测集-chatbi.json` 里 5 个预置异常恰好命中，不多不少。**
2. **`制造` 域每个块的 `描述` 必须含口径声明关键词**（分母 / 汇总 / 加权 /
   现成列 / 重算 / 窗口 至少命中一项）—— 把 ADR-40 §3.2 的要求变成可执行检查。
3. **ADR-40 §5 三处分歧点各自都有两侧口径，缺一侧就红。**
4. **语义层 `表.字段` ↔ 真实 CSV 表头零偏差**（W139 的校验脚本并入本门禁）。

「恰好」怎么判（第 1 条，四层）
------------------------------
「恰好 5 条」不能只数个数 —— 数量对而内容换掉了照样过，那种门禁等于没有。
所以拆成四层，任一层不过就红：

- **1a 编号集合严格相等**：`{A_01..A_05}`，多一条（`A_06`）少一条（删掉 `A_03`）
  都当场对不上。
- **1b 每条的关键实体全在**：ADR-40 §6 第 1 条把 5 个答案连车型/产线/日期窗口/
  工序都写明了，逐条比对 `需求` + `期望结果` 的合并文本。**只对上编号不算命中** ——
  把 `A_03` 的内容悄悄换成另一个客户，编号集合仍然相等，但这一层会红。
  同一实体允许多种写法（`2026-06` / `2026年6月`），给的是候选组、命中其一即可。
- **1c 序号自述对齐**：第 k 条的 `期望结果` 必须自称 `预置异常 k：`，
  防止五条内容互相错位。
- **1d 非 `A_` 用例不许自称预置异常**：否则可以把第 6 个异常伪装成
  `Q_PUB_011` 混进来，绕过 1a 的编号集合。

第 3 条第三处（缺陷率）为什么不是「两个块」
------------------------------------------
达成率与单车电耗那两处，两侧口径各有一个独立块（`达成率权重`/`达成率均值`、
`单车电耗现成`/`单车电耗重算`）。缺陷率**不是**这样：它的「另一侧」是
「先算行级比率再平均」，而那个口径**是错的** —— 两表粒度不同（缺陷表 2992 行带
工序/缺陷类型/严重度三维，产量表 2896 行），行级比率根本对不上，平均出来没有业务
含义（`缺陷率` 块描述里的实测：2026-06 先汇总后相除 0.050550 vs 行级比率平均
0.032218，差 57%）。

**为一个已知错误的口径造一个块，等于把错口径升格成「可选口径」**，那与 AGENTS.md
第四节要防的「兄弟能力缺位」是同一种病（照着用会跑通、结果是错的）。所以这一处按
「一个块 + 描述里显式点名并否掉另一侧 + 分子侧姊妹块在位」判：

- `制造/缺陷率` 在位，且 `描述` 同时含 `先汇总后相除`（自报采纳口径）与
  `行级比率`（点名另一侧），并含一句明确的否决表述；
- 分子侧的绝对汇总块 `制造/缺陷汇总` 在位，且被 `缺陷率` 的描述点名。

这样既不放水（描述里删掉「非行级比率的平均」当场红，见反例测试），也不逼着造一个
不该存在的块。**这条判法与 ADR-40 §6 第 3 条的字面「各有两个块」有出入，已在
W144 报告里提请修订 ADR-40。**

第 4 条：数据集不在场时显式 skip，绝不静默当通过
------------------------------------------------
`赛题/` 是仓库顶层目录、**不进 wheel / sdist**（ADR-40 §7 已实证），CI 上是否
checkout 得到取决于它有没有被提交。所以第 4 条拿不到数据集时**打印
「因数据集缺失跳过第 4 条」并在结论行里带上跳过标记**，不假装通过 —— 静默通过
会让「语义层指向不存在的列」这类事故在没有数据集的环境里永远抓不到。

第 2 条的已知弱点（写在这里，免得它被当成比实际更强的保证）
----------------------------------------------------------
关键词是**子串命中**，所以 `不汇总`、`不加权` 这类**否定式**表述同样算命中。
它证明的是「描述在口径维度上表过态」，**不**证明口径写得对。口径对不对由块自测与
W140-W142 的 DoD 实测数字保证，不是本条。

零第三方依赖
------------
只用标准库（`csv` / `json` / `pathlib` / `argparse`）。CSV 一律 `utf-8-sig`
—— 8 张表都带 BOM，用 `utf-8` 读会让第一个列名变成 `\ufeffmodel_id` 而假红。

用法
----
    python scripts/check_manufacturing_contract.py                # 查真仓库
    python scripts/check_manufacturing_contract.py --quiet        # 结论走 stderr
    python scripts/check_manufacturing_contract.py --块根 <目录>   # 反例测试用
    python scripts/check_manufacturing_contract.py --数据集 <目录>

`--quiet` 的约定（与 `check_protocol_doc.py`/G16 同款，供 `check_stdlib_contract.py`
串用）：**全部输出走 stderr，且只打一行结论**（失败时附明细）。这样主门禁在
`--json` 模式下 stdout 仍是纯 JSON，而 G22 的结论行照样单独可见 ——
不会被 G12 之类的红掩盖。

退出码 0 全过 / 1 有违规 / 2 用法或环境问题（`--块根` 指的目录根本不存在等）。
"""

