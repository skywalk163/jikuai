def 校验预置异常(评测集路径: pathlib.Path) -> tuple:
    """返回 (问题列表, 通过说明)。判法四层见模块 docstring。"""
    if not 评测集路径.is_file():
        return (["评测集不存在：%s（ADR-40 §6 第 1 条的 5 个预置异常无处可查）"
                 % 评测集路径], None)
    数据 = 读json(评测集路径)
    用例 = 数据.get("用例")
    if not isinstance(用例, list) or not 用例:
        return (["%s 里没有 `用例` 列表，或它不是列表——评测集结构变了，"
                 "本门禁拒绝静默通过" % 评测集路径.name], None)

    问题 = []
    按编号 = {}
    for 条 in 用例:
        编号 = (条.get("id") or "").strip()
        if 编号 in 按编号:
            问题.append("评测集里 id 重复：%s" % 编号)
        按编号[编号] = 条

    期望编号 = {编号 for 编号, _, _ in 预置异常表}
    实际编号 = {编号 for 编号 in 按编号 if 编号.startswith(异常编号前缀)}

    # 1a 编号集合严格相等
    少 = sorted(期望编号 - 实际编号)
    多 = sorted(实际编号 - 期望编号)
    if 少:
        问题.append("预置异常少了 %s——ADR-40 §6 第 1 条列的是 5 条，"
                    "少一条就不是「恰好」" % 少)
    if 多:
        问题.append("预置异常多了 %s——ADR-40 §6 第 1 条只有 5 条，"
                    "多一条同样不是「恰好」（要加异常先改 ADR-40）" % 多)

    # 1b/1c 逐条查关键实体与序号自述
    for 编号, 序号, 实体组 in 预置异常表:
        条 = 按编号.get(编号)
        if 条 is None:
            continue                       # 1a 已经报过了，不重复刷屏
        文本 = "%s\n%s" % (条.get("需求") or "", 条.get("期望结果") or "")
        缺实体 = [组 for 组 in 实体组 if not any(写法 in 文本 for 写法 in 组)]
        if 缺实体:
            问题.append("%s 的关键实体没对上：缺 %s——编号在、内容被换掉，"
                        "照 ADR-40 §6 第 1 条这不算命中"
                        % (编号, ["/".join(组) for 组 in 缺实体]))
        记号 = "%s %d" % (异常自述, 序号)
        if 记号 not in 文本:
            问题.append("%s 的 期望结果 里没有「%s：」自述——五条内容错位时"
                        "只查实体查不出来" % (编号, 记号))

    # 1d 非 A_ 用例不许自称预置异常
    冒名 = sorted(编号 for 编号, 条 in 按编号.items()
                 if not 编号.startswith(异常编号前缀)
                 and 异常自述 in (条.get("期望结果") or ""))
    if 冒名:
        问题.append("非预置异常用例 %s 的 期望结果 里自称「%s」——"
                    "第 6 个异常伪装成公开题混进来，1a 的编号集合抓不到"
                    % (冒名, 异常自述))

    if 问题:
        return (问题, None)
    return ([], "预置异常 %d/%d 恰好命中（编号集合严格相等 + 关键实体逐条比对 + "
                "序号自述对齐 + 无冒名）" % (len(期望编号), len(预置异常表)))


