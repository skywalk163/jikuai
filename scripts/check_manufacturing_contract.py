# 断言 2：口径声明关键词
# ---------------------------------------------------------------------------

def 校验口径关键词(块表: dict) -> tuple:
    问题 = []
    for 块名 in sorted(块表):
        描述 = 块表[块名]["描述"]
        if not 描述.strip():
            问题.append("%s/%s：`描述` 是空的" % (领域名, 块名))
            continue
        命中 = [词 for 词 in 口径关键词 if 词 in 描述]
        if not 命中:
            问题.append("%s/%s：`描述` 一个口径声明关键词都没有（要求 %s 至少一项）"
                        "——ADR-40 §3.2 要求口径块自报口径，"
                        "描述不表态等于把口径判断甩给选块的人瞎猜"
                        % (领域名, 块名, list(口径关键词)))
    if 问题:
        return (问题, None)
    return ([], "%d 个 %s 域块的 描述 全部含口径声明关键词"
                % (len(块表), 领域名))


