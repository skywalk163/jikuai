def 读json(路径: pathlib.Path):
    """读一份 JSON。**读不动就抛**——新门禁解析不了就是它自己坏了（同 G16/G17）。"""
    with 路径.open("r", encoding="utf-8") as f:
        return json.load(f)


def 收集块(块根: pathlib.Path) -> dict:
    """扫 `<块根>/制造/*/块.json`，返回 {块名: {"描述", "领域", "路径"}}。

    刻意**不**读 `索引.json`：索引忘刷是本项目自己记录的最常见返工原因
    （`贡献指南.md`），拿它当真源会让「块加了但索引没刷」时本门禁跟着一起瞎。
    索引一致性归 G11 管。
    """
    域目录 = 块根 / 领域名
    表 = {}
    if not 域目录.is_dir():
        return 表
    for 子 in sorted(域目录.iterdir()):
        if not 子.is_dir():
            continue                      # 语义层.json 这类数据文件不是块
        元 = 子 / "块.json"
        if not 元.is_file():
            continue
        数据 = 读json(元)
        表[子.name] = {
            "描述": 数据.get("描述") or "",
            "领域": 数据.get("领域") or [],
            "路径": 元,
        }
    return 表


def 读表头(csv路径: pathlib.Path) -> list:
    """读一张 CSV 的表头。`utf-8-sig` 是必需而非防御——8 张表都带 BOM。"""
    with csv路径.open("r", encoding="utf-8-sig", newline="") as f:
        for 行 in csv.reader(f):
            return 行
    return []


