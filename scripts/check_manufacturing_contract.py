def _查必含(块表, 块名, 必含, 场景):
    """块在位且描述含全部必含词，返回问题列表。"""
    问题 = []
    if 块名 not in 块表:
        问题.append("%s：缺块 %s/%s（%s）——ADR-40 §5 的分歧点缺一侧，"
                    "选块的人就看不见还有另一个口径，会把默认口径当唯一口径"
                    % (场景, 领域名, 块名, 必含 and "口径声明" or ""))
        return 问题
    描述 = 块表[块名]["描述"]
    缺 = [词 for 词 in 必含 if 词 not in 描述]
    if 缺:
        问题.append("%s：%s/%s 的 描述 里缺口径自述 %s"
                    % (场景, 领域名, 块名, 缺))
    return 问题


def 校验分歧点(块表: dict) -> tuple:
    问题 = []
    通过 = []
    for 处 in 分歧点表:
        场景 = "分歧点「%s」" % 处["名"]
        if 处["模式"] == "双块":
            甲, 乙 = 处["两侧"]
            问题 += _查必含(块表, 甲["块"], 甲["必含"], 场景)
            问题 += _查必含(块表, 乙["块"], 乙["必含"], 场景)
            # 互相点名：ADR-40 §5.1 明写「禁止只做一个块然后在描述里含糊」，
            # 两块互不知情等价于让人漏看另一个口径。
            for 这, 那 in ((甲, 乙), (乙, 甲)):
                if 这["块"] in 块表 and 那["块"] in 块表:
                    if 那["块"] not in 块表[这["块"]]["描述"]:
                        问题.append("%s：%s/%s 的 描述 没点名另一侧 %s/%s——"
                                    "两块必须互相点名"
                                    % (场景, 领域名, 这["块"],
                                       领域名, 那["块"]))
            if not 问题:
                通过.append("%s：%s（%s）+ %s（%s）两侧齐、互相点名"
                            % (场景, 甲["块"], 甲["口径"], 乙["块"], 乙["口径"]))
        else:
            块名 = 处["块"]
            问题 += _查必含(块表, 块名, 处["采纳口径必含"], 场景)
            问题 += _查必含(块表, 块名, 处["点名另一侧必含"], 场景)
            if 块名 in 块表:
                描述 = 块表[块名]["描述"]
                if not any(句 in 描述 for 句 in 处["否决表述候选"]):
                    问题.append("%s：%s/%s 的 描述 点了另一侧「行级比率」却没有"
                                "明确否决表述（要 %s 之一）——只提一句不否掉，"
                                "读的人会以为那也是个可选口径"
                                % (场景, 领域名, 块名,
                                   list(处["否决表述候选"])))
                姊妹 = 处["姊妹块"]
                if 姊妹 not in 块表:
                    问题.append("%s：缺%s姊妹块 %s/%s"
                                % (场景, 处["姊妹块理由"], 领域名, 姊妹))
                elif 姊妹 not in 描述:
                    问题.append("%s：%s/%s 的 描述 没点名%s姊妹块 %s"
                                % (场景, 领域名, 块名, 处["姊妹块理由"], 姊妹))
            if not 问题:
                通过.append("%s：%s 单块 + 描述显式否掉行级比率平均 + 分子侧姊妹块 %s"
                            "（另一侧是已知错口径，刻意不造块，见脚本 docstring）"
                            % (场景, 块名, 处["姊妹块"]))
    if 问题:
        return (问题, None)
    return ([], "ADR-40 §5 三处分歧点全部就位：\n      - "
                + "\n      - ".join(通过))


