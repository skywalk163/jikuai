def is_idiom(text) -> bool:
    """判定 text 是否为内置词库中的四字成语。

    宽容策略：非字符串、空串、长度不为 4 一律返回 False 而不报错——
    「断言」类函数对任何输入都应该给出是/否的答案。
    首尾空白会被忽略（" 一帆风顺 " 视为 "一帆风顺"）。
    """
    if not isinstance(text, str):
        return False
    word = text.strip()
    if len(word) != 4:
        return False
    return word in IDIOMS


def is_xiehouyu(first, second) -> bool:
    """判定 (前半, 后半) 是否构成内置词库中的歇后语。

    前半不在词库中、或后半与词库记载不符，均返回 False。首尾空白会被忽略。
    """
    if not isinstance(first, str) or not isinstance(second, str):
        return False
    head = first.strip()
    tail = second.strip()
    if not head or not tail:
        return False
    return XIEHOUYU.get(head) == tail