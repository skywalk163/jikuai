# -*- coding: utf-8 -*-
"""制造.产量汇总 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层**块（ADR-40 §3.2），不是引擎层算子。它只声明并执行一个口径：

    产量 = fact_production_actual.actual_quantity 按维度列**求和**

产量是可加绝对量（单位：台），跨维度合计有业务含义，所以口径是求和而不是
平均。返回值不做舍入、不换算单位，出的就是台数。

与 制造.分组汇总（导出 `维聚`）的分工
------------------------------------
`维聚` 是通用 group-by：对任意度量列出六个聚合量，空值跳过并另报非空个数。
本块窄得多，但多了三条口径判断，这也是它存在的全部理由：

1. **产量列出现空值直接报错**，不跳过、不填 0。产量表实测零空值
   （ADR-40 §4.3：全数据集只有 `fact_orders` 两列有空值），所以空值只有两种
   来源——数据源换了，或上游 `联表` 漏配。`维聚` 的「跳过 + 另报非空个数」在
   通用层是对的；在产量口径上，那等于让分子悄悄变小而报表看着完全正常。
2. **拒绝汇总现成比率列**：`achievement_rate` / `energy_per_vehicle`（数据集里
   实测唯一的两个现成比率列，语义层 `现成比率列: true`）传进来当场报错。对比率
   列求和没有业务含义，而 `维聚` 会老老实实加起来给一个错数。
3. **结果按产量降序**（Q_PUB_001「按产量从高到低排序」要的就是排名），`维聚`
   按维度键升序。

维度键空值：**自成一组不丢弃**，与 `维聚` 同口径。丢弃会让「各车型产量合计」
不等于「总产量」——这种静默不守恒是 BI 里最难查的错。

行序确定性
----------
主键产量降序，同产量时按维度键升序（`_排序键` 给出全序，`None` 排最前）。
只按产量排会在并列时行序不定，上层「取前 N」就不可复现。

不做的事：不筛选、不切窗口、不联维表、不算比率。范围先用 制造.窗口(`截期`)
或 制造.选取(`筛行`) 切；中文车型名用 制造.连接(`联表`) 联 `dim_model`；
达成率去 制造.达成率权重(`达权`) / 制造.达成率均值(`达均`)。

零第三方依赖（WBS 执行原则第 6 条）：本文件只用 Python 内置类型与 `sorted`。
"""

#: 数据集里实测唯一的两个**现成比率列**（ADR-40 §5 修正框、语义层 `现成比率列`）。
#: 对它们求和没有业务含义，本块直接拒绝。
_现成比率列 = ('achievement_rate', 'energy_per_vehicle')

#: 本块固定输出的聚合列名。维度列与它们撞名会静默覆盖结果，先挡下
#: （不静默覆盖，与 W135 连接算子的列名冲突策略同口径）。
_固定列 = ('产量', '记录数')


def _排序键(组键):
    """把可能含空值 / 混合类型的维度键映射成可确定排序的元组。

    分档：`None` → 0、布尔 → 1、数值 → 2、其余（字符串等）→ 3；同档内按值升序。
    分档是必要的：Python 3 里 `None < "M001"` 直接 TypeError，而维度列确实会
    出现空值。分了档才有全序，同产量并列时的行序才真的确定。
    """
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def 计产(表, 维度列, 产量列):
    """按维度列汇总产量，按产量降序返回。

    入参：
      表      —— 列表<字典<字符串,任意>>，行的列表（ADR-40 §3.1 的表表示）
      维度列  —— 列名字符串的列表，可多列（复合维度，如 `line_id` + `shift`）
      产量列  —— 实际产量列名，通常是 `actual_quantity`

    出参：列表<字典<字符串,任意>>，每组一行，键为各维度列名 + `产量` + `记录数`。
      `产量` = 组内产量之和（台），`记录数` = 参与汇总的行数。
      按 `产量` 降序；同产量按维度键升序（空值键排最前）。

    报错口径（都是「宁可报错也不给错数」）：
      * 维度列 / 产量列在任一行不存在 → 报错，不静默返回空表
      * 产量列出现 `空` → 报错，不跳过也不填 0
      * 产量列出现非数值（含布尔） → 报错
      * 产量列是现成比率列 → 报错
    空表输入是合法的，返回空表（那是「没有数据」，不是错误）。
    """
    if not isinstance(维度列, list):
        raise ValueError('产量汇总：维度列必须是列名的列表，得到 %s'
                         % type(维度列).__name__)
    if not 维度列:
        raise ValueError('产量汇总：维度列不能为空——本块是「按维度汇总产量」，'
                         '至少要一个维度列；要全表一个总数请传单一常量维度列，'
                         '或用 数据 域的求和块')
    for 列 in 维度列:
        if not isinstance(列, str):
            raise ValueError('产量汇总：维度列的每一项必须是列名字符串，得到 %r' % (列,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('产量汇总：维度列有重复项 %r' % (维度列,))
    if not isinstance(产量列, str):
        raise ValueError('产量汇总：产量列必须是单个列名字符串，得到 %s'
                         % type(产量列).__name__)
    if 产量列 in 维度列:
        raise ValueError('产量汇总：产量列「%s」同时出现在维度列里 %r；'
                         '拿被汇总的度量当分组键是口径错误' % (产量列, 维度列))
    if 产量列 in _现成比率列:
        raise ValueError(
            '产量汇总：产量列「%s」是数据集里的**现成比率列**，对比率列求和没有'
            '业务含义，本块拒绝汇总。要平均达成率请用 制造/达成率权重(达权) 或 '
            '制造/达成率均值(达均)；要单车电耗请用 制造 域的单车电耗块。'
            % 产量列)
    撞名 = [列 for 列 in 维度列 if 列 in _固定列]
    if 撞名:
        raise ValueError('产量汇总：维度列 %s 与本块固定输出的列名撞车（%s），'
                         '会静默覆盖汇总结果；请先用 制造/投影 改名'
                         % (撞名, '/'.join(_固定列)))

    # 空表：没有行可汇总，返回空结果表。这是「没有数据」而不是错误，也无从
    # 校验列是否存在（一行都没有，表头无处可查）。
    if not isinstance(表, list):
        raise ValueError('产量汇总：表必须是行的列表，得到 %s' % type(表).__name__)
    if not 表:
        return []

    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('产量汇总：表的第 %d 行不是字典（表必须是行的列表，'
                             '每行是列名→值的字典），得到 %s'
                             % (序, type(行).__name__))

    # 列存在性：要求**每一行**都有这些列。只查首行会漏掉参差表，漏掉的后果是
    # 某些行悄悄按「空值」入组，比报错难查得多。
    for 列 in list(维度列) + [产量列]:
        角色 = '维度列' if 列 in 维度列 else '产量列'
        for 序, 行 in enumerate(表, start=1):
            if 列 not in 行:
                raise ValueError(
                    '产量汇总：%s「%s」在表的第 %d 行不存在（该行的列：%s）；'
                    '不静默返回空表，请核对列名'
                    % (角色, 列, 序, sorted(行.keys())))

    桶表 = {}
    for 序, 行 in enumerate(表, start=1):
        值 = 行[产量列]
        if 值 is None:
            raise ValueError(
                '产量汇总：产量列「%s」在第 %d 行是空值。本块**不跳过也不填 0**：'
                'fact_production_actual 实测零空值（ADR-40 §4.3），出现空值意味着'
                '数据源不对或上游连接漏配；跳过会让产量合计悄悄变小而报表看着正常。'
                '确实要排除这些行，请先用 制造/选取(筛行) 显式筛掉。'
                % (产量列, 序))
        if isinstance(值, bool) or not isinstance(值, (int, float)):
            raise ValueError(
                '产量汇总：产量列「%s」在第 %d 行是非数值 %r（类型 %s），无法汇总；'
                '产量只接受数值' % (产量列, 序, 值, type(值).__name__))
        组键 = tuple(行[列] for 列 in 维度列)
        桶 = 桶表.get(组键)
        if 桶 is None:
            # 空值维度键照样建桶——这就是「空值自成一组、各组之和守恒」的落点。
            桶 = {'产量': 0, '记录数': 0}
            桶表[组键] = 桶
        桶['产量'] += 值
        桶['记录数'] += 1

    # 双键排序：产量降序为主，维度键升序为次（并列时行序才确定、可复现）。
    组键序 = sorted(桶表, key=_排序键)
    组键序.sort(key=lambda 键: 桶表[键]['产量'], reverse=True)

    结果 = []
    for 组键 in 组键序:
        输出行 = {}
        for 位, 列 in enumerate(维度列):
            输出行[列] = 组键[位]
        输出行['产量'] = 桶表[组键]['产量']
        输出行['记录数'] = 桶表[组键]['记录数']
        结果.append(输出行)
    return 结果
