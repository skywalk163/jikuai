# -*- coding: utf-8 -*-
"""制造.停线汇总 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块**（ADR-40 §3.2）：按维度列汇总 `fact_production_actual` 的
`downtime_minutes`（停线时长）。列名与所在表写死在本模块里，不由调用方传。

列名与单位（自己读表头核实过，不是抄文档）
------------------------------------------
`fact_production_actual` 的真实表头（`utf-8-sig` 读出）：

    actual_id, plan_id, production_date, line_id, model_id, shift,
    actual_quantity, working_hours, downtime_minutes, achievement_rate

所以停线时长列名是 **`downtime_minutes`**，在**生产实绩表**上（不是计划表、
不是能耗表）。粒度：日 × 产线 × 车型 × 班次。

**单位陷阱（本块反复点名的一条）**：`downtime_minutes` 是**分钟**，而同表
`working_hours` 是**小时**。算停线占比必须先换算——
`downtime_minutes / (working_hours × 60)`，直接相除会差 60 倍。本块只汇总分钟数、
**不算占比**，就是为了不把这个换算藏进一个看不见的地方；要占比请自己按上式算，
或等专门的口径块。

空值口径（与 `制造.延期汇总` 同一套纪律）
------------------------------------------
ADR-40 §4.3 实测：**`downtime_minutes` 这一列零空值**——全数据集只有
`fact_orders` 的 `actual_delivery_date` 与 `delay_days` 两列有空值（各 57 行）。
但本块仍然**显式排除空值行并报出排除条数**（元组第 2 项 + 每组 `缺测记录数` 列），
理由有两条：

1. **换一份数据就会有空值**。零空值是本数据集的事实，不是本块的前提。
   把「零空值」写进假设的块，遇到真有停线未记录的数据时会静默把空当 0 分钟，
   得出「这条线没停过」——正是 W142 要防的那类错。
2. **`downtime_minutes` 里有 128 行是 0**（W139 实测，`tests/
   test_v0_26_0_w139_质量体检.py::test_零算合法值不算空值` 钉着）。0 = 那个班次
   真的没停线，是有效数据，进分母、进合计；空 = 没记录，不可比。两者绝不合并。
   本块另出一个 `零停线记录数` 列，让「真没停」这件事看得见，不至于和「没数据」
   在同一个 0 上打架。

输出契约
--------
`计停(表, 维度列)` → `(汇总表, 排除的空值行数)`

`汇总表` 是「行的列表」，每组一行，键为：

  <各维度列名>       —— 该组的维度取值（`维度列` 传空列表时这些键不出现）
  记录数             —— 组内总行数，含缺测（SQL `COUNT(*)`）
  计入记录数         —— `downtime_minutes` 非空的行数，**它是 停线均值分钟 的分母**
  缺测记录数         —— `downtime_minutes` 为空、被本块排除的行数
  零停线记录数       —— `downtime_minutes == 0` 的行数（真没停，**不是**缺测）
  停线合计分钟       —— 非空值求和；计入记录数为 0 时返回 `空` 而非 0
  停线均值分钟       —— 合计 / 计入记录数；计入记录数为 0 时返回 `空`
  最长停线分钟       —— 非空值最大；计入记录数为 0 时返回 `空`

恒等式：`记录数 = 计入记录数 + 缺测记录数`；`sum(各组缺测记录数) = 元组第 2 项`。

行序：按维度键升序（空值键组排最前），与 `制造.分组汇总` 同口径，可复现。
本块**不排序成排行榜**——「停线最长的产线」要接 `制造.排序` + `制造.取前N`。
本块也**不切时间窗口**——「4-08~4-18 哪条线停线偏高」先用 `制造.窗口`（`截期`）
切好再调本块，窗口口径必须由调用方声明，不许块替使用者猜。

零第三方依赖，只用 Python 标准语法。
"""

#: 本块认的停线时长列名。ADR-40 §4.2 冻结的 `fact_production_actual` 列名。
停线列 = 'downtime_minutes'

#: 固定输出列名。与维度列撞车会静默覆盖聚合结果，构造前先挡下。
_固定列 = ('记录数', '计入记录数', '缺测记录数', '零停线记录数',
           '停线合计分钟', '停线均值分钟', '最长停线分钟')


def _排序键(组键):
    """与 `制造.分组汇总._排序键` / `制造.延期汇总._排序键` 同一口径。

    分档：空 0 < 布尔 1 < 数 2 < 其余 3。Python 3 里 `None < "L001"` 直接
    TypeError，分档才有全序、行序才真的确定。
    """
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def _校验维度列(维度列):
    if not isinstance(维度列, list):
        raise ValueError('停线汇总：维度列必须是列名的列表（要整表汇总成一行传 【】），'
                         '得到 %s' % type(维度列).__name__)
    for 列 in 维度列:
        if not isinstance(列, str):
            raise ValueError('停线汇总：维度列的每一项必须是列名字符串，得到 %r' % (列,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('停线汇总：维度列有重复项 %r' % (维度列,))
    撞名 = [列 for 列 in 维度列 if 列 in _固定列]
    if 撞名:
        raise ValueError('停线汇总：维度列 %s 与本块固定输出的列名撞车（%s），'
                         '会静默覆盖统计结果；请先用 制造/投影 改名'
                         % (撞名, '/'.join(_固定列)))
    if 停线列 in 维度列:
        raise ValueError('停线汇总：不能把停线时长列「%s」自己当维度列——'
                         '本块要对它做汇总，拿它分组等于按每个分钟数各成一组' % 停线列)


def _分钟(值, 序):
    """停线分钟的非空值必须是数值，且不接受负数。

    布尔显式排除（`True` == 1 会悄悄多出一分钟停线）；负分钟没有业务含义，
    几乎肯定是上游数据错，报错而不是照收。
    """
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError(
            '停线汇总：第 %d 行的「%s」是非空的非数值 %r（类型 %s），无法汇总。'
            '停线时长只接受数值或 空（空 = 未记录，本块会把它排除并计数；'
            '0 = 该班次真的没停线，是有效数据）'
            % (序, 停线列, 值, type(值).__name__))
    if 值 < 0:
        raise ValueError(
            '停线汇总：第 %d 行的「%s」是负数 %r。停线时长没有负分钟的语义，'
            '照收会让某条产线的合计被悄悄扣掉——这是上游数据错，本块拒绝兜'
            % (序, 停线列, 值))
    return 值


def 计停(表, 维度列):
    """按维度汇总 `fact_production_actual.downtime_minutes`（分钟）。

    参数
    ----
    表     : 行的列表（列表<字典<字符串,任意>>），每行必须有 `downtime_minutes` 列
    维度列 : 列名字符串的列表（如 `【"line_id"】`、`【"line_id", "shift"】`）；
             传 `【】` 表示整表汇总成一行

    返回
    ----
    `(汇总表, 排除的空值行数)`，逐项含义见模块 docstring。

    空表输入返回 `([], 0)`。
    """
    _校验维度列(维度列)

    if not isinstance(表, list):
        raise ValueError('停线汇总：表必须是「行的列表」（列表<字典<字符串,任意>>），'
                         '得到 %s' % type(表).__name__)
    if not 表:
        return [], 0

    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('停线汇总：表的第 %d 行不是字典（表必须是行的列表，'
                             '每行是列名→值的字典），得到 %s'
                             % (序, type(行).__name__))

    # 列存在性：要求**每一行**都有这些列（只查首行会漏掉参差表）。
    for 列 in list(维度列) + [停线列]:
        角色 = '维度列' if 列 in 维度列 else '停线时长列'
        for 序, 行 in enumerate(表, start=1):
            if 列 not in 行:
                raise ValueError(
                    '停线汇总：%s「%s」在表的第 %d 行不存在（该行的列：%s）；'
                    '不静默返回空表。停线时长列固定是 %s，在 '
                    'fact_production_actual 上——传成计划表或能耗表就会看到这条错'
                    % (角色, 列, 序, sorted(行.keys()), 停线列))

    桶表 = {}
    排除数 = 0
    for 序, 行 in enumerate(表, start=1):
        组键 = tuple(行[列] for 列 in 维度列)
        桶 = 桶表.get(组键)
        if 桶 is None:
            桶 = {'记录数': 0, '计入记录数': 0, '缺测记录数': 0,
                  '零停线记录数': 0, '合计': None, '最长': None}
            桶表[组键] = 桶
        桶['记录数'] += 1

        值 = 行[停线列]
        if 值 is None:
            # 空 = 未记录。排除出汇总，但记条数（本数据集实测 0 行，
            # 换数据集就不一定了——见模块 docstring 的两条理由）。
            桶['缺测记录数'] += 1
            排除数 += 1
            continue

        值 = _分钟(值, 序)
        桶['计入记录数'] += 1
        if 值 == 0:
            # 0 = 该班次真的没停线，**有效数据**：进分母、进合计（加 0）。
            # 单独计数，免得「真没停」和「没记录」在同一个 0 上打架。
            桶['零停线记录数'] += 1
        桶['合计'] = 值 if 桶['合计'] is None else 桶['合计'] + 值
        桶['最长'] = 值 if 桶['最长'] is None else max(桶['最长'], 值)

    汇总表 = []
    for 组键 in sorted(桶表, key=_排序键):
        桶 = 桶表[组键]
        行 = {}
        for 位, 列 in enumerate(维度列):
            行[列] = 组键[位]
        行['记录数'] = 桶['记录数']
        行['计入记录数'] = 桶['计入记录数']
        行['缺测记录数'] = 桶['缺测记录数']
        行['零停线记录数'] = 桶['零停线记录数']
        行['停线合计分钟'] = 桶['合计']
        # 分母是 计入记录数，不是 记录数。全组皆缺测时返回 空 而不是 0
        # （「没测到」≠「没停线」）。
        行['停线均值分钟'] = (None if 桶['计入记录数'] == 0
                          else 桶['合计'] / 桶['计入记录数'])
        行['最长停线分钟'] = 桶['最长']
        汇总表.append(行)
    return 汇总表, 排除数
