# -*- coding: utf-8 -*-
"""制造.分组汇总 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

引擎层关系算子 **group-by**：按维度列列表分组，一次遍历同时算出
`行数` / `非空个数` / `求和` / `均值` / `最大` / `最小` 六个量。上层口径块
（W140-W142）会反复调它，所以多个聚合量必须一趟扫完，不能让调用方为了拿
四个数扫表四次。

**不含业务口径**：本模块不认识「产量」「达成率」「缺陷率」，只对调用方点名的
度量列做通用数值聚合。ADR-40 §5 那三处口径分歧（加权 vs 行级平均、现成列 vs
重算、先汇总后相除）不在这一层决定，也不许在这一层偷偷替上层选一个。

**与 数据/分组（导出 聚簇）划清界限**：`聚簇` 把一个列表按固定大小切成等长
若干段，本模块按维度列取值分组后逐组聚合。两者语义完全不同，见 .jk 门面注释。

为什么下沉到 Python 背衬而不是纯 .jk：分组要按复合维度键建桶、要对可能含空值
与混合类型的键做确定性排序、要以维度列名为键动态构造结果字典。这些在纯 .jk
里写起来又长又易错，标准库的 `dict` 保序 + `sorted` 一把梳清。零第三方依赖。

空值语义（本模块最要紧的一处，全部写死、不给开关）
--------------------------------------------------
- **分组键含空值**：空值（极快 `空` ↔ Python `None`）**自成一组，不丢弃**。
  丢弃会让「各车型产量合计」不等于「总产量」——这种静默不守恒是 BI 里最难查
  的错，宁可多出一个「空」组让人看见。
- **度量列含空值**：
  * 计数分两个量：`行数` = 组内行数（含空值行，等价 SQL `COUNT(*)`）、
    `非空个数` = 该度量列非空值个数（等价 `COUNT(col)`）。两者混用是经典错误，
    所以两个都出，不让调用方拿一个当另一个用。
  * `均值` 的**分母是 `非空个数`，不是 `行数`**。全组皆空时 `均值` 返回 `None`。
  * `求和` 跳过空值；**全组皆空时返回 `None`（极快 `空`）而不是 0**——
    「没有数据」与「合计为零」不是一回事。
  * `最大` / `最小` 同样跳过空值，全组皆空返回 `None`。
- **行序确定**：结果按维度键升序排列（见 `_排序键`），同一输入两次调用结果
  完全一致。不确定的行序会让上层「取前 N」不可复现。

报错口径：维度列或度量列不存在时**抛错**，绝不静默返回空表——静默返回空表会
让上层把「列名拼错」当成「这个维度没有数据」。空表输入是合法的，返回空表。
"""


def _数值(值, 列名):
    """度量列的非空值必须是数值，否则抛可读中文错误。

    布尔显式排除：`True + True = 2` 这种 Python 语义在业务度量里没有意义，
    与其求和求出个 2 让人以后对着报表发呆，不如当场报错。
    """
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError(
            '分组汇总：度量列「%s」出现非空的非数值 %r（类型 %s），无法聚合；'
            '度量列只接受数值或空值'
            % (列名, 值, type(值).__name__))
    return 值


def _排序键(组键):
    """把可能含空值 / 混合类型的维度键映射成可确定排序的元组。

    分档：`None` → 0、布尔 → 1、数值 → 2、其余（字符串等）→ 3；同档内按值升序。
    分档是必要的：Python 3 里 `None < "M001"` 直接 TypeError，而制造域的维度列
    恰恰会出现空值（ADR-40 §4.3：`fact_orders` 两列未交付时为空）。分了档就有
    全序，行序才真的确定——「空值排最前」是本块对外承诺的一部分。
    """
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def 维聚(表, 维度列, 度量列):
    """按维度列分组，对度量列一次遍历算出六个聚合量。

    入参：
      表      —— 列表<字典<字符串,任意>>，行的列表（ADR-40 §3.1 的表表示）
      维度列  —— 列名字符串的列表，可多列（复合维度）
      度量列  —— 单个列名字符串

    出参：列表<字典<字符串,任意>>，仍是一张表，每组一行，键为
      各维度列名 + `行数` / `非空个数` / `求和` / `均值` / `最大` / `最小`。
      按维度键升序，空值键组排最前。

    口径与空值语义见模块 docstring——那是本块的对外承诺，改实现必须同步改那里
    与 `块.json` 的 `描述`。
    """
    if not isinstance(维度列, list):
        raise ValueError('分组汇总：维度列必须是列名的列表，得到 %s'
                         % type(维度列).__name__)
    if not 维度列:
        raise ValueError('分组汇总：维度列不能为空——group-by 至少要一个维度列；'
                         '要算全表单列统计请用 数据 域的标量统计块')
    for 列 in 维度列:
        if not isinstance(列, str):
            raise ValueError('分组汇总：维度列的每一项必须是列名字符串，得到 %r' % (列,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('分组汇总：维度列有重复项 %r' % (维度列,))
    if not isinstance(度量列, str):
        raise ValueError('分组汇总：度量列必须是单个列名字符串，得到 %s'
                         % type(度量列).__name__)

    # 空表：没有行可分组，返回空结果表。这是「没有数据」而不是错误，也无从
    # 校验列是否存在（一行都没有，表头无处可查）。
    if not 表:
        return []

    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('分组汇总：表的第 %d 行不是字典（表必须是行的列表，'
                             '每行是列名→值的字典），得到 %s'
                             % (序, type(行).__name__))

    # 列存在性：要求**每一行**都有这些列。只查首行会漏掉参差表；
    # 漏掉的后果是某些行悄悄按「空值」入组，比报错难查得多。
    for 列 in list(维度列) + [度量列]:
        角色 = '维度列' if 列 in 维度列 else '度量列'
        for 序, 行 in enumerate(表, start=1):
            if 列 not in 行:
                raise ValueError(
                    '分组汇总：%s「%s」在表的第 %d 行不存在（该行的列：%s）；'
                    '不静默返回空表，请核对列名'
                    % (角色, 列, 序, sorted(行.keys())))

    # 维度列名与固定聚合列名撞车会静默覆盖聚合结果，先挡下（不静默覆盖，
    # 与 W135 连接算子的列名冲突策略同口径）。
    固定列 = ('行数', '非空个数', '求和', '均值', '最大', '最小')
    撞名 = [列 for 列 in 维度列 if 列 in 固定列]
    if 撞名:
        raise ValueError('分组汇总：维度列 %s 与本块固定输出的聚合列名撞车（%s），'
                         '会静默覆盖聚合结果；请先用 制造/投影 改名'
                         % (撞名, '/'.join(固定列)))

    桶表 = {}
    for 行 in 表:
        组键 = tuple(行[列] for 列 in 维度列)
        桶 = 桶表.get(组键)
        if 桶 is None:
            # 空值键照样建桶——这就是「空值自成一组」的落点。
            桶 = {'行数': 0, '非空个数': 0, '求和': None,
                  '最大': None, '最小': None}
            桶表[组键] = 桶
        桶['行数'] += 1
        值 = 行[度量列]
        if 值 is None:
            # 度量列空值：只计入 行数，不计入 非空个数，不参与 求和/最大/最小。
            continue
        值 = _数值(值, 度量列)
        桶['非空个数'] += 1
        桶['求和'] = 值 if 桶['求和'] is None else 桶['求和'] + 值
        桶['最大'] = 值 if 桶['最大'] is None else max(桶['最大'], 值)
        桶['最小'] = 值 if 桶['最小'] is None else min(桶['最小'], 值)

    结果 = []
    for 组键 in sorted(桶表, key=_排序键):
        桶 = 桶表[组键]
        输出行 = {}
        for 位, 列 in enumerate(维度列):
            输出行[列] = 组键[位]
        输出行['行数'] = 桶['行数']
        输出行['非空个数'] = 桶['非空个数']
        输出行['求和'] = 桶['求和']
        # 均值的分母是 非空个数：全组皆空时没有分母，返回 空。
        # 这里不做任何舍入——舍入是口径决定（财务/保留分 的 ROUND_HALF_UP），
        # 引擎层出原值，要几位小数由上层口径块说。
        输出行['均值'] = (None if 桶['非空个数'] == 0
                       else 桶['求和'] / 桶['非空个数'])
        输出行['最大'] = 桶['最大']
        输出行['最小'] = 桶['最小']
        结果.append(输出行)
    return 结果
