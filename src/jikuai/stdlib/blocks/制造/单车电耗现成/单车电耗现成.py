# -*- coding: utf-8 -*-
"""制造.单车电耗现成 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块 · ADR-40 §5.2 分歧点 2 的「用现成列」这一侧。**

块名换名记录（ADR-15 §3.7）
--------------------------
W141 原分配的块名 `单车电耗现列` **不可用**：`tokenize('单车电耗现列')` 切成
`单车电耗现`(IDENT) + `列`(VERB，列表构造动词)，导入语句
`从 blocks.制造.单车电耗现列 导入 车耗现。` 直接 ParseError。与 WBS 执行原则 7
记录的 `择列`/`列排` 死名同源，区别是这次踩在**块目录名**上——块名也会出现在导入
路径里，同样必须词法原子。改用 `单车电耗现成`（实测单 IDENT）。导出名 `车耗现`
一字未动。

口径（写死，也全写进 `块.json` 的 `描述`）
--------------------------------------
度量列 = `fact_energy_usage.energy_per_vehicle`，**数据集里已经算好的现成比率列**
（kWh/台）。本块不重算、不读产量表、不做任何跨表关联。ADR-40 §5.2 决议：这就是
默认口径（数据字典即如此定义）。

只做算术平均，不做求和
--------------------
`energy_per_vehicle` 是比率列。跨行求和得到的数没有业务含义——把两条记录的
「每台多少度」加起来不等于任何东西。ADR-40 §5 点名的「现成比率列直接汇总会算出
错数」就是指这个。所以本块**只提供算术平均**，并且明说平均是**记录等权**：每条
日×车间×产线×车型×班次 记录权重相同，与产量多少无关。

另一侧口径：`制造.单车电耗重算`（导出 `车耗算`）
--------------------------------------------
那个块按 `line_id + model_id + 日期 + shift` 关联 `fact_production_actual`，
用 `sum(electricity_kwh) / sum(actual_quantity)` 重算，分母是真实产量（产量加权）。
两块会在 `jk 块 选` 的候选里并排出现，**选块的人必须自己拍一个**。

2026-08-18 实测：两个口径在本数据集上**数值等值**——2896/2896 行逐行核对，
`energy_per_vehicle` 恒等于 `electricity_kwh` / 同键 `actual_quantity`，最大绝对差
0.005（现成列两位小数舍入所致）、最大相对差 5.4e-5，零漏配。等值的原因是数据
生成时两边口径一致（ADR-40 §5.2 已结账），**不是** 重算块写错了。换一份真实工厂
数据这两个数就会分叉，届时 `车耗算` 已经在。

空值口径
-------
`energy_per_vehicle` 为空的记录不进均值分母：`单车电耗均值` 的分母是 `非空记录数`
而不是 `记录数`，两个量都输出、不许互相顶替（拿 `记录数` 当分母会把均值算低）。
整组皆空时 `单车电耗均值` 返回 None（极快 `空`）而不是 0——「没有数据」与「每台
零度电」不是一回事。

行序：按维度键升序（含空值键排最前），完全确定可复现。

零第三方依赖，只用 Python 标准语法。
"""

单车电耗列 = 'energy_per_vehicle'
固定列 = ('记录数', '非空记录数', '单车电耗均值')


def _排序键(组键):
    """含空值 / 混合类型的维度键 → 可确定排序的元组（分档保证全序）。"""
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def _校验表(表):
    if not isinstance(表, list):
        raise ValueError('单车电耗现成：能耗表必须是「行的列表」'
                         '（列表<字典<字符串,任意>>），得到 %s' % type(表).__name__)
    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('单车电耗现成：能耗表第 %d 行不是字典，得到 %s'
                             % (序, type(行).__name__))
    return 表


def _校验维度列(维度列):
    if not isinstance(维度列, list):
        raise ValueError('单车电耗现成：维度列必须是列名的列表（列表<字符串>），得到 %s'
                         % type(维度列).__name__)
    if not 维度列:
        raise ValueError('单车电耗现成：维度列不能为空——至少要一个维度列'
                         '（如 【"line_id"】）')
    for 名 in 维度列:
        if not isinstance(名, str):
            raise ValueError('单车电耗现成：维度列的每一项必须是列名字符串，得到 %r' % (名,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('单车电耗现成：维度列有重复项 %r' % (维度列,))
    撞名 = [名 for 名 in 维度列 if 名 in 固定列]
    if 撞名:
        raise ValueError('单车电耗现成：维度列 %s 与固定输出列（%s）撞名，会静默覆盖'
                         '结果；请先用 制造/投影 改名' % (撞名, '/'.join(固定列)))
    return list(维度列)


def _校验列存在(表, 列清单, 角色):
    for 名 in 列清单:
        for 序, 行 in enumerate(表, start=1):
            if 名 not in 行:
                raise ValueError(
                    '单车电耗现成：%s「%s」在能耗表第 %d 行不存在（该行的列：%s）；'
                    '不静默返回空表，也**不会**改口径去关联产量表重算'
                    '（那是 制造/单车电耗重算 的活），请核对列名'
                    % (角色, 名, 序, sorted(行.keys())))


def 车耗现(能耗表, 维度列):
    """按维度列对现成列 `energy_per_vehicle` 取算术平均（记录等权）。

    入参
    ----
    能耗表 : 列表<字典<字符串,任意>>  —— `fact_energy_usage` 形状的表。
    维度列 : 列表<字符串>             —— 分组维度，如 【"line_id"】、【"workshop", "shift"】。

    出参
    ----
    列表<字典<字符串,任意>>：每组一行，键为各维度列名 + `记录数` + `非空记录数`
    + `单车电耗均值`。均值分母是 `非空记录数`；整组皆空则均值为 None。
    按维度键升序。空表输入返回空表。

    口径见模块 docstring 与 `块.json` 的 `描述`。另一侧口径在 `制造.单车电耗重算`
    （导出 `车耗算`）。
    """
    _校验表(能耗表)
    维度 = _校验维度列(维度列)

    if not 能耗表:
        return []

    _校验列存在(能耗表, 维度, '维度列')
    _校验列存在(能耗表, [单车电耗列], '度量列')

    桶表 = {}
    for 行号, 行 in enumerate(能耗表, start=1):
        组键 = tuple(行[名] for 名 in 维度)
        桶 = 桶表.get(组键)
        if 桶 is None:
            桶 = {'记录数': 0, '非空记录数': 0, '合计': 0.0}
            桶表[组键] = 桶
        桶['记录数'] += 1
        值 = 行[单车电耗列]
        if 值 is None:
            # 空值只计入 记录数，不进均值分母。整组皆空时下面会给 None。
            continue
        if isinstance(值, bool) or not isinstance(值, (int, float)):
            raise ValueError(
                '单车电耗现成：能耗表第 %d 行的 %s 是 %r（类型 %s），不是数值，'
                '无法求平均' % (行号, 单车电耗列, 值, type(值).__name__))
        桶['非空记录数'] += 1
        桶['合计'] += 值

    结果 = []
    for 组键 in sorted(桶表, key=_排序键):
        桶 = 桶表[组键]
        行 = {}
        for 位, 名 in enumerate(维度):
            行[名] = 组键[位]
        行['记录数'] = 桶['记录数']
        行['非空记录数'] = 桶['非空记录数']
        # 分母是 非空记录数，不是 记录数；全空组返回 None 而不是 0。
        行['单车电耗均值'] = (None if 桶['非空记录数'] == 0
                            else 桶['合计'] / 桶['非空记录数'])
        结果.append(行)
    return 结果
