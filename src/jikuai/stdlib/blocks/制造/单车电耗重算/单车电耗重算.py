# -*- coding: utf-8 -*-
"""制造.单车电耗重算 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块 · ADR-40 §5.2 分歧点 2 的「重算」这一侧。**

口径（写死，也全写进 `块.json` 的 `描述`）
--------------------------------------
    单车电耗 = sum(electricity_kwh) / sum(actual_quantity)

- 分子 `electricity_kwh` 来自 `fact_energy_usage`。
- **分母 `actual_quantity` 来自 `fact_production_actual`** —— 能耗表里根本没有产量
  列，现成的 `energy_per_vehicle` 是数据生成时算好的，其分母就取自产量表
  （ADR-40 §5.2）。这是本块最要紧的一句口径声明：**分母来源在另一张表**。
- 对齐方式：**四键**
  `line_id + model_id + 日期 + shift`。日期列两表名字不同（能耗 `usage_date`、
  产量 `production_date`），本块内部按位对齐，不要求两边同名。
- 聚合次序：先按 `维度列` 把分子分母各自求和，**再相除**（产量加权口径），不是
  「先算每行比率再平均」。

另一侧口径：`制造.单车电耗现成`（导出 `车耗现`）
--------------------------------------------
直接取现成列 `energy_per_vehicle` 求**记录等权**的算术平均，不碰产量表。两块会在
`jk 块 选` 的候选里并排出现，**选块的人必须自己拍一个**。

本块的价值（W141 DoD 要求写清）
-----------------------------
2026-08-18 实测：两个口径在本数据集上**数值等值**——2896/2896 行逐行核对，
最大绝对差 0.005（现成列两位小数舍入所致）、最大相对差 5.4e-5、零漏配。
所以本块**不是**用来在本数据集上算出不同的数，它的价值是两条：

(a) **换一份真实工厂数据、两个口径会分叉时，重算块已经在**，不必临时补一个块，
    也不必让人在报表出问题的当天才发现「原来那一列是别人算好的」；
(b) **交叉校验现成列**——本轮正是靠这个块证明了 `energy_per_vehicle` 恒等于
    `electricity_kwh / actual_quantity`，把 ADR-40 §5.2 的「现成列口径为何」
    从推理变成实测。

等值的原因是数据生成时口径一致（ADR-40 §5.2 已结账），**不是**本块写错了。

分母为 0 / 分母键缺失：显式决议，不静默当 0（与 `制造.缺陷率` 同口径）
------------------------------------------------------------------
每个输出组给出 `对齐记录数` / `漏配记录数` / `电耗合计` / `漏配电耗` /
`产量合计` / `单车电耗`：

- **分母为 0**（该组四键都对上了，但 `sum(actual_quantity)` = 0，例如停产还在耗电）：
  `单车电耗` = None，`产量合计` 如实给 0。除以 0 没有意义，但分子分母都摆出来。
- **分母键缺失**（某条能耗记录的四键在产量表里一条都对不上）：那条记录**不进分子
  也不进分母**（否则分子多算、分母没跟上，会把单车电耗算高），但它的条数与电量
  分别计入 `漏配记录数` 与 `漏配电耗`——**一度电都不会静默消失**。整组全漏配时
  `电耗合计` / `产量合计` / `单车电耗` 三项皆为 None。
- 两条都不报错、不静默丢弃：报错会让一整张报表因为一个边缘组全废；静默丢弃会让
  电量不守恒，那种错最难查。

单元格空值 → 报错
----------------
`electricity_kwh` 或 `actual_quantity` 出现空值直接抛错。「单元格缺值」与「整组
缺失 / 为 0」是不同层次的问题，必须分开处理，不许混为一谈。

行序：按维度键升序（空值键最前），完全确定可复现。

零第三方依赖，只用 Python 标准语法。
"""

#: 分子列（能耗表）与分母列（产量表）。改它们等于改口径。
分子列 = 'electricity_kwh'
分母列 = 'actual_quantity'

#: 四键在两张表里的列名。ADR-40 §4.2 冻结的真实列名，日期列刻意不同名。
能耗键 = ('usage_date', 'line_id', 'model_id', 'shift')
产量键 = ('production_date', 'line_id', 'model_id', 'shift')

固定列 = ('对齐记录数', '漏配记录数', '电耗合计', '漏配电耗', '产量合计', '单车电耗')


def _排序键(组键):
    """含空值 / 混合类型的维度键 → 可确定排序的元组（分档保证全序）。"""
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def _校验表(表, 表名):
    if not isinstance(表, list):
        raise ValueError('单车电耗重算：%s 必须是「行的列表」'
                         '（列表<字典<字符串,任意>>），得到 %s'
                         % (表名, type(表).__name__))
    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('单车电耗重算：%s 第 %d 行不是字典，得到 %s'
                             % (表名, 序, type(行).__name__))
    return 表


def _校验维度列(维度列):
    if not isinstance(维度列, list):
        raise ValueError('单车电耗重算：维度列必须是列名的列表（列表<字符串>），得到 %s'
                         % type(维度列).__name__)
    if not 维度列:
        raise ValueError('单车电耗重算：维度列不能为空——至少要一个维度列（如 【"line_id"】）')
    for 名 in 维度列:
        if not isinstance(名, str):
            raise ValueError('单车电耗重算：维度列的每一项必须是列名字符串，得到 %r' % (名,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('单车电耗重算：维度列有重复项 %r' % (维度列,))
    撞名 = [名 for 名 in 维度列 if 名 in 固定列]
    if 撞名:
        raise ValueError('单车电耗重算：维度列 %s 与固定输出列（%s）撞名，会静默覆盖'
                         '结果；请先用 制造/投影 改名' % (撞名, '/'.join(固定列)))
    return list(维度列)


def _校验列存在(表, 列清单, 表名):
    for 名 in 列清单:
        for 序, 行 in enumerate(表, start=1):
            if 名 not in 行:
                raise ValueError(
                    '单车电耗重算：列「%s」在%s第 %d 行不存在（该行的列：%s）；'
                    '不静默返回空表，请核对列名' % (名, 表名, 序, sorted(行.keys())))


def _数值(值, 列名, 表名, 行号):
    if 值 is None:
        raise ValueError(
            '单车电耗重算：%s第 %d 行的 %s 是空值。单元格缺值与「整组缺失 / 分母为 0」'
            '是不同层次的问题，本块不静默跳过也不当 0；请先修数据或用 制造/选取 '
            '把空值行筛掉（筛掉多少条要自己报出来）' % (表名, 行号, 列名))
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError('单车电耗重算：%s第 %d 行的 %s 是 %r（类型 %s），不是数值'
                         % (表名, 行号, 列名, 值, type(值).__name__))
    return 值


def 车耗算(能耗表, 产量表, 维度列):
    """按四键关联产量表重算单车电耗（产量加权），再按维度列汇总。

    入参
    ----
    能耗表 : 列表<字典<字符串,任意>>  —— `fact_energy_usage` 形状，供分子
        `electricity_kwh` 与四键 usage_date/line_id/model_id/shift。
    产量表 : 列表<字典<字符串,任意>>  —— `fact_production_actual` 形状，供**分母**
        `actual_quantity` 与四键 production_date/line_id/model_id/shift。
    维度列 : 列表<字符串>             —— 输出分组维度，必须是**能耗表**的列
        （如 【"line_id"】、【"workshop"】）。

    出参
    ----
    列表<字典<字符串,任意>>：每组一行，键为各维度列名 + `对齐记录数` +
    `漏配记录数` + `电耗合计` + `漏配电耗` + `产量合计` + `单车电耗`。
    分母为 0 或整组漏配时 `单车电耗` 为 None（见模块 docstring 的显式决议）。
    按维度键升序。能耗表为空返回空表。

    另一侧口径在 `制造.单车电耗现成`（导出 `车耗现`）。
    """
    _校验表(能耗表, '能耗表')
    _校验表(产量表, '产量表')
    维度 = _校验维度列(维度列)

    if not 能耗表:
        return []

    _校验列存在(能耗表, list(维度) + list(能耗键) + [分子列], '能耗表')
    if 产量表:
        _校验列存在(产量表, list(产量键) + [分母列], '产量表')

    # 产量表按四键建索引。同一四键可能有多行（本数据集实测唯一，但不假设），
    # 全部相加——这是「同键产量之和」，与 ADR-40 §5.2 的关联口径一致。
    产量桶 = {}
    for 行号, 行 in enumerate(产量表, start=1):
        键 = tuple(行[名] for 名 in 产量键)
        产量桶[键] = 产量桶.get(键, 0) + _数值(行[分母列], 分母列, '产量表', 行号)

    桶表 = {}
    for 行号, 行 in enumerate(能耗表, start=1):
        组键 = tuple(行[名] for 名 in 维度)
        桶 = 桶表.get(组键)
        if 桶 is None:
            桶 = {'对齐记录数': 0, '漏配记录数': 0,
                  '电耗合计': 0.0, '漏配电耗': 0.0, '产量合计': 0}
            桶表[组键] = 桶
        电量 = _数值(行[分子列], 分子列, '能耗表', 行号)
        四键 = tuple(行[名] for 名 in 能耗键)
        if 四键 in 产量桶:
            # 分子与分母来自同一组已对齐的记录，两边同进同出。
            桶['对齐记录数'] += 1
            桶['电耗合计'] += 电量
            桶['产量合计'] += 产量桶[四键]
        else:
            # 分母键缺失：这条记录不进分子也不进分母（否则会把单车电耗算高），
            # 但条数与电量都要报出来——一度电都不许静默消失。
            桶['漏配记录数'] += 1
            桶['漏配电耗'] += 电量

    结果 = []
    for 组键 in sorted(桶表, key=_排序键):
        桶 = 桶表[组键]
        行 = {}
        for 位, 名 in enumerate(维度):
            行[名] = 组键[位]
        行['对齐记录数'] = 桶['对齐记录数']
        行['漏配记录数'] = 桶['漏配记录数']
        if 桶['对齐记录数'] == 0:
            # 整组全漏配：没有任何可用的分子分母对，三项都给 空 而不是 0。
            行['电耗合计'] = None
            行['产量合计'] = None
            行['单车电耗'] = None
        else:
            行['电耗合计'] = 桶['电耗合计']
            行['产量合计'] = 桶['产量合计']
            # 分母为 0（停产还在耗电）→ 空；产量合计仍如实给 0。
            行['单车电耗'] = (None if 桶['产量合计'] == 0
                            else 桶['电耗合计'] / 桶['产量合计'])
        行['漏配电耗'] = 桶['漏配电耗']
        结果.append(行)
    return 结果
