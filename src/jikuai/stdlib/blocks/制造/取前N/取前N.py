# -*- coding: utf-8 -*-
"""制造.取前N 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**这是引擎层关系算子，不含任何业务口径**（ADR-40 §3.1）。它只截取前 N 行：
不排序、不过滤、不汇总、不加权、不做时间窗口对齐、不碰任何现成比率列、
不改任何数值。口径判断全部留给口径层（产量 / 达成率 / 缺陷率是 W140-W142 的事）。

**本块不排序，这一点最容易被误会。** 「延期最多的前 3 单」= 先 `制造.排序`
按延期天数降序，再 `制造.取前N` 取 3 行；单独调本块拿到的是**原表前 3 行**，
和「最多」没有关系。把排序偷偷做进来会更「好用」，但那样调用方就看不见排序口径
（按哪列、升还是降、空值怎么排），溯源说明也写不出来——所以刻意不做。

为什么下沉到 Python 背衬（而不是纯 `.jk`）：极快没有列表切片动词
（`子串` 只吃字符串，`其余` 只去掉一个头），纯 `.jk` 得写 `遍历` + 计数器 +
`追加` 逐行搬，每次 `追加` 复制一遍整个列表（`a + [b]`），2896 行就是
O(行数²) 的复制。Python 一个切片就完事。

═══════════════════════════════════════════════════════════════════════
三条刻意做出的语义决定（全部写进了 `块.json` 的 `描述`，调用方看得见）
═══════════════════════════════════════════════════════════════════════

**一、N 大于行数 → 返回全部，不报错。** 「取前 10 名」在只有 8 行时给 8 行是
自然的，报错反而逼调用方先去数行数。这与 SQL `LIMIT` 一致。

**二、N = 0 → 返回空表，不报错。** 0 行是一个合法的、有意义的请求（例如上层
按分页参数算出本页取 0 条）。

**三、N < 0 → 报错。** 负数没有「取前负三行」的语义，几乎肯定是上层算错了
（常见来源：`总数 - 已取` 算成了负数）。这里若照 Python 切片的语义走
（`表[:-3]` = 去掉末尾三行），就会**静默返回一个行数不对的表**——跑得通、
数是错的，正是最该防的那类故障。所以报错。

N 也必须是整数：`摘前(表, 2.5)` 意思不明（2 行还是 3 行？），不猜，直接报错。

零第三方依赖，只用 Python 标准语法。
"""


def _类型档(值):
    """把值归到一个粗类型档，只用于报错文案（与 `制造.连接` 同口径）。"""
    if 值 is None:
        return '空'
    if isinstance(值, bool):
        return '布尔'
    if isinstance(值, (int, float)):
        return '数'
    if isinstance(值, str):
        return '字符串'
    return '其它(%s)' % type(值).__name__


def _校验表(表):
    """表必须是「行的列表」：列表<字典<字符串,任意>>。"""
    if not isinstance(表, list):
        raise ValueError(
            '取前N：表必须是「行的列表」（列表<字典<字符串,任意>>），'
            '实际收到 %s' % _类型档(表))
    for 序, 行 in enumerate(表):
        if not isinstance(行, dict):
            raise ValueError(
                '取前N：表第 %d 行不是「列名→值」的字典，实际是 %s'
                % (序 + 1, _类型档(行)))
        for 名 in 行:
            if not isinstance(名, str):
                raise ValueError(
                    '取前N：表第 %d 行有非字符串列名（%r），表的列名必须是字符串'
                    % (序 + 1, 名))
    return 表


def _校验行数(行数):
    """N 必须是非负整数。"""
    # bool 是 int 的子类，`摘前(表, 真)` 会被 Python 当成 1——那是笔误不是意图。
    if isinstance(行数, bool) or not isinstance(行数, int):
        raise ValueError(
            '取前N：行数必须是整数，实际收到 %s（%r）。'
            '小数没有「取前 2.5 行」的语义，本块不替调用方猜是 2 还是 3'
            % (_类型档(行数), 行数))
    if 行数 < 0:
        raise ValueError(
            '取前N：行数不能是负数（收到 %d）。负数没有「取前负几行」的语义，'
            '通常是上层算错了（例如「总数 - 已取」算成了负数）。'
            '本块刻意不照 Python 切片那样把负数当「去掉末尾几行」——'
            '那会静默返回一个行数不对的表，跑得通、数是错的' % 行数)
    return 行数


def 摘前(表, 行数):
    """取表的前 N 行，返回新表。**本块不排序**。

    参数
    ----
    表     : 行的列表（列表<字典<字符串,任意>>）
    行数   : 取几行；非负整数。大于总行数时返回全部，等于 0 时返回空表，
             负数报错

    返回
    ----
    行的列表，长度 = min(行数, 总行数)，行序与原表一致。行是原行对象本身
    （内容不改），输入表不被改动。

    注意：想要「最大的前 N 行」必须先用 `制造.排序`（导出名 `定序`）排好再调本块。
    本块只截取，不排序。
    """
    行表 = _校验表(表)
    条数 = _校验行数(行数)
    # 切片天然处理 条数 > len(行表) 与 条数 == 0 两种情形，且返回的是新列表。
    return 行表[:条数]
