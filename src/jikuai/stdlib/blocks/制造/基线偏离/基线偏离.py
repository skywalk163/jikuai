# -*- coding: utf-8 -*-
"""制造.基线偏离 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块**（ADR-40 §3.2）：观察窗相对**自身基线窗**的升幅。v0.27.0 W155。
这是 `Q_PUB_004`（「哪条产线单车电耗异常升高」）的正确答案形状。

姊妹块：`制造.窗间对比`（导出 `窗比`）
------------------------------------
ADR-40 §5.4 分歧点的两侧，**互相点名**（G22 断言 3 的双块判法）：

- **本块 `基线偏离`（`基偏`）**：**相对自身基线，不是横向比较**。基线窗代表「这条
  产线平时什么水平」，观察窗代表「这一段时间什么水平」，输出是**升幅**。口径
  不对称：调换两个入表会得到不同的结论（不是简单变符号，因为分母换了）。
- **`窗间对比`（`窗比`）**：两个**平级**窗口相比，谁当基期由调用方指定，口径对称，
  主输出是**绝对量差值**。「六月比五月多产了多少台」用它。

═══════════════════════════════════════════════════════════════════════
坑：**绝对量榜与比率榜的结论不同，这不是 bug**
═══════════════════════════════════════════════════════════════════════

这是 BACKLOG §12.3 第 5 条点名的坑，本块用一条实测断言把它钉死（见
`tests/test_v0_27_0_w155_基线偏离.py` 与 `测试.jk`）：

`fact_energy_usage` 上，观察窗 `2026-06-10..06-24`、基线 = 该窗之前的全部日期，
按 `line_id` 对现成列 `energy_per_vehicle` 取算术平均：

- **升幅榜（本块）**：L002 `151.8007 → 191.0953` = **+25.89%**，遥遥领先；
  其余七条产线全在 **−3.79% ~ +3.15%** 区间（本底噪声）。**答案是 L002。**
- **横向绝对量榜**（观察窗单车电耗降序，不用本块、直接排 `车耗现` 的输出）：
  L006 `256.5050` 第一、L005 `247.8620` 第二、L007 `205.0937` 第三，
  **L002 `191.0953` 只排第 4**。

两个榜结论不同，各自都对：L006 平时就是耗电大户（重型车型 / 工艺不同），它没有
「升高」；L002 平时 151、这一段 191，**它才是异常升高的那条**。问「哪条产线电耗
最高」用横向榜，问「哪条产线异常升高」用本块。**后人若发现两个榜不一致而去
「修正」其中一个，那是把正确答案改错**——所以两个榜的名次都写进了断言。

═══════════════════════════════════════════════════════════════════════
决议：本块**不汇总**，也**不替调用方选基线窗**
═══════════════════════════════════════════════════════════════════════

1. **不汇总**：两个入表必须已经一行一组（同 `窗间对比`）。求和 / 算术平均 /
   产量加权是三个不同的答案，替调用方拍一个正是 ADR-40 §5 三处分歧点的病根。
   重复键当场报错，文案点名该用哪个汇总块。
2. **不替调用方选基线窗**。「基线」是业务判断：上面那组数用的是「观察窗之前的
   全部日期」，换成「前 15 天」L002 是 +27.13%、换成「同月观察窗前」是 +26.78%
   ——**三种基线都给出同一个结论（L002 异常），但数值不同**。本块只负责算，
   基线窗怎么切由调用方用 `制造.窗口`（`截期`）决定并自己写进报告里。
   开成参数会让人以为有个「标准基线」，那是本块给不出的承诺。

空值口径：空 ≠ 0，三种状况分得开
--------------------------------
1. **维度键只在一窗出现**（新投产 / 停产的产线）→ `对齐` 是 `缺基线` / `缺观察`，
   缺的那侧值为 `空`，`偏离` 与 `升幅` 都是 `空`。**不把缺的那侧当 0** ——
   当 0 会算出「从 0 升到 191，升幅无穷」这种纯人造的异常，而它会稳稳占据榜首。
2. **两窗都有该键、但某侧汇总值本身为 `空`**（整组记录的度量列全为空值，如
   `车耗现` 对全空组返回的 `单车电耗均值=空`）→ `对齐` 是 `两窗齐`、值为 `空`。
   靠 `对齐` 字段与第 1 种区分（`班间对比` 的同一条教训）。
3. **基线值是真的 0** → `偏离` 照算，`升幅` 返回 `空` **而不是 `inf`**。
   基线值为负时 `升幅` 同样为 `空`（负分母下比率符号会翻，把恶化读成好转），
   而绝对量的 `偏离` 仍然照算仍然可信。

输出契约
--------
`基偏(观察表, 基线表, 维度列, 度量列)` → 列表<字典<字符串,任意>>，每组一行：

  <各维度列名>  —— 原样回填维度键
  对齐          —— `两窗齐` / `缺基线` / `缺观察`
  基线值        —— 基线窗该组的 `度量列` 值（可能是 `空`）
  观察值        —— 观察窗该组的 `度量列` 值（可能是 `空`）
  偏离          —— `观察值 - 基线值`（绝对量）；任一侧为 `空` 时为 `空`
  升幅          —— `偏离 / 基线值`，**0-1 小数**（`0.2589` 表示升 25.89%）；
                   基线值为 `空` / 0 / 负数时为 `空`

**`升幅` 的单位是 0-1 小数，不是百分数。** 与数据集的 `achievement_rate`、
`defect_rate` 等比率列一致（那两列也是 0-1 小数而非百分数，`Q_PUB_005` 已踩过），
也与姊妹块 `窗间对比` 的 `变化率` 一致。要百分数自己乘 100。
（WBS W155 的行文写的是「升幅 %」，那是指标的口语说法；单位这里统一取 0-1 小数，
偏离点已在交付报告里记档。）

行序按维度键升序（空值键排最前），两窗键的**并集**都出现，确定可复现。
**本块不排序、不取前 N** —— 要「升幅最大的那条」请接 `制造.排序` + `制造.取前N`。

零第三方依赖，只用 Python 标准语法。
"""

#: 固定输出列。维度列与它们撞名会静默覆盖结果，故校验时当场报错。
固定列 = ('对齐', '基线值', '观察值', '偏离', '升幅')

#: `对齐` 的三种取值。**不是布尔**：压成布尔就把「缺哪一侧」丢了。
对齐_齐 = '两窗齐'
对齐_缺基线 = '缺基线'
对齐_缺观察 = '缺观察'


def _排序键(组键):
    """含空值 / 混合类型的维度键 → 可确定排序的元组（分档保证全序）。

    与 `制造.窗间对比._排序键`、`制造.单车电耗现成._排序键` 同法。
    """
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def _校验维度列(维度列):
    if not isinstance(维度列, list):
        raise ValueError('基线偏离：维度列必须是列名的列表（列表<字符串>），得到 %s'
                         % type(维度列).__name__)
    if not 维度列:
        raise ValueError('基线偏离：维度列不能为空——至少要一个维度列（如 【"line_id"】）；'
                         '不分维度的「全厂一个升幅」请直接比两个标量')
    for 名 in 维度列:
        if not isinstance(名, str) or not 名:
            raise ValueError('基线偏离：维度列的每一项必须是非空列名字符串，得到 %r' % (名,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('基线偏离：维度列有重复项 %r' % (维度列,))
    撞名 = [名 for 名 in 维度列 if 名 in 固定列]
    if 撞名:
        raise ValueError('基线偏离：维度列 %s 与固定输出列（%s）撞名，会静默覆盖结果；'
                         '请先用 制造/投影 改名' % (撞名, '/'.join(固定列)))
    return list(维度列)


def _校验度量列(度量列, 维度):
    if not isinstance(度量列, str) or not 度量列:
        raise ValueError('基线偏离：度量列必须是单个非空列名字符串，得到 %r' % (度量列,))
    if 度量列 in 维度:
        raise ValueError('基线偏离：度量列「%s」同时也是维度列——它是分组键，'
                         '不是可对比的度量' % 度量列)
    if 度量列 in 固定列:
        raise ValueError('基线偏离：度量列「%s」与固定输出列（%s）撞名，'
                         '请先用 制造/投影 改名' % (度量列, '/'.join(固定列)))


def _数值或空(值, 侧, 度量列, 序):
    """度量列的值只接受数值或 `空`。布尔显式排除（同 `制造.分组汇总._数值`）。"""
    if 值 is None:
        return None
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError(
            '基线偏离：%s第 %d 行的度量列「%s」是非空的非数值 %r（类型 %s），'
            '无法算升幅；度量列只接受数值或 空'
            % (侧, 序, 度量列, 值, type(值).__name__))
    return 值


def _收一侧(表, 侧, 维度, 度量列):
    """一侧的表 → {维度键: 度量值}。重复键 / 缺列 / 非数值都当场报错。"""
    if not isinstance(表, list):
        raise ValueError('基线偏离：%s必须是「行的列表」（列表<字典<字符串,任意>>），'
                         '得到 %s' % (侧, type(表).__name__))
    出 = {}
    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('基线偏离：%s第 %d 行不是字典（表必须是行的列表，'
                             '每行是列名→值的字典），得到 %s'
                             % (侧, 序, type(行).__name__))
        for 名 in 维度:
            if 名 not in 行:
                raise ValueError(
                    '基线偏离：维度列「%s」在%s第 %d 行不存在（该行的列：%s）。'
                    '两窗的列名必须一致——本块按列名对齐，列名不同就对不上，'
                    '不静默当作缺键。列名确实不同请先用 制造/投影 改名'
                    % (名, 侧, 序, sorted(行.keys())))
        if 度量列 not in 行:
            raise ValueError(
                '基线偏离：度量列「%s」在%s第 %d 行不存在（该行的列：%s）；'
                '不静默按空值处理。两个入表都得是**已汇总**的表，度量列名通常是'
                '上游汇总块的输出列名（如 分组汇总 的 均值 / 求和、'
                '单车电耗现成 的 单车电耗均值）'
                % (度量列, 侧, 序, sorted(行.keys())))
        键 = tuple(行[名] for 名 in 维度)
        if 键 in 出:
            raise ValueError(
                '基线偏离：%s里维度键 %r 出现了不止一行。本块**不汇总**——它要求'
                '两个入表已经一行一组。请先用 制造/分组汇总（维聚）或对应的口径'
                '汇总块（产量汇总 / 能耗汇总 / 缺陷汇总 / 单车电耗现成 / '
                '单车电耗重算）把表汇总到一行一组，再丢进来。本块刻意不替你选'
                '汇总口径（求和 / 算术平均 / 产量加权是三个不同的答案，'
                'ADR-40 §5 的分歧点就是这么来的）'
                % (侧, 键))
        出[键] = _数值或空(行[度量列], 侧, 度量列, 序)
    return 出


def 基偏(观察表, 基线表, 维度列, 度量列):
    """观察窗相对自身基线窗的升幅，逐维度键一行。

    入参
    ----
    观察表 : 列表<字典<字符串,任意>>  —— 观察窗，**已汇总到一行一组**
    基线表 : 列表<字典<字符串,任意>>  —— 基线窗（代表「平时什么水平」），同上
    维度列 : 列表<字符串>             —— 对齐用的维度，如 【"line_id"】
    度量列 : 字符串                   —— 要比的列名（通常是上游汇总块的输出列名）

    出参
    ----
    列表<字典<字符串,任意>>，每组一行，键为各维度列名 + `对齐` + `基线值` +
    `观察值` + `偏离` + `升幅`。`升幅` 是 **0-1 小数**。两窗键的并集都出现；
    按维度键升序。两个入表都空时返回空表。

    **口径不对称**：调换 `观察表` 与 `基线表` 不是简单变符号（分母换了），
    会得到另一个数。**相对自身基线，不是横向比较** ——「哪条产线电耗最高」是
    横向问题，直接排观察窗的值即可，不该用本块。要两个平级窗口的绝对量差值
    用姊妹块 `制造.窗间对比`（导出 `窗比`）。

    报错
    ----
    - 某侧维度键重复（说明没汇总）→ 报错并点名该用哪个汇总块
    - 维度列 / 度量列在某行缺失（含两表列名不一致）→ 报错
    - 度量列是非空的非数值 → 报错
    """
    维度 = _校验维度列(维度列)
    _校验度量列(度量列, 维度)

    观 = _收一侧(观察表, '观察表', 维度, 度量列)
    基 = _收一侧(基线表, '基线表', 维度, 度量列)

    结果 = []
    for 键 in sorted(set(观) | set(基), key=_排序键):
        在观 = 键 in 观
        在基 = 键 in 基
        观值 = 观.get(键)
        基值 = 基.get(键)

        if 在观 and 在基:
            对齐 = 对齐_齐
        elif 在观:
            对齐 = 对齐_缺基线
        else:
            对齐 = 对齐_缺观察

        # 空 ≠ 0：缺一侧、或某侧汇总值本身为空，偏离都是 空，不把缺的那侧当 0。
        偏离 = None if (观值 is None or 基值 is None) else 观值 - 基值

        if 偏离 is None or 基值 is None or 基值 <= 0:
            # 基线为 0 → 空 而不是 inf（inf 会稳占升幅榜首，是纯人造的异常）；
            # 基线为负 → 空，因为比率符号会翻，把恶化读成好转。
            升幅 = None
        else:
            升幅 = 偏离 / 基值

        行 = {}
        for 位, 名 in enumerate(维度):
            行[名] = 键[位]
        行['对齐'] = 对齐
        行['基线值'] = 基值
        行['观察值'] = 观值
        行['偏离'] = 偏离
        行['升幅'] = 升幅
        结果.append(行)
    return 结果
