# -*- coding: utf-8 -*-
"""制造.延期排行 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块**（ADR-40 §3.2）：按 `fact_orders.delay_days` **降序**取前 N 单，
并把被排除的空值行数一起返回。列名写死在本模块里，不由调用方传。

与 `制造.排序`+`制造.取前N` 的差别（为什么不是「已有块拼一下」）
--------------------------------------------------------------------
引擎层那两个块拼起来能排出前 N 行，但**拼不出这一条关键信息：有多少行因为
`delay_days` 为空而根本没进榜**。`制造.排序` 的空值口径是「排末尾」——57 张
未交付订单会静默沉到表尾，取前 10 时看不见它们，于是调用方得到一张
「看起来完整」的榜，却不知道样本里有 57 单还没交付、压根没有延期天数可比。

ADR-40 §4.3：`delay_days` 的 空 = 未交付（57 行），而**同一列另有 977 行是 0**
（按期交付）。排行榜口径下这两者的差别更隐蔽——0 排在榜尾无害，空排在榜尾却
是「不可比」被当成了「最不延期」。所以本块：
  1. **先把空值行剔掉**（不是排到末尾），
  2. 把剔掉的条数与实际参与排序的行数一起返回。

排序口径（全部写死，不给开关）
--------------------------------
- 主键：`delay_days` **降序**（延期最多的在前）。
- 次键：**原表行序**（稳定排序）。同天数的订单谁在前由输入表的行序决定，
  同一份输入两次调用结果完全一致。刻意**不**用 `order_id` 当次键——那会让本块
  依赖一个它本不该认识的列（`fact_orders` 之外的表没有 `order_id`）。
- 返回的是**原行对象本身**，列一个不裁、值一个不改（同 `制造.取前N`）。
  想只要几列请接 `制造.投影`。

N 的三条边界（与 `制造.取前N` 完全同口径，刻意保持一致）
--------------------------------------------------------
一、N 大于参与排序的行数 → 返回全部，不报错（同 SQL LIMIT）。
二、N = 0 → 返回空榜，不报错。
三、N < 0 → 报错。绝不照 Python 切片把负数当「去掉末尾几行」——那会静默返回
   一个行数不对的榜，跑得通、数是错的。N 也必须是整数，小数不猜。

输出契约
--------
`延榜(表, 前N)` → `(榜表, 排除的空值行数, 参与排序的行数)`

`榜表` 是原行的列表（长度 = min(前N, 参与排序的行数)）。

恒等式：`原表行数 = 排除的空值行数 + 参与排序的行数`。

零第三方依赖，只用 Python 标准语法。
"""

#: 本块认的延期天数列名。ADR-40 §4.2 冻结的 `fact_orders` 列名，不开成参数。
延期列 = 'delay_days'


def _类型档(值):
    """把值归到一个粗类型档，只用于报错文案（与 `制造.取前N` 同口径）。"""
    if 值 is None:
        return '空'
    if isinstance(值, bool):
        return '布尔'
    if isinstance(值, (int, float)):
        return '数'
    if isinstance(值, str):
        return '字符串'
    return '其它(%s)' % type(值).__name__


def _校验表(表):
    if not isinstance(表, list):
        raise ValueError(
            '延期排行：表必须是「行的列表」（列表<字典<字符串,任意>>），'
            '实际收到 %s' % _类型档(表))
    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError(
                '延期排行：表第 %d 行不是「列名→值」的字典，实际是 %s'
                % (序, _类型档(行)))
        if 延期列 not in 行:
            raise ValueError(
                '延期排行：延期天数列「%s」在表的第 %d 行不存在（该行的列：%s）；'
                '不静默返回空榜，请核对是不是传错了表'
                % (延期列, 序, sorted(行.keys())))
    return 表


def _校验前N(前N):
    """N 必须是非负整数。三条边界见模块 docstring。"""
    # bool 是 int 的子类，`延榜(表, 真)` 会被 Python 当成 1——那是笔误不是意图。
    if isinstance(前N, bool) or not isinstance(前N, int):
        raise ValueError(
            '延期排行：前N 必须是整数，实际收到 %s（%r）。'
            '小数没有「取前 2.5 单」的语义，本块不替调用方猜是 2 还是 3'
            % (_类型档(前N), 前N))
    if 前N < 0:
        raise ValueError(
            '延期排行：前N 不能是负数（收到 %d）。负数没有「取前负几单」的语义，'
            '通常是上层算错了。本块刻意不照 Python 切片把负数当「去掉末尾几行」'
            '——那会静默返回一个行数不对的榜，跑得通、数是错的' % 前N)
    return 前N


def _天数(值, 序):
    """延期天数的非空值必须是数值（布尔与字符串都报错，理由同 延期汇总）。"""
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError(
            '延期排行：第 %d 行的「%s」是非空的非数值 %r（类型 %s），无法排序。'
            '延期天数只接受数值或 空（空 = 未交付，本块会把它排除并计数）'
            % (序, 延期列, 值, type(值).__name__))
    return 值


def 延榜(表, 前N):
    """按 `delay_days` 降序取前 N 单，空值行排除且排除条数一起返回。

    参数
    ----
    表   : 行的列表（列表<字典<字符串,任意>>），每行必须有 `delay_days` 列
    前N  : 取几单；非负整数。大于参与排序行数时返回全部，0 返回空榜，负数报错

    返回
    ----
    `(榜表, 排除的空值行数, 参与排序的行数)`

    空表输入返回 `([], 0, 0)`。
    """
    _校验表(表)
    条数 = _校验前N(前N)

    # 先剔空值、同时记条数。**不是**把它们排到末尾——那会让「不可比」被读成
    # 「最不延期」，是本块要防的那类静默误读。
    参与 = []
    排除数 = 0
    for 序, 行 in enumerate(表, start=1):
        值 = 行[延期列]
        if 值 is None:
            排除数 += 1
            continue
        参与.append((_天数(值, 序), 行))

    # 稳定排序：主键 -延期天数（降序），次键隐含为原表行序。
    # Python 的 sorted 是稳定的，所以只给主键就够，不必显式带序号。
    参与.sort(key=lambda 对: -对[0])
    榜表 = [行 for _天, 行 in 参与[:条数]]
    return 榜表, 排除数, len(参与)
