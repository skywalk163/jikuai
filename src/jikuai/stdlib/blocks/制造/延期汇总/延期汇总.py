# -*- coding: utf-8 -*-
"""制造.延期汇总 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块**（ADR-40 §3.2），不是引擎层算子：它认得 `fact_orders.delay_days`
这一列，列名**写死在本模块里**，不由调用方传。理由见「为什么写死列名」一节。

═══════════════════════════════════════════════════════════════════════
本块存在的唯一理由：`delay_days` 这一列里「空」和「0」是两个业务含义
═══════════════════════════════════════════════════════════════════════

ADR-40 §4.3 + W139 实测（`tests/test_v0_26_0_w139_质量体检.py`）：

- `delay_days` 有 **57 行为空**（`order_status='生产中'`，订单还没交付，
  与 `actual_delivery_date` 为空的 57 行完全重合）；
- **同一列另有 977 行值为 `0`**（按期交付，延期零天）。

把那 57 行当 0 天延期会让分母凭空多 57 行、平均延期天数被稀释，**而运行期
一声不响**。实测差值：非空口径 2213/1793 = 1.234244 天，填 0 口径
2213/1850 = 1.196216 天。两个数都「像对的」，只有一个是对的。

所以本块的做法是：**空值行显式排除，并把排除条数当成返回值的一等公民报出来**
（元组第 2 项 + 每组的 `未交付单数` 列）。不是静默 `continue`——静默跳过的块
在调用方眼里与「填 0」无法区分，溯源说明也写不出「这个平均值的分母是谁」。

判交付看什么（本块不踩的坑）
--------------------------------
- ✅ `delay_days` 为空 / `actual_delivery_date` 为空 / `order_status='生产中'`
  ——三者在本数据集上完全等价；
- ❌ **不能看 `delivered_quantity == 0`**：那 57 张未交付订单的
  `delivered_quantity` 是**非零的部分交付值**（实测 4 ~ 66，最小 4），一行都不是 0。
  本块只读 `delay_days`，不碰 `delivered_quantity`，从结构上避开这个坑。

为什么写死列名
--------------
引擎层的 `制造.分组汇总`（导出 `维聚`）已经能「按维度列分组、对任意度量列聚合」，
本块若也把列名开成参数，就只是它的一个更啰嗦的重复。本块的价值恰恰在于**它知道
自己在数延期天数**，因此能：
  1. 把「空 = 未交付」这条业务口径写进描述与返回结构；
  2. 分出 `延期单数`（> 0）与 `按期单数`（== 0）——这个切分只在延期语义下成立，
     通用聚合算子给不出来。
要对别的列做通用聚合，用 `维聚`，别用本块。

输出契约
--------
`计延(表, 维度列)` → `(汇总表, 排除的空值行数, 计入统计的行数)`

`汇总表` 是「行的列表」，每组一行，键为：

  <各维度列名>       —— 该组的维度取值（`维度列` 传空列表时这些键不出现）
  订单数             —— 组内总行数，含未交付（SQL `COUNT(*)`）
  计入单数           —— `delay_days` 非空的行数（SQL `COUNT(delay_days)`），
                        **它就是 `延期天数均值` 的分母**
  未交付单数         —— `delay_days` 为空、被本块排除的行数
  延期单数           —— `delay_days > 0` 的行数
  按期单数           —— `delay_days == 0` 的行数（**不是**未交付）
  延期天数合计       —— 非空值求和；计入单数为 0 时返回 `空` 而非 0
  延期天数均值       —— 合计 / 计入单数；计入单数为 0 时返回 `空`
  最长延期天数       —— 非空值最大；计入单数为 0 时返回 `空`

三条恒等式（`测试.jk` 与 pytest 都钉了）：
  * `订单数 = 计入单数 + 未交付单数`（守恒，不丢行）
  * `计入单数 = 延期单数 + 按期单数`（0 与正数把非空行切完）
  * `sum(各组未交付单数) = 元组第 2 项`（排除条数与明细对得上）

行序：按维度键升序（空值键组排最前），与 `制造.分组汇总` 同口径，可复现。
要排名请接 `制造.排序` + `制造.取前N`，本块不替调用方决定排序口径。

零第三方依赖，只用 Python 标准语法。
"""

#: 本块认的延期天数列名。ADR-40 §4.2 冻结的 `fact_orders` 列名，不开成参数。
延期列 = 'delay_days'

#: 固定输出列名。与维度列撞车会静默覆盖聚合结果，构造前先挡下。
_固定列 = ('订单数', '计入单数', '未交付单数', '延期单数', '按期单数',
           '延期天数合计', '延期天数均值', '最长延期天数')


def _排序键(组键):
    """把可能含空值 / 混合类型的维度键映射成可确定排序的元组。

    与 `制造.分组汇总._排序键` 同一口径（分档：空 0 < 布尔 1 < 数 2 < 其余 3），
    两块的行序才对得上。Python 3 里 `None < "M001"` 直接 TypeError，而制造域的
    维度列确实会出现空值，所以必须分档才有全序。
    """
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def _校验维度列(维度列):
    if not isinstance(维度列, list):
        raise ValueError('延期汇总：维度列必须是列名的列表（要整表汇总成一行传 【】），'
                         '得到 %s' % type(维度列).__name__)
    for 列 in 维度列:
        if not isinstance(列, str):
            raise ValueError('延期汇总：维度列的每一项必须是列名字符串，得到 %r' % (列,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('延期汇总：维度列有重复项 %r' % (维度列,))
    撞名 = [列 for 列 in 维度列 if 列 in _固定列]
    if 撞名:
        raise ValueError('延期汇总：维度列 %s 与本块固定输出的列名撞车（%s），'
                         '会静默覆盖统计结果；请先用 制造/投影 改名'
                         % (撞名, '/'.join(_固定列)))
    if 延期列 in 维度列:
        raise ValueError('延期汇总：不能把延期天数列「%s」自己当维度列——'
                         '本块要对它做统计，拿它分组等于按每个天数值各成一组' % 延期列)


def _天数(值, 序):
    """延期天数的非空值必须是数值。

    布尔显式排除：`True` 在 Python 里等于 1，被求进「延期天数」里只会让报表
    多出一天谁也查不出来源。字符串同样报错——`表载入` 已把整数串推成整数，
    这里还是字符串说明上游没走 `读表` 或列里有脏值，那是该报的错。
    """
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError(
            '延期汇总：第 %d 行的「%s」是非空的非数值 %r（类型 %s），无法统计。'
            '延期天数只接受数值或 空（空 = 未交付，本块会把它排除并计数）'
            % (序, 延期列, 值, type(值).__name__))
    return 值


def 计延(表, 维度列):
    """按维度统计 `fact_orders.delay_days`，空值行排除且排除条数一起返回。

    参数
    ----
    表     : 行的列表（列表<字典<字符串,任意>>），每行必须有 `delay_days` 列
    维度列 : 列名字符串的列表；传 `【】` 表示整表汇总成一行

    返回
    ----
    `(汇总表, 排除的空值行数, 计入统计的行数)`，逐项含义见模块 docstring。

    空表输入返回 `([], 0, 0)`——「没有订单」是合法结果，不是错误。
    """
    _校验维度列(维度列)

    if not isinstance(表, list):
        raise ValueError('延期汇总：表必须是「行的列表」（列表<字典<字符串,任意>>），'
                         '得到 %s' % type(表).__name__)
    if not 表:
        # 一行都没有，表头无处可查，也就无从校验列是否存在。
        return [], 0, 0

    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('延期汇总：表的第 %d 行不是字典（表必须是行的列表，'
                             '每行是列名→值的字典），得到 %s'
                             % (序, type(行).__name__))

    # 列存在性：要求**每一行**都有这些列。只查首行会漏掉参差表，而漏掉的后果是
    # 某些行悄悄按「空值 = 未交付」入组——正是本块要防的那类静默污染。
    for 列 in list(维度列) + [延期列]:
        角色 = '维度列' if 列 in 维度列 else '延期天数列'
        for 序, 行 in enumerate(表, start=1):
            if 列 not in 行:
                raise ValueError(
                    '延期汇总：%s「%s」在表的第 %d 行不存在（该行的列：%s）；'
                    '不静默返回空表，请核对列名（延期天数列固定是 %s）'
                    % (角色, 列, 序, sorted(行.keys()), 延期列))

    桶表 = {}
    排除数 = 0
    计入数 = 0
    for 序, 行 in enumerate(表, start=1):
        组键 = tuple(行[列] for 列 in 维度列)
        桶 = 桶表.get(组键)
        if 桶 is None:
            # 维度键含空值照样建桶（空值自成一组，不丢弃）——丢弃会让各组
            # 订单数之和不等于原表行数，这种不守恒在 BI 里最难查。
            桶 = {'订单数': 0, '计入单数': 0, '未交付单数': 0,
                  '延期单数': 0, '按期单数': 0,
                  '合计': None, '最长': None}
            桶表[组键] = 桶
        桶['订单数'] += 1

        值 = 行[延期列]
        if 值 is None:
            # ★ 本块的核心：空 = 未交付，**排除出统计，但记下条数**。
            #   不是 continue 了就算，未交付单数会随结果一起交给调用方。
            桶['未交付单数'] += 1
            排除数 += 1
            continue

        值 = _天数(值, 序)
        桶['计入单数'] += 1
        计入数 += 1
        if 值 > 0:
            桶['延期单数'] += 1
        elif 值 == 0:
            # 0 = 按期交付。它是**有效数据**，进分母、进合计（加 0），
            # 与「未交付」分属两个计数器，绝不合并。
            桶['按期单数'] += 1
        else:
            # 负数 = 提前交付。本数据集没有（实测最小 0），但真实工厂会有，
            # 不报错、如实计入合计，只是既不算延期也不算按期。
            pass
        桶['合计'] = 值 if 桶['合计'] is None else 桶['合计'] + 值
        桶['最长'] = 值 if 桶['最长'] is None else max(桶['最长'], 值)

    汇总表 = []
    for 组键 in sorted(桶表, key=_排序键):
        桶 = 桶表[组键]
        行 = {}
        for 位, 列 in enumerate(维度列):
            行[列] = 组键[位]
        行['订单数'] = 桶['订单数']
        行['计入单数'] = 桶['计入单数']
        行['未交付单数'] = 桶['未交付单数']
        行['延期单数'] = 桶['延期单数']
        行['按期单数'] = 桶['按期单数']
        行['延期天数合计'] = 桶['合计']
        # 分母是 计入单数，不是 订单数——这一行就是整个块的要点。
        # 全组皆未交付时没有分母，返回 空 而不是 0（「没有数据」≠「零延期」）。
        行['延期天数均值'] = (None if 桶['计入单数'] == 0
                          else 桶['合计'] / 桶['计入单数'])
        行['最长延期天数'] = 桶['最长']
        汇总表.append(行)
    return 汇总表, 排除数, 计入数
