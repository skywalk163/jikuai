"""制造.投影 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**这是引擎层关系算子，不含任何业务口径**（ADR-40 §3.1）。它只取列子集：
不过滤行、不汇总、不加权、不做时间窗口对齐、不碰任何现成比率列、不改任何数值、
不改行序。口径判断全部留给口径层（产量 / 达成率 / 缺陷率是 W140-W142 的事）。

为什么下沉到 Python 背衬（而不是纯 `.jk`）：

**极快没有「给字典按动态键写值」的手段。** 字典的索引赋值走的是列表那条路
（`赵典["甲"] = 1` 会去 `int("甲")`，直接报错），而字典字面量虽然允许变量做键
（`{赵键: 赵值}`），但一次只能造一对；要按 N 个列名拼出一行，只能反复 `合并`
N 次，每次复制一遍整个字典——O(列数²) 的复制，还得在 `.jk` 里写两层 `遍历`
（副词 `皆` 不接用户函数）。Python 侧一个 dict 推导就完事，且天然保序。

ADR-40 §3.1 已写明：`值类型: 任意` 会让 `glue.py` 的 `type_feeds` 双向放行，
所以**类型图在引擎层不起作用**，本块的正确性完全由 `测试.jk` 保证。

═══════════════════════════════════════════════════════════════════════
三条刻意做出的语义决定（全部写进了 `块.json` 的 `描述`，调用方看得见）
═══════════════════════════════════════════════════════════════════════

**一、输出列序 = 调用方给的列名清单顺序，不是原表列序。**

这是本块与「删掉几列」的关键差别。溯源说明要按人读的顺序列字段
（`line_id, shift, actual_quantity` 而不是 CSV 里的原始次序），所以列序必须
由调用方指定。反过来说：想保持原表列序的调用方，得自己按原序传清单。

**二、列名清单里有重复列名 → 报错。**

字典的键天然唯一，重复列名会被静默吃掉，结果的列数与请求的列数不一致。
静默的数量不一致是最难查的一类 bug（下游按「我要了 5 列」写代码，实际拿到 4 列），
所以宁可当场拒绝——重复通常是复制粘贴漏改。

**三、列名清单为空 → 报错。**

投影出零列的表（一串空字典）没有任何业务含义，几乎肯定是上游把清单算错了。
返回一串空字典比报错糟得多：行数还对得上，列全没了，下游取列时才炸。

零第三方依赖，只用 Python 标准语法。
"""


def _类型档(值):
    """把值归到一个粗类型档，只用于报错文案（与 `制造.连接` 同口径）。"""
    if 值 is None:
        return '空'
    if isinstance(值, bool):
        return '布尔'
    if isinstance(值, (int, float)):
        return '数'
    if isinstance(值, str):
        return '字符串'
    return '其它(%s)' % type(值).__name__


def _列序(行表):
    """表的列名，按各行键的出现顺序取并集（dict 保序）。"""
    列 = {}
    for 行 in 行表:
        for 名 in 行:
            列[名] = True
    return list(列)


def _校验表(表):
    """表必须是「行的列表」：列表<字典<字符串,任意>>。"""
    if not isinstance(表, list):
        raise ValueError(
            '投影：表必须是「行的列表」（列表<字典<字符串,任意>>），'
            '实际收到 %s' % _类型档(表))
    for 序, 行 in enumerate(表):
        if not isinstance(行, dict):
            raise ValueError(
                '投影：表第 %d 行不是「列名→值」的字典，实际是 %s'
                % (序 + 1, _类型档(行)))
        for 名 in 行:
            if not isinstance(名, str):
                raise ValueError(
                    '投影：表第 %d 行有非字符串列名（%r），表的列名必须是字符串'
                    % (序 + 1, 名))
    return 表


def _校验列名清单(列名清单):
    """列名清单必须是非空、无重复的字符串列表。"""
    if not isinstance(列名清单, list):
        raise ValueError(
            '投影：列名清单必须是列名的列表（列表<字符串>），实际收到 %s'
            % _类型档(列名清单))
    if not 列名清单:
        raise ValueError(
            '投影：列名清单是空列表——投影出零列的表（一串空字典）没有业务含义，'
            '行数还对得上、列全没了，下游取列时才炸。本块直接拒绝')
    for 名 in 列名清单:
        if not isinstance(名, str):
            raise ValueError(
                '投影：列名清单里有非字符串项（%r），列名必须是字符串' % (名,))
    if len(set(列名清单)) != len(列名清单):
        重复 = sorted({名 for 名 in 列名清单 if 列名清单.count(名) > 1})
        raise ValueError(
            '投影：列名清单里有重复列名（%s）。字典的键天然唯一，重复会被静默'
            '吃掉，导致结果列数与请求列数不一致——静默的数量不一致最难查，'
            '故本块直接拒绝' % '、'.join(重复))
    return list(列名清单)


def _校验列存在(行表, 列名清单):
    """请求的列必须在表里存在，而且**每一行都有**。

    这里绝不能静默跳过缺失的列——那会让结果少一列，而下游只会发现「取列取到
    了空」，查半天才回溯到投影这一步。
    """
    列集 = set(_列序(行表))
    缺列 = [名 for 名 in 列名清单 if 名 not in 列集]
    if 缺列:
        raise ValueError(
            '投影：表里没有列「%s」。表实际的列是：%s。'
            '本块选择报错而不是悄悄少给一列——静默少列会让下游把「列名打错」'
            '误读成「这一列确实没值」'
            % ('、'.join(缺列), '、'.join(_列序(行表)) or '（无列）'))
    for 序, 行 in enumerate(行表):
        for 名 in 列名清单:
            if 名 not in 行:
                raise ValueError(
                    '投影：表第 %d 行缺少列「%s」。要投影的列必须每行都有，'
                    '否则输出表的行会参差不齐——本块不替缺列的行补空值，'
                    '补空等于凭空造数据' % (序 + 1, 名))


def 择字段(表, 列名清单):
    """取列子集，**按调用方给的列名清单顺序**排列输出列。

    参数
    ----
    表         : 行的列表（列表<字典<字符串,任意>>）
    列名清单   : 要保留的列名列表；非空、无重复。**输出列序就是这个顺序**，
                 不是原表列序

    返回
    ----
    行的列表，行数与行序与原表完全一致（本块不过滤行、不排序）。每个输出行是
    新字典，输入表与输入行都不被改动。

    空表短路：表为空则直接返回空表，此时不校验列名——空表在运行时没有列
    （表就是行的列表，没有独立 schema），无从判定；而空表投影出来必然是空表，
    短路不会产出任何错数。
    """
    行表 = _校验表(表)
    清单 = _校验列名清单(列名清单)

    if not 行表:
        return []

    _校验列存在(行表, 清单)

    # dict 保插入序（Python 3.7+ 语言保证），所以这里的推导式直接决定了输出列序。
    return [{名: 行[名] for 名 in 清单} for 行 in 行表]
