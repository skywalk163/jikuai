# -*- coding: utf-8 -*-
"""制造.排序 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**这是引擎层关系算子，不含任何业务口径**（ADR-40 §3.1）。它只按单列排序：
不过滤行、不汇总、不加权、不做时间窗口对齐、不碰任何现成比率列、不改任何数值。
口径判断全部留给口径层（产量 / 达成率 / 缺陷率是 W140-W142 的事）。

为什么下沉到 Python 背衬（而不是纯 `.jk`）：

1. **要一个稳定排序**。内建 `排序` 动词只对齐整的可比列表成立，对「行的列表」
   没有「按某列排」的语义；纯 `.jk` 自己写排序既慢又难保证稳定。Python 的
   `sorted` 是标准库保证的稳定排序（Timsort），直接用。
2. **空值要排到末尾且不参与比较**。这需要把空值行与非空行分开处理——在 `.jk`
   里写这套分桶逻辑（副词 `皆`/`只` 不接用户函数，得写显式 `遍历`）比下沉繁琐。

ADR-40 §3.1 已写明：`值类型: 任意` 会让 `glue.py` 的 `type_feeds` 双向放行，
所以**类型图在引擎层不起作用**，本块的正确性完全由 `测试.jk` 保证。

═══════════════════════════════════════════════════════════════════════
两条刻意做出的语义决定（全部写进了 `块.json` 的 `描述`，调用方看得见）
═══════════════════════════════════════════════════════════════════════

**一、空值一律排在末尾——升序降序都一样。**

`fact_orders` 的 `delay_days` 未交付时是空（ADR-40 §4.3）。若把空当成
「极小」或「极大」参与排序，未交付订单就会在延期排行榜里挤到头部或尾部，
污染「延期最多的前 N 单」这类问题。决议是空值不参与大小比较、永远沉到末尾，
且**空值行之间保持原相对次序**（也是稳定的一部分）。

**二、排序是稳定的：相等的值保持输入时的相对次序。**

不稳定排序会让「取前 N」在有并列时结果不确定——今天跑出来的 top3 和明天可能
不一样，溯源说明就没法复现。稳定性靠 Python `sorted` 的语言保证，再叠加
「非空段整体在前、空值段整体在后、两段内部各自保序」的拼接。

**类型混排会报错**：一列里既有数值又有字符串，Python 3 比较会抛 TypeError；
本块把它翻译成可读的中文错误，而不是让一个 TypeError 冒到调用方脸上。空值不算
「混排」——它被摘出去单独垫底，不参与比较。

零第三方依赖，只用 Python 标准语法。
"""


def _类型档(值):
    """把值归到一个粗类型档，只用于报错文案（与 `制造.连接` 同口径）。"""
    if 值 is None:
        return '空'
    if isinstance(值, bool):
        return '布尔'
    if isinstance(值, (int, float)):
        return '数'
    if isinstance(值, str):
        return '字符串'
    return '其它(%s)' % type(值).__name__


def _列序(行表):
    """表的列名，按各行键的出现顺序取并集（dict 保序）。"""
    列 = {}
    for 行 in 行表:
        for 名 in 行:
            列[名] = True
    return list(列)


def _校验表(表):
    """表必须是「行的列表」：列表<字典<字符串,任意>>。"""
    if not isinstance(表, list):
        raise ValueError(
            '排序：表必须是「行的列表」（列表<字典<字符串,任意>>），'
            '实际收到 %s' % _类型档(表))
    for 序, 行 in enumerate(表):
        if not isinstance(行, dict):
            raise ValueError(
                '排序：表第 %d 行不是「列名→值」的字典，实际是 %s'
                % (序 + 1, _类型档(行)))
        for 名 in 行:
            if not isinstance(名, str):
                raise ValueError(
                    '排序：表第 %d 行有非字符串列名（%r），表的列名必须是字符串'
                    % (序 + 1, 名))
    return 表


def _校验列存在(行表, 列名):
    """列名必须在表里存在，而且**每一行都有**。"""
    列集 = set(_列序(行表))
    if 列名 not in 列集:
        raise ValueError(
            '排序：表里没有列「%s」。表实际的列是：%s。'
            '本块选择报错而不是返回原表——静默不排序会让调用方以为「已按此列排好」'
            % (列名, '、'.join(_列序(行表)) or '（无列）'))
    for 序, 行 in enumerate(行表):
        if 列名 not in 行:
            raise ValueError(
                '排序：表第 %d 行缺少列「%s」。排序列必须每行都有，'
                '否则「缺这一列」的行没法定位——本块不替缺列的行编一个空值'
                % (序 + 1, 列名))


def 定序(表, 列名, 降序):
    """按单列排序，返回排好序的新表。空值排末尾，排序稳定。

    参数
    ----
    表     : 行的列表（列表<字典<字符串,任意>>）
    列名   : 按哪一列排（字符串）
    降序   : 必须是 `真` / `假`。真 = 降序，假 = 升序。
             空值无论升降都排在末尾

    返回
    ----
    行的列表，长度与原表相同（排序不增删行）。行是原行对象本身（内容不改），
    输入表不被改动。

    稳定性：相等的值保持输入时的相对次序；空值行之间也保持原相对次序。

    空表短路：表为空则直接返回空表，此时不校验列名。
    """
    行表 = _校验表(表)
    if not isinstance(列名, str):
        raise ValueError(
            '排序：列名必须是字符串，实际收到 %s（%r）' % (_类型档(列名), 列名))
    # 严格要求布尔，不吃「真值」。若放行任意真值，把列名误传到这个槽位
    #（字符串是真值）就会**静默降序**——参数顺序写错却跑得通、数是错的。
    if not isinstance(降序, bool):
        raise ValueError(
            '排序：降序必须是 真 或 假，实际收到 %s（%r）。'
            '本块不吃「真值」——放行任意真值时，把列名误传到这个槽位会静默变成'
            '降序，跑得通、次序是错的' % (_类型档(降序), 降序))

    if not 行表:
        return []

    _校验列存在(行表, 列名)

    # 分桶：非空行按原序进 有值段，空值行按原序进 垫底段。
    # 两段都保原序 = 稳定性的一半；sorted 的稳定性 = 另一半。
    有值 = [行 for 行 in 行表 if 行[列名] is not None]
    垫底 = [行 for 行 in 行表 if 行[列名] is None]

    try:
        有序 = sorted(有值, key=lambda 行: 行[列名], reverse=降序)
    except TypeError:
        # 一列里混了不可互比的类型（数值 + 字符串）。摘出前两个不同类型档
        # 报给调用方，而不是让裸 TypeError 冒上去。
        档 = []
        for 行 in 有值:
            d = _类型档(行[列名])
            if d not in 档:
                档.append(d)
        raise ValueError(
            '排序：列「%s」里有无法互相比较的混合类型（%s），没法排序。'
            '通常是这一列的类型推断出了错——把它统一成同一类型再排'
            % (列名, '、'.join(档)))

    return 有序 + 垫底
