# -*- coding: utf-8 -*-
"""制造.班间对比 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块**（ADR-40 §3.2）：把一张表按 `shift` 列切成白班/夜班两组，对
**调用方点名的度量列**各算一组数，再给出差值（白班 − 夜班）。

【目录名注记 · 偏离 WBS 预定名】WBS/任务把本块命名为 `制造/班次对比`（导出 `班比`）。
导出名 `班比` 两道验名都过（词法原子 + 全局唯一），照用。但**块目录名 `班次对比`
不是词法原子**：`tokenize('班次对比')` → `班`(IDENT) + `次`(**KEYWORD**) + `对比`(IDENT)，
`次` 是循环关键字，被切成三个 token，于是 `从 blocks.制造.班次对比 导入 班比。`
直接 ParseError——是 WBS 执行原则 7 点名的那类死块（同 `归组`/`归月`）。任务只预验了
导出名、没验目录名。故目录名改为词法原子的 `班间对比`（tokenize 单 IDENT），
导出名不动。详见交付报告的「偏离点」一节。

刻意的分工：度量列由调用方传，班次口径由本块写死
--------------------------------------------------
- `度量列` **是参数**。本块是通用的「两班对比」，不是某个指标专属的块——
  达成率、产量、停线分钟、电耗都能传进来。
- `班次列` 与两个班次名**写死**：列名 `shift`，取值 `白班` / `夜班`
  （ADR-40 §4.2 + 语义层实测：这一列恰好只有这两个中文串）。写死是因为
  「哪两个值算白班和夜班」是数据集事实而非调用方偏好，开成参数只会让不同
  调用方各拼一遍、拼错了还不报错。

**本块不做的三件事**（不做才让口径看得见）
------------------------------------------
1. **不筛产线**。「同产线白班 vs 夜班」要先用 `制造.选取`（`筛行`）筛到单条
   产线再调本块；直接把全表丢进来拿到的是**跨产线的两组数**，那是另一个问题的
   答案。本块不偷偷替调用方按 `line_id` 分组——分组了就得返回一张表，
   「两组数 + 差值」这个形状反而没了。
2. **不切时间窗口**。要按月/按旬对比先用 `制造.窗口`（`截期`）。
3. **不认识任何具体指标**。传 `achievement_rate` 进来它只会做**行级算术平均**
   （每条班次记录等权）。**这不是 ADR-40 §5.1 的加权口径**
   （`sum(actual_quantity)/sum(planned_quantity)`），两者数值不等。达成率的两个
   口径块是 W140 的事（`制造.达成率加权` / `制造.达成率均值`）；本块只是个
   通用的两组对比器，传现成比率列进来算出的就是行级均值，**用之前先想清楚
   你要的是哪个口径**。

═══════════════════════════════════════════════════════════════════════
决议：某个班次一行都没有 → **报错**（不返回 空、不返回空组）
═══════════════════════════════════════════════════════════════════════

理由三条：

1. **「差值」在缺一组时不存在。** 返回 `空` 差值会被上层读成「两班没差别」，
   而 `空` 与 `0` 混淆恰恰是 W142 立项要防的那类错（`delay_days` 的空 vs 0
   是同一个病）。这个块的全部用途就是给出差值，给不出差值就该说给不出。
2. **不报错就无法与「有行但度量列全空」区分。** 那才是真正应该返回 `空` 的
   情形：该班次有记录，只是度量值缺测——此时本块**返回该组 `非空个数=0`、
   `均值=空`、差值=`空`**，让调用方看到「有记录、没数据」。若「一行都没有」
   也走这条路，两种完全不同的状况就并成一个 `空`，谁也查不出是筛错了产线
   还是数据缺测。
3. **它几乎总是调用方的错，而且是可当场修的错。** 「一行都没有」的真实来源
   通常是：`制造.选取` 把 `line_id` 写成了不存在的值、时间窗口切空了、
   或者传进来的是 `fact_quality_defects`（**那张表没有 shift 列**，语义层
   已点名）。报错文案会把这三种可能直接写出来，比让人对着一个 `空` 猜快得多。

代价（写在这里，不藏）：真有单班制产线时本块会报错而不是给出「夜班没有」。
那个报错本身就是答案，且文案会说明「该班次零记录」；要静默处理单班制，
调用方应先自己判断班次种数，或用 `制造.分组汇总` 按 `shift` 分组。

输出契约
--------
`班比(表, 度量列)` → `(白班组, 夜班组, 差值)`

`白班组` / `夜班组` 是字典，键为：

  班次       —— `"白班"` / `"夜班"`（把组标在数据里，免得调用方靠位置记）
  行数       —— 该班次的行数（SQL `COUNT(*)`，含度量列为空的行）
  非空个数   —— 度量列非空的行数（SQL `COUNT(col)`），**它是 均值 的分母**
  求和       —— 非空值求和；非空个数为 0 时为 `空` 而非 0
  均值       —— 求和 / 非空个数；非空个数为 0 时为 `空`
  最大 / 最小 —— 非空值极值；非空个数为 0 时为 `空`

`差值` = 白班均值 − 夜班均值。任一侧均值为 `空` 时差值也是 `空`。
**符号约定：正数 = 白班高于夜班。** 这条必须记住，反过来读会把结论说反。

`shift` 出现除白班/夜班之外的第三种取值时**报错**——静默丢掉第三个班次会让
两组之和不等于总行数，是本块不接受的那种不守恒。

零第三方依赖，只用 Python 标准语法。
"""

#: 本块认的班次列名（ADR-40 §4.2 冻结）。
班次列 = 'shift'

#: 白班 / 夜班的字面取值。实测 `fact_production_actual.shift` 恰好只有这两个。
白班名 = '白班'
夜班名 = '夜班'


def _数值(值, 度量列, 序):
    """度量列的非空值必须是数值。

    布尔显式排除：`True + True = 2` 在业务度量里没有意义，与其求和求出个 2
    让人对着报表发呆，不如当场报错（同 `制造.分组汇总._数值`）。
    """
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError(
            '班次对比：度量列「%s」在第 %d 行是非空的非数值 %r（类型 %s），'
            '无法对比；度量列只接受数值或 空'
            % (度量列, 序, 值, type(值).__name__))
    return 值


def _空组(班次):
    return {'班次': 班次, '行数': 0, '非空个数': 0,
            '求和': None, '均值': None, '最大': None, '最小': None}


def 班比(表, 度量列):
    """同一张表里白班 vs 夜班的度量对比，返回两组数 + 差值（白 − 夜）。

    参数
    ----
    表     : 行的列表（列表<字典<字符串,任意>>），每行必须有 `shift` 与 `度量列`
    度量列 : 要对比的列名（如 `"achievement_rate"`、`"downtime_minutes"`、
             `"actual_quantity"`）

    返回
    ----
    `(白班组, 夜班组, 差值)`，逐项含义见模块 docstring。

    报错
    ----
    - 空表 / 某个班次一行都没有 → 报错（决议见模块 docstring，理由三条）
    - `shift` 出现第三种取值 → 报错
    - `shift` 或 `度量列` 在某行缺失 → 报错
    """
    if not isinstance(度量列, str) or not 度量列:
        raise ValueError('班次对比：度量列必须是单个非空列名字符串，得到 %r' % (度量列,))
    if 度量列 == 班次列:
        raise ValueError('班次对比：度量列不能是班次列「%s」本身——它是分组键，'
                         '不是可聚合的度量' % 班次列)
    if not isinstance(表, list):
        raise ValueError('班次对比：表必须是「行的列表」（列表<字典<字符串,任意>>），'
                         '得到 %s' % type(表).__name__)

    # 空表在本块里也是错：一张空表既没有白班也没有夜班，两组都缺，
    # 差值无从谈起。返回两个空组 + 空差值会被上层读成「两班没差别」。
    if not 表:
        raise ValueError(
            '班次对比：表是空的，白班与夜班都零记录，「差值」无从计算。'
            '本块刻意不返回 空——那会被读成「两班没差别」。'
            '常见来源：前一步 制造.选取 的条件筛空了，或 制造.窗口 的区间切空了')

    组表 = {白班名: _空组(白班名), 夜班名: _空组(夜班名)}
    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('班次对比：表的第 %d 行不是字典（表必须是行的列表，'
                             '每行是列名→值的字典），得到 %s'
                             % (序, type(行).__name__))
        if 班次列 not in 行:
            raise ValueError(
                '班次对比：班次列「%s」在表的第 %d 行不存在（该行的列：%s）。'
                '注意 fact_quality_defects 没有 %s 列，缺陷类指标做不到班次粒度；'
                'dim_workshop_line.shift_type 是产线的排班制度、不是记录的班次，'
                '不能拿来当分组键'
                % (班次列, 序, sorted(行.keys()), 班次列))
        if 度量列 not in 行:
            raise ValueError(
                '班次对比：度量列「%s」在表的第 %d 行不存在（该行的列：%s）；'
                '不静默按空值处理，请核对列名'
                % (度量列, 序, sorted(行.keys())))

        班 = 行[班次列]
        if 班 not in 组表:
            # 第三种取值：静默丢掉会让两组之和不等于总行数（不守恒）。
            raise ValueError(
                '班次对比：第 %d 行的「%s」是 %r，本块只认 %r 与 %r 两个班次。'
                '出现第三种取值时静默丢掉会让两组行数之和不等于总行数，'
                '故报错而不是兜掉；要按任意班次值分组请用 制造.分组汇总（维聚）'
                % (序, 班次列, 班, 白班名, 夜班名))

        组 = 组表[班]
        组['行数'] += 1
        值 = 行[度量列]
        if 值 is None:
            # 度量列空值：只计入 行数，不进 非空个数/求和/极值。
            continue
        值 = _数值(值, 度量列, 序)
        组['非空个数'] += 1
        组['求和'] = 值 if 组['求和'] is None else 组['求和'] + 值
        组['最大'] = 值 if 组['最大'] is None else max(组['最大'], 值)
        组['最小'] = 值 if 组['最小'] is None else min(组['最小'], 值)

    # ★ 决议落点：某个班次一行都没有 → 报错。与「有行但度量列全空」区分开，
    #   后者会走下去、给出 非空个数=0 / 均值=空 / 差值=空。
    缺 = [名 for 名 in (白班名, 夜班名) if 组表[名]['行数'] == 0]
    if 缺:
        raise ValueError(
            '班次对比：%s 一行都没有（另一班 %d 行），「差值」无从计算。'
            '本块刻意不返回 空 也不返回空组——空差值会被读成「两班没差别」，'
            '且会与「该班次有记录但度量列全为空」（那种情形本块会如实返回'
            '非空个数=0、均值=空）无法区分。常见来源：制造.选取 把 line_id '
            '写成了不存在的值、时间窗口切空了、或传进来的表本身只有单班记录'
            % ('/'.join(缺),
               sum(组表[名]['行数'] for 名 in (白班名, 夜班名) if 名 not in 缺)))

    for 组 in 组表.values():
        # 均值的分母是 非空个数，不是 行数。全组皆空时返回 空 而不是 0。
        组['均值'] = (None if 组['非空个数'] == 0
                    else 组['求和'] / 组['非空个数'])

    白 = 组表[白班名]
    夜 = 组表[夜班名]
    # 符号约定：正数 = 白班高于夜班。任一侧均值为空则差值为空。
    差值 = (None if 白['均值'] is None or 夜['均值'] is None
            else 白['均值'] - 夜['均值'])
    return 白, 夜, 差值
