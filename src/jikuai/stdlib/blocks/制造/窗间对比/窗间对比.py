# -*- coding: utf-8 -*-
"""制造.窗间对比 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块**（ADR-40 §3.2）：把两个**已经切好窗口、已经汇总到一行一组**的表按
维度键对齐，逐组给出 `差值` 与 `变化率`。v0.27.0 W154。

姊妹块：`制造.基线偏离`（导出 `基偏`）
------------------------------------
两块是 §12.4 缺口的两半，**互相点名**（G22 断言 3 的双块判法）：

- **本块 `窗间对比`（`窗比`）**：两个**平级**窗口相比（六月 vs 五月、本旬 vs 上旬）。
  谁当基期由调用方指定，口径对称。主输出是 `差值`（绝对量），`变化率` 是附带。
- **`基线偏离`（`基偏`）**：观察窗相对**自身长期基线**的升幅，口径不对称——基线代表
  「这条产线平时什么水平」。主输出是 `升幅`。

**只比两窗差值，不含基线偏离。** 需求里的「相比平时/相比基线/异常升高」要的是
`基线偏离`，不是本块：拿本块的「上一个窗口」当基线，会把一次性波动当成常态。

═══════════════════════════════════════════════════════════════════════
决议一：本块**不汇总**，两个入表必须已经一行一组
═══════════════════════════════════════════════════════════════════════

「按维度分组后汇总」这一步的口径分歧（求和 vs 算术平均 vs 产量加权）不在本块解决，
也不许本块偷偷替调用方拍一个 —— 那正是 ADR-40 §5 三处分歧点的病根。所以本块要求
两个入表**每个维度键最多一行**，重复键当场报错，并在文案里点名该用哪个汇总块：

- `制造.分组汇总`（`维聚`）—— 通用 group-by，行数/非空个数/求和/均值/极值一次给全
- `制造.产量汇总`（`产聚`）、`制造.能耗汇总`、`制造.缺陷汇总` —— 各自声明口径
- `制造.单车电耗现成`（`车耗现`）/ `制造.单车电耗重算`（`车耗算`）—— 比率列两口径

好处是本块的口径只剩一句话可说：**对齐 + 相减**。汇总口径写在上游块的描述里，
选块的人在候选列表里就能看见分歧，而不是在本块里被蒙掉。

═══════════════════════════════════════════════════════════════════════
决议二：空 ≠ 0，且「缺这一窗」与「这一窗值为空」必须能分开
═══════════════════════════════════════════════════════════════════════

三种不同的状况，绝不能并成同一个 `空`（`班间对比` 的同一条教训，源头是
`fact_orders.delay_days` 的 57 个空 vs 977 个 0）：

1. **维度键只在一窗出现**（新投产 / 停产的产线）→ 输出行的 `对齐` 是
   `缺基期` / `缺比期`，缺的那侧值为 `空`，`差值` 与 `变化率` 都是 `空`。
   **不当 0 处理** —— 当 0 会算出「从 0 涨到 191，涨幅无穷」这种假异常。
2. **两窗都有这个键，但某侧汇总值本身是 `空`**（该组记录全为空值，如
   `车耗现` 对全空组返回的 `单车电耗均值=空`）→ `对齐` 是 `两窗齐`，值为 `空`，
   `差值` / `变化率` 为 `空`。与第 1 种靠 `对齐` 字段区分。
3. **基期值是 0**（真的是零）→ `差值` 照算（`比期值 - 0`），但 `变化率` 是 `空`
   **而不是 `inf`**：0 做分母时「变化了百分之几」没有定义，返回 `inf` 会让下游
   排序把它顶到榜首，成为一条纯人造的异常。

`变化率` 的分母为负时也返回 `空`：`(比期 - 基期) / 基期` 在基期为负时符号会翻，
「+50%」会被读成好转而实际是恶化。绝对量的 `差值` 此时仍然照算、仍然可信。

输出契约
--------
`窗比(基期表, 比期表, 维度列, 度量列)` → 列表<字典<字符串,任意>>，每组一行：

  <各维度列名>  —— 原样回填维度键
  对齐          —— `两窗齐` / `缺基期` / `缺比期`
  基期值        —— 基期表该组的 `度量列` 值（可能是 `空`）
  比期值        —— 比期表该组的 `度量列` 值（可能是 `空`）
  差值          —— `比期值 - 基期值`；任一侧为 `空` 时为 `空`
  变化率        —— `差值 / 基期值`，**0-1 小数**（0.2589 即涨 2589‱ 不是 25.89，
                   见下）；基期值为 `空` / 0 / 负数时为 `空`

**`变化率` 的单位是 0-1 小数**（`0.2589` 表示涨 25.89%），与本数据集的
`achievement_rate`、`defect_rate` 等比率列一致，也与姊妹块 `基线偏离` 的 `升幅`
一致。要百分数自己乘 100 —— 本块不返回两种单位的同一个量。

行序按维度键升序（空值键排最前），确定可复现。两窗键的**并集**都会出现在输出里。

零第三方依赖，只用 Python 标准语法。
"""

#: 固定输出列。维度列与它们撞名会静默覆盖结果，故校验时当场报错。
固定列 = ('对齐', '基期值', '比期值', '差值', '变化率')

#: `对齐` 字段的三种取值。**不是布尔**：两窗齐/缺基期/缺比期是三态，
#: 压成布尔就又把「缺哪一侧」丢了。
对齐_齐 = '两窗齐'
对齐_缺基期 = '缺基期'
对齐_缺比期 = '缺比期'


def _排序键(组键):
    """含空值 / 混合类型的维度键 → 可确定排序的元组（分档保证全序）。

    与 `制造.单车电耗现成._排序键` 同法：空值排最前，其后布尔 / 数值 / 字符串
    各成一档，跨档不比较大小，保证任何输入都有确定行序。
    """
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def _校验维度列(维度列):
    if not isinstance(维度列, list):
        raise ValueError('窗间对比：维度列必须是列名的列表（列表<字符串>），得到 %s'
                         % type(维度列).__name__)
    if not 维度列:
        raise ValueError('窗间对比：维度列不能为空——至少要一个维度列（如 【"line_id"】）；'
                         '不按任何维度分的「两窗一个总数对比」请直接比两个标量')
    for 名 in 维度列:
        if not isinstance(名, str) or not 名:
            raise ValueError('窗间对比：维度列的每一项必须是非空列名字符串，得到 %r' % (名,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('窗间对比：维度列有重复项 %r' % (维度列,))
    撞名 = [名 for 名 in 维度列 if 名 in 固定列]
    if 撞名:
        raise ValueError('窗间对比：维度列 %s 与固定输出列（%s）撞名，会静默覆盖结果；'
                         '请先用 制造/投影 改名' % (撞名, '/'.join(固定列)))
    return list(维度列)


def _校验度量列(度量列, 维度):
    if not isinstance(度量列, str) or not 度量列:
        raise ValueError('窗间对比：度量列必须是单个非空列名字符串，得到 %r' % (度量列,))
    if 度量列 in 维度:
        raise ValueError('窗间对比：度量列「%s」同时也是维度列——它是分组键，'
                         '不是可对比的度量' % 度量列)
    if 度量列 in 固定列:
        raise ValueError('窗间对比：度量列「%s」与固定输出列（%s）撞名，'
                         '请先用 制造/投影 改名' % (度量列, '/'.join(固定列)))


def _数值或空(值, 侧, 度量列, 序):
    """度量列的值只接受数值或 `空`。

    布尔显式排除：`True + True = 2` 在业务度量里没有意义（同
    `制造.分组汇总._数值` 与 `制造.班间对比._数值`）。
    """
    if 值 is None:
        return None
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError(
            '窗间对比：%s第 %d 行的度量列「%s」是非空的非数值 %r（类型 %s），'
            '无法对比；度量列只接受数值或 空'
            % (侧, 序, 度量列, 值, type(值).__name__))
    return 值


def _收一侧(表, 侧, 维度, 度量列):
    """一侧的表 → {维度键: 度量值}。重复键 / 缺列 / 非数值都当场报错。"""
    if not isinstance(表, list):
        raise ValueError('窗间对比：%s必须是「行的列表」（列表<字典<字符串,任意>>），'
                         '得到 %s' % (侧, type(表).__name__))
    出 = {}
    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('窗间对比：%s第 %d 行不是字典（表必须是行的列表，'
                             '每行是列名→值的字典），得到 %s'
                             % (侧, 序, type(行).__name__))
        for 名 in 维度:
            if 名 not in 行:
                raise ValueError(
                    '窗间对比：维度列「%s」在%s第 %d 行不存在（该行的列：%s）。'
                    '两窗的列名必须一致——本块按列名对齐，列名不同就对不上，'
                    '不静默当作缺键。列名确实不同请先用 制造/投影 改名'
                    % (名, 侧, 序, sorted(行.keys())))
        if 度量列 not in 行:
            raise ValueError(
                '窗间对比：度量列「%s」在%s第 %d 行不存在（该行的列：%s）；'
                '不静默按空值处理。注意两个入表都得是**已汇总**的表，'
                '度量列名通常是上游汇总块的输出列名（如 分组汇总 的 均值 / 求和、'
                '单车电耗现成 的 单车电耗均值）'
                % (度量列, 侧, 序, sorted(行.keys())))
        键 = tuple(行[名] for 名 in 维度)
        if 键 in 出:
            raise ValueError(
                '窗间对比：%s里维度键 %r 出现了不止一行。本块**不汇总**——它要求'
                '两个入表已经一行一组。请先用 制造/分组汇总（维聚）或对应的口径'
                '汇总块（产量汇总 / 能耗汇总 / 缺陷汇总 / 单车电耗现成 / '
                '单车电耗重算）把表汇总到一行一组，再丢进来。本块刻意不替你选'
                '汇总口径（求和 / 算术平均 / 产量加权是三个不同的答案，'
                'ADR-40 §5 的分歧点就是这么来的）'
                % (侧, 键))
        出[键] = _数值或空(行[度量列], 侧, 度量列, 序)
    return 出


def 窗比(基期表, 比期表, 维度列, 度量列):
    """两个已汇总的窗口表按维度键对齐，逐组给出差值与变化率。

    入参
    ----
    基期表 : 列表<字典<字符串,任意>>  —— 基期（被减的那一侧），**已汇总到一行一组**
    比期表 : 列表<字典<字符串,任意>>  —— 比期（减去基期的那一侧），同上
    维度列 : 列表<字符串>             —— 对齐用的维度，如 【"line_id"】
    度量列 : 字符串                   —— 要对比的列名（通常是上游汇总块的输出列名）

    出参
    ----
    列表<字典<字符串,任意>>，每组一行，键为各维度列名 + `对齐` + `基期值` +
    `比期值` + `差值` + `变化率`。两窗键的并集都出现；按维度键升序。
    两个入表都空时返回空表。

    口径与三种「空」的区分见模块 docstring。**只比两窗差值，不含基线偏离**——
    要相对自身基线的升幅用姊妹块 `制造.基线偏离`（导出 `基偏`）。

    报错
    ----
    - 某侧维度键重复（说明没汇总）→ 报错并点名该用哪个汇总块
    - 维度列 / 度量列在某行缺失（含两表列名不一致）→ 报错
    - 度量列是非空的非数值 → 报错
    """
    维度 = _校验维度列(维度列)
    _校验度量列(度量列, 维度)

    基 = _收一侧(基期表, '基期表', 维度, 度量列)
    比 = _收一侧(比期表, '比期表', 维度, 度量列)

    结果 = []
    for 键 in sorted(set(基) | set(比), key=_排序键):
        在基 = 键 in 基
        在比 = 键 in 比
        基值 = 基.get(键)
        比值 = 比.get(键)

        if 在基 and 在比:
            对齐 = 对齐_齐
        elif 在比:
            对齐 = 对齐_缺基期
        else:
            对齐 = 对齐_缺比期

        # 空 ≠ 0：缺一侧、或某侧汇总值本身为空，差值都是 空 而不是把缺的那侧当 0。
        差值 = None if (基值 is None or 比值 is None) else 比值 - 基值

        if 差值 is None or 基值 is None or 基值 <= 0:
            # 分母 0 → 空 而不是 inf（inf 会被下游排序顶成假异常榜首）；
            # 分母为负 → 空，因为比率的符号会翻，把恶化读成好转。
            变化率 = None
        else:
            变化率 = 差值 / 基值

        行 = {}
        for 位, 名 in enumerate(维度):
            行[名] = 键[位]
        行['对齐'] = 对齐
        行['基期值'] = 基值
        行['比期值'] = 比值
        行['差值'] = 差值
        行['变化率'] = 变化率
        结果.append(行)
    return 结果
