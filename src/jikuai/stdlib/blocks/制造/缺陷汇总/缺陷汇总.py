# -*- coding: utf-8 -*-
"""制造.缺陷汇总 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块**（ADR-40 §3.2）。与引擎层的 `制造.分组汇总`（导出 `维聚`）分工：
`维聚` 是通用 group-by，度量列由调用方点名、不认识任何业务语义；本块把度量列
**写死为 `defect_count`**，因此它自己就是一句口径声明——「缺陷数 =
sum(fact_quality_defects.defect_count)」。选块的人拿到 `计陷` 就不用再猜
「按什么列汇总」。

口径（全部写进 `块.json` 的 `描述`，调用方看得见）
------------------------------------------------
- **度量列**：`defect_count`（缺陷件数，整数，绝对量）。
- **聚合方式**：求和。不是行计数——一条缺陷记录的 `defect_count` 可以大于 1，
  拿行数当缺陷数会低估。故本块同时给出 `记录条数`，让两个量各归各位、不互相顶替。
- **下钻**：`维度列` 放什么就按什么下钻。`process`（工序）/ `defect_type`
  （缺陷类型）/ `severity`（严重度）都是 `fact_quality_defects` 的真实列，
  可单列也可多列复合。
- **不算分母**：本块只出分子侧的绝对汇总。缺陷率是跨表派生指标，在姊妹块
  `制造.缺陷率`（导出 `陷率`）里算，那里会写明分母来源。
- **行序**：按 `缺陷数` 降序（本块就是给「缺陷最多的是谁」用的排行），
  同分时按维度键升序兜底，所以行序完全确定、可复现。

空值口径：**报错，不静默当 0**
-----------------------------
`defect_count` 出现空值（极快 `空` ↔ Python `None`）直接抛错。理由：把「不知道
有几个缺陷」当成 0 会让该组缺陷数凭空缩水，且运行期不报错——这正是 AGENTS.md
第四节说的「跑得通、数是错的」。ADR-40 §4.3 实测 `fact_quality_defects` 零空值，
所以这条在本数据集上不会触发；它是给换数据集时留的闸。

维度键含空值时**自成一组不丢弃**（与 `维聚` 同口径）：丢弃会让各组缺陷数之和
不等于总缺陷数，这种静默不守恒在 BI 里最难查。

零第三方依赖，只用 Python 标准语法。
"""

#: 本块写死的度量列名。改它等于改口径，必须同步改 `块.json` 的 `描述` 与本模块
#: docstring——三处任意一处漂了，「自报口径」这件事就作废了。
缺陷数列 = 'defect_count'

#: 固定输出列名。与维度列撞名会静默覆盖聚合结果，故先挡下（同 W135 连接算子的
#: 列名冲突策略：不静默覆盖）。
固定列 = ('缺陷数', '记录条数')


def _排序键(组键):
    """把可能含空值 / 混合类型的维度键映射成可确定排序的元组。

    分档：`None` → 0、布尔 → 1、数值 → 2、其余 → 3；同档内按值升序。
    Python 3 里 `None < "M001"` 直接 TypeError，而维度列确实会出现空值，
    分档之后才有全序，行序才真的确定。
    """
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def _校验表(表, 表名):
    """表必须是「行的列表」：列表<字典<字符串,任意>>。"""
    if not isinstance(表, list):
        raise ValueError(
            '缺陷汇总：%s 必须是「行的列表」（列表<字典<字符串,任意>>），得到 %s'
            % (表名, type(表).__name__))
    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError(
                '缺陷汇总：%s 第 %d 行不是「列名→值」的字典，得到 %s'
                % (表名, 序, type(行).__name__))
    return 表


def _校验维度列(维度列):
    """维度列必须是非空、无重复的列名字符串列表，且不与固定输出列撞名。"""
    if not isinstance(维度列, list):
        raise ValueError('缺陷汇总：维度列必须是列名的列表（列表<字符串>），得到 %s'
                         % type(维度列).__name__)
    if not 维度列:
        raise ValueError(
            '缺陷汇总：维度列不能为空——本块按维度汇总，至少要一个维度列；'
            '要全表一个总数请传 【"model_id"】 之后自己相加，或用 数据 域的求和块')
    for 名 in 维度列:
        if not isinstance(名, str):
            raise ValueError('缺陷汇总：维度列的每一项必须是列名字符串，得到 %r' % (名,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('缺陷汇总：维度列有重复项 %r（复制粘贴漏改？）' % (维度列,))
    撞名 = [名 for 名 in 维度列 if 名 in 固定列]
    if 撞名:
        raise ValueError(
            '缺陷汇总：维度列 %s 与本块固定输出列（%s）撞名，会静默覆盖聚合结果；'
            '请先用 制造/投影 改名' % (撞名, '/'.join(固定列)))
    return list(维度列)


def _校验列存在(表, 列清单, 角色):
    """要求**每一行**都有这些列。只查首行会漏掉参差表，漏掉的行会悄悄按空值入组。"""
    for 名 in 列清单:
        for 序, 行 in enumerate(表, start=1):
            if 名 not in 行:
                raise ValueError(
                    '缺陷汇总：%s「%s」在缺陷表第 %d 行不存在（该行的列：%s）；'
                    '不静默返回空表，请核对列名'
                    % (角色, 名, 序, sorted(行.keys())))


def _缺陷值(值, 行号):
    """`defect_count` 必须是非空数值。空值报错——不静默当 0。"""
    if 值 is None:
        raise ValueError(
            '缺陷汇总：缺陷表第 %d 行的 %s 是空值。本块**不把空值当 0**——'
            '「不知道有几个缺陷」与「零缺陷」不是一回事，静默当 0 会让该组缺陷数'
            '凭空缩水且运行期不报错。请先修数据，或用 制造/选取 把空值行筛掉'
            '（筛掉多少条要自己报出来）' % (行号, 缺陷数列))
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError(
            '缺陷汇总：缺陷表第 %d 行的 %s 是 %r（类型 %s），不是数值，无法求和'
            % (行号, 缺陷数列, 值, type(值).__name__))
    return 值


def 计陷(缺陷表, 维度列):
    """按维度列汇总 `fact_quality_defects.defect_count`。

    入参
    ----
    缺陷表 : 列表<字典<字符串,任意>>
        `fact_quality_defects` 形状的表（行的列表）。必须每行都有 `defect_count`
        与全部维度列。
    维度列 : 列表<字符串>
        分组维度。下钻就是往这里加列：`【"model_id"】`、
        `【"process", "defect_type"】`、`【"severity"】` 等。

    出参
    ----
    列表<字典<字符串,任意>>：每组一行，键为各维度列名 + `缺陷数` + `记录条数`。
    **按 `缺陷数` 降序**，同分按维度键升序兜底。空表输入返回空表（合法，非错误）。

    口径见模块 docstring 与 `块.json` 的 `描述`——那是对外承诺，改实现必须同步改。
    """
    _校验表(缺陷表, '缺陷表')
    维度 = _校验维度列(维度列)

    # 空表：没有行可分组。这是「没有数据」而不是错误，也无从校验列是否存在
    # （一行都没有，表头无处可查）。
    if not 缺陷表:
        return []

    _校验列存在(缺陷表, 维度, '维度列')
    _校验列存在(缺陷表, [缺陷数列], '度量列')

    桶表 = {}
    for 行号, 行 in enumerate(缺陷表, start=1):
        组键 = tuple(行[名] for 名 in 维度)
        桶 = 桶表.get(组键)
        if 桶 is None:
            # 维度键含空值照样建桶——「空值自成一组」是守恒的前提。
            桶 = {'缺陷数': 0, '记录条数': 0}
            桶表[组键] = 桶
        桶['缺陷数'] += _缺陷值(行[缺陷数列], 行号)
        桶['记录条数'] += 1

    结果 = []
    for 组键 in 桶表:
        行 = {}
        for 位, 名 in enumerate(维度):
            行[名] = 组键[位]
        行['缺陷数'] = 桶表[组键]['缺陷数']
        行['记录条数'] = 桶表[组键]['记录条数']
        结果.append((组键, 行))
    # 缺陷数降序（排行），同分按维度键升序 → 行序完全确定。
    结果.sort(key=lambda 项: (-项[1]['缺陷数'], _排序键(项[0])))
    return [行 for _键, 行 in 结果]
