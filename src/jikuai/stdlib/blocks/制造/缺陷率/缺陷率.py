# -*- coding: utf-8 -*-
"""制造.缺陷率 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块 · ADR-40 §5.3 分歧点 3**。缺陷率是全数据集唯一一个**无现成列、必须
跨表算分子分母**的指标（§5 的 2026-08-18 修正框已订正初稿「三个现成比率列」的
计数错误——真实表头里只有 achievement_rate、energy_per_vehicle 两个现成比率列）。

口径（写死，也全写进 `块.json` 的 `描述`）
--------------------------------------
    缺陷率 = sum(defect_count) / sum(actual_quantity)
其中分子来自 `fact_quality_defects.defect_count`、分母来自
`fact_production_actual.actual_quantity`。**先按维度各自汇总，再相除。**

为什么不能「先算行级比率再平均」
------------------------------
两张表粒度不同：缺陷表按 日×产线×车型×工序×缺陷类型×严重度（2992 行），产量表
按 日×产线×车型×班次（2896 行）。行级比率根本对不上——一条缺陷记录没有对应的
「那一行的产量」。硬凑出来的行级比率平均没有业务含义。实测 2026-06 全量：
先汇总后相除 = 1513 / 29931 = 0.050550，行级比率算术平均 = 0.032218，差 57%。

对齐键上限
---------
缺陷表**没有 shift 列**，所以对齐最细到「日×产线×车型」，做不到班次。本块要求
`维度列` 在两张表里**同名同在**，故实际可用的对齐维度是 line_id / model_id。
两表日期列名不同（defect_date vs production_date），要按时间窗口对齐请先各自用
`制造.窗口`（截期）切好再传进来——本块不替调用方猜日期列怎么对。

分母为 0 / 分母键缺失：显式决议，绝不静默当 0（本模块最要紧的一段）
--------------------------------------------------------------
每个输出组给出四个量：维度键 + `缺陷数`(分子) + `产量`(分母) + `缺陷率`(商)。

- **分母键缺失**（缺陷组在产量表找不到对应维度组）：`产量` = None、`缺陷率` =
  None，该组**照常出现在结果里**。返回 None 而不是 0，是因为「这个维度组在产量
  表里没有记录」与「产量为 0」是两码事——前者是数据覆盖问题，后者是停产。
- **分母为 0**（产量表有该组，但 sum(actual_quantity) = 0）：`缺陷率` = None、
  `产量` = 0。除以 0 没有意义，但分子分母都如实给出，让人当场看见「有缺陷、零
  产量」这个异常。
- **反向**（产量表有该组、缺陷表没有）：`缺陷数` = 0、`产量` = 实测、`缺陷率` =
  0.0。这是**真的零缺陷**，不是「把未知当 0」，所以照常给数。

三条都不报错、不静默丢弃：报错会让一整张报表因为一个边缘组全废（某产线某月停产
在 BI 里是常态）；静默丢弃会让各组缺陷数之和不等于 `制造.缺陷汇总` 的总缺陷数，
那种不守恒最难查。

分子/分母单元格空值 → 报错
------------------------
`defect_count` 或 `actual_quantity` 出现空值（极快 `空`）直接抛错，不静默跳过、
不当 0。这是「单元格缺值」，与上面「整组缺失/为 0」是不同层次的问题，必须分开
处理。ADR-40 §4.3 实测这两列零空值，所以本条在本数据集上不触发，是给换数据集
留的闸。

行序：按 `缺陷率` 降序（None 排最后），同率按维度键升序兜底。缺陷率最高的组读
第一行即得，行序完全确定可复现。

零第三方依赖，只用 Python 标准语法。
"""

分子列 = 'defect_count'
分母列 = 'actual_quantity'
固定列 = ('缺陷数', '产量', '缺陷率')


def _排序键(组键):
    """含空值 / 混合类型的维度键 → 可确定排序的元组（分档保证全序）。"""
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def _校验表(表, 表名):
    if not isinstance(表, list):
        raise ValueError('缺陷率：%s 必须是「行的列表」（列表<字典<字符串,任意>>），得到 %s'
                         % (表名, type(表).__name__))
    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('缺陷率：%s 第 %d 行不是字典，得到 %s'
                             % (表名, 序, type(行).__name__))
    return 表


def _校验维度列(维度列):
    if not isinstance(维度列, list):
        raise ValueError('缺陷率：维度列必须是列名的列表（列表<字符串>），得到 %s'
                         % type(维度列).__name__)
    if not 维度列:
        raise ValueError('缺陷率：维度列不能为空——至少要一个对齐维度（如 model_id）')
    for 名 in 维度列:
        if not isinstance(名, str):
            raise ValueError('缺陷率：维度列的每一项必须是列名字符串，得到 %r' % (名,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('缺陷率：维度列有重复项 %r' % (维度列,))
    撞名 = [名 for 名 in 维度列 if 名 in 固定列]
    if 撞名:
        raise ValueError('缺陷率：维度列 %s 与固定输出列（%s）撞名，会静默覆盖结果；'
                         '请先用 制造/投影 改名' % (撞名, '/'.join(固定列)))
    return list(维度列)


def _汇总(表, 维度列, 度量列, 表名):
    """按维度列把度量列求和，返回 {维度键元组: 合计}。空单元格报错，不当 0。"""
    for 名 in list(维度列) + [度量列]:
        for 序, 行 in enumerate(表, start=1):
            if 名 not in 行:
                raise ValueError(
                    '缺陷率：列「%s」在%s第 %d 行不存在（该行的列：%s）；'
                    '不静默返回空表，请核对列名' % (名, 表名, 序, sorted(行.keys())))
    桶 = {}
    for 序, 行 in enumerate(表, start=1):
        键 = tuple(行[名] for 名 in 维度列)
        值 = 行[度量列]
        if 值 is None:
            raise ValueError(
                '缺陷率：%s第 %d 行的 %s 是空值。分子/分母的单元格空值属于「缺值」，'
                '本块不静默跳过也不当 0（那与「整组缺失」是不同层次的问题）；'
                '请先修数据或用 制造/选取 把空值行筛掉' % (表名, 序, 度量列))
        if isinstance(值, bool) or not isinstance(值, (int, float)):
            raise ValueError('缺陷率：%s第 %d 行的 %s 是 %r（类型 %s），不是数值'
                             % (表名, 序, 度量列, 值, type(值).__name__))
        桶[键] = 桶.get(键, 0) + 值
    return 桶


def 陷率(缺陷表, 产量表, 维度列):
    """按维度列先汇总分子分母、再相除，算 缺陷率。

    入参
    ----
    缺陷表 : 列表<字典<字符串,任意>>   —— fact_quality_defects 形状，供分子 defect_count。
    产量表 : 列表<字典<字符串,任意>>   —— fact_production_actual 形状，供分母 actual_quantity。
    维度列 : 列表<字符串>              —— 对齐维度，必须在两张表里同名同在（如 【"model_id"】）。

    出参
    ----
    列表<字典<字符串,任意>>：每组一行，键为各维度列名 + `缺陷数` + `产量` + `缺陷率`。
    分母缺失 / 为 0 时 `缺陷率` 为 None（见模块 docstring 的显式决议）。按 `缺陷率`
    降序（None 最后），同率按维度键升序。两表任一为空按各自的空处理。
    """
    _校验表(缺陷表, '缺陷表')
    _校验表(产量表, '产量表')
    维度 = _校验维度列(维度列)

    分子桶 = _汇总(缺陷表, 维度, 分子列, '缺陷表') if 缺陷表 else {}
    分母桶 = _汇总(产量表, 维度, 分母列, '产量表') if 产量表 else {}

    所有键 = list(分子桶)
    for 键 in 分母桶:
        if 键 not in 分子桶:
            所有键.append(键)

    结果 = []
    for 键 in 所有键:
        缺陷数 = 分子桶.get(键, 0)        # 分子缺失 = 真的零缺陷
        产量 = 分母桶.get(键)            # 分母缺失 = None（键缺失），不当 0
        if 产量 is None:
            缺陷率 = None                # 分母键缺失 → 空
        elif 产量 == 0:
            缺陷率 = None                # 分母为 0 → 空（除 0 无意义），但产量=0 如实给
        else:
            缺陷率 = 缺陷数 / 产量
        行 = {}
        for 位, 名 in enumerate(维度):
            行[名] = 键[位]
        行['缺陷数'] = 缺陷数
        行['产量'] = 产量
        行['缺陷率'] = 缺陷率
        结果.append((键, 行))
    # 缺陷率降序（None 视为最小，排最后），同率按维度键升序 → 行序确定。
    结果.sort(key=lambda 项: (项[1]['缺陷率'] is None,
                              -(项[1]['缺陷率'] or 0.0),
                              _排序键(项[0])))
    return [行 for _键, 行 in 结果]
