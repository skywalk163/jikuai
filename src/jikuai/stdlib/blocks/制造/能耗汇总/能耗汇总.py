# -*- coding: utf-8 -*-
"""制造.能耗汇总 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层块**（ADR-40 §3.2）。按维度**汇总**能源三项绝对量：电 / 水 / 气。

三个真实列名（实读 `fact_energy_usage` 表头确认，2026-08-18）
----------------------------------------------------------
表头 = `energy_id, usage_date, workshop, line_id, model_id, shift,
electricity_kwh, water_ton, gas_m3, energy_per_vehicle`。本块汇总的三列：

===== ==================== ================================
输出   源列                 单位
===== ==================== ================================
电耗   `electricity_kwh`    千瓦时 kWh
水耗   `water_ton`          **吨**（不是立方米）
气耗   `gas_m3`             立方米（列名后缀 `m3`）
===== ==================== ================================

三者都是**绝对量**，跨维度汇总就是求和。三项一次遍历一起算完，上层不必为了拿三个
数扫表三遍。

刻意不碰 `energy_per_vehicle`
----------------------------
那是**现成比率列**，把「每台多少度」跨行相加得到的数没有业务含义（ADR-40 §5 点名的
「现成比率列直接汇总会算出错数」）。单车电耗有专门的一对口径块：
`制造.单车电耗现成`（`车耗现`，用现成列）与 `制造.单车电耗重算`（`车耗算`，按产量
重算）。本块只管绝对量。

按车间统计的两条路
----------------
`fact_energy_usage` **自己就有 `workshop` 列**（冗余落在事实表里），所以
`计耗(能耗表, ["workshop"])` 直接可用；也可以先用 `制造.连接`（`联表`）按 `line_id`
联 `dim_workshop_line` 再按维表的 `workshop` 分组。W141 实测两条路在本数据集上
**结果完全一致**（2026-06 四个车间的电耗逐个相等）。注意 `fact_production_actual`
与 `fact_quality_defects` **没有** `workshop` 列，按车间统计那两类指标只能走联表。

空值口径：报错，不静默当 0
------------------------
三列任一出现空值（极快 `空`）直接抛错。电水气是绝对量，「不知道用了多少」与「一点
没用」不是一回事；静默当 0 会让车间能耗凭空缩水，而运行期不报错。ADR-40 §4.3 实测
`fact_energy_usage` 零空值，本条是给换数据集留的闸。

维度键含空值时自成一组不丢弃（与 `制造.分组汇总` 同口径），否则各组之和不等于总量。

行序：按维度键升序（空值键最前），确定可复现。

零第三方依赖，只用 Python 标准语法。
"""

#: 输出列名 → 源列名。改这张表等于改口径，必须同步改 `块.json` 的 `描述`。
度量映射 = (
    ('电耗', 'electricity_kwh'),
    ('水耗', 'water_ton'),
    ('气耗', 'gas_m3'),
)

固定列 = ('记录数', '电耗', '水耗', '气耗')


def _排序键(组键):
    """含空值 / 混合类型的维度键 → 可确定排序的元组（分档保证全序）。"""
    出 = []
    for 元 in 组键:
        if 元 is None:
            出.append((0, 0))
        elif isinstance(元, bool):
            出.append((1, int(元)))
        elif isinstance(元, (int, float)):
            出.append((2, 元))
        else:
            出.append((3, str(元)))
    return 出


def _校验表(表):
    if not isinstance(表, list):
        raise ValueError('能耗汇总：能耗表必须是「行的列表」（列表<字典<字符串,任意>>），'
                         '得到 %s' % type(表).__name__)
    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('能耗汇总：能耗表第 %d 行不是字典，得到 %s'
                             % (序, type(行).__name__))
    return 表


def _校验维度列(维度列):
    if not isinstance(维度列, list):
        raise ValueError('能耗汇总：维度列必须是列名的列表（列表<字符串>），得到 %s'
                         % type(维度列).__name__)
    if not 维度列:
        raise ValueError('能耗汇总：维度列不能为空——至少要一个维度列'
                         '（如 【"workshop"】）')
    for 名 in 维度列:
        if not isinstance(名, str):
            raise ValueError('能耗汇总：维度列的每一项必须是列名字符串，得到 %r' % (名,))
    if len(set(维度列)) != len(维度列):
        raise ValueError('能耗汇总：维度列有重复项 %r' % (维度列,))
    撞名 = [名 for 名 in 维度列 if 名 in 固定列]
    if 撞名:
        raise ValueError('能耗汇总：维度列 %s 与固定输出列（%s）撞名，会静默覆盖结果；'
                         '请先用 制造/投影 改名' % (撞名, '/'.join(固定列)))
    return list(维度列)


def _校验列存在(表, 列清单, 角色):
    for 名 in 列清单:
        for 序, 行 in enumerate(表, start=1):
            if 名 not in 行:
                raise ValueError(
                    '能耗汇总：%s「%s」在能耗表第 %d 行不存在（该行的列：%s）；'
                    '不静默返回空表也不静默跳过这一项，请核对列名'
                    % (角色, 名, 序, sorted(行.keys())))


def _数值(值, 输出名, 源列, 行号):
    if 值 is None:
        raise ValueError(
            '能耗汇总：能耗表第 %d 行的 %s（%s）是空值。电水气是绝对量，本块**不把'
            '空值当 0**——「不知道用了多少」与「一点没用」不是一回事，静默当 0 会让'
            '该组能耗凭空缩水且运行期不报错。请先修数据，或用 制造/选取 把空值行'
            '筛掉（筛掉多少条要自己报出来）' % (行号, 源列, 输出名))
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError('能耗汇总：能耗表第 %d 行的 %s 是 %r（类型 %s），不是数值，'
                         '无法求和' % (行号, 源列, 值, type(值).__name__))
    return 值


def 计耗(能耗表, 维度列):
    """按维度列一次遍历汇总电 / 水 / 气三项绝对量。

    入参
    ----
    能耗表 : 列表<字典<字符串,任意>>  —— `fact_energy_usage` 形状的表。必须每行都有
        `electricity_kwh` / `water_ton` / `gas_m3` 与全部维度列。
    维度列 : 列表<字符串>             —— 分组维度，如 【"workshop"】、【"line_id", "shift"】。

    出参
    ----
    列表<字典<字符串,任意>>：每组一行，键为各维度列名 + `记录数` + `电耗`（kWh）
    + `水耗`（吨）+ `气耗`（立方米）。按维度键升序。空表输入返回空表。

    **不汇总** `energy_per_vehicle`（现成比率列）——单车电耗见 `制造.单车电耗现成`
    与 `制造.单车电耗重算`。口径详见模块 docstring 与 `块.json` 的 `描述`。
    """
    _校验表(能耗表)
    维度 = _校验维度列(维度列)

    if not 能耗表:
        return []

    源列清单 = [源 for _名, 源 in 度量映射]
    _校验列存在(能耗表, 维度, '维度列')
    _校验列存在(能耗表, 源列清单, '度量列')

    桶表 = {}
    for 行号, 行 in enumerate(能耗表, start=1):
        组键 = tuple(行[名] for 名 in 维度)
        桶 = 桶表.get(组键)
        if 桶 is None:
            # 维度键含空值照样建桶——「空值自成一组」是各组之和守恒的前提。
            桶 = {'记录数': 0}
            for 名, _源 in 度量映射:
                桶[名] = 0
            桶表[组键] = 桶
        桶['记录数'] += 1
        # 三项一趟扫完，上层不必为了三个数扫表三遍。
        for 名, 源 in 度量映射:
            桶[名] += _数值(行[源], 名, 源, 行号)

    结果 = []
    for 组键 in sorted(桶表, key=_排序键):
        桶 = 桶表[组键]
        行 = {}
        for 位, 名 in enumerate(维度):
            行[名] = 组键[位]
        行['记录数'] = 桶['记录数']
        for 名, _源 in 度量映射:
            行[名] = 桶[名]
        结果.append(行)
    return 结果
