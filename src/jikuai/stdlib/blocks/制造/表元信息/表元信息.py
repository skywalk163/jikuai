"""制造.表元信息 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

引擎层算子（ADR-40 §3.1）。给一张 `列表<字典<字符串,任意>>`（`表载入.读表`
的产物），返回 `[行数, 列名列表]`，供溯源面板与 W139 数据质量检查用。
**不含业务口径**：只数行、只取列名，不看任何列的值、不做汇总或判断。

为什么下沉到 Python
------------------
列名必须**保持载入时的原始列序**（引擎层的投影依赖列序，ADR-40 §4 冻结了
列序）。Python 3.7+ 的 dict 按插入序迭代，`csv.DictReader` / `表载入.读表`
建行字典时就是按表头顺序插入的，所以 `list(行[0].keys())` 天然还原表头列序。
极快侧遍历字典也能拿到键，但要还原「取第一行的键并保序」这套逻辑不如背衬直接。

空表行为（写进 `块.json` 描述）
----------------------------
行数为 0 时列名无从得知（表示里列信息只存在于行字典的键中），返回
`[0, []]`——空行数配空列名列表，不抛错。调用方据此判空。

零第三方依赖：纯标准库（其实一个都没用到）。
"""

from __future__ import annotations


def 表况(表):
    """返回 `[行数, 列名列表]`。

    - `行数` = 行的条数。
    - `列名列表` = 第一行字典的键，按原始列序；空表时为空列表。

    形状对应 `块.json` 里的精确元组 `("数", 列表<字符串>)`（极快元组的运行时
    表示就是列表，见 `财务.税单` 等既有块）。
    """
    if not isinstance(表, list):
        raise ValueError(
            '表元信息：入参必须是「行的列表」，得到 %s' % type(表).__name__)

    行数 = len(表)
    if 行数 == 0:
        return [0, []]

    首行 = 表[0]
    if not isinstance(首行, dict):
        raise ValueError(
            '表元信息：每一行必须是「列名→值」的字典，第 1 行得到 %s'
            % type(首行).__name__)

    列名 = list(首行.keys())
    return [行数, 列名]
