# -*- coding: utf-8 -*-
"""制造.表载入 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

引擎层算子（ADR-40 §3.1），只做「把 CSV 变成行的列表」这一件事，
**不含任何业务口径**：不做汇总、不算分母、不判现成列、不重算指标、不切窗口，
也**不校验 schema**。schema 冻结校验是 `scripts/check_chatbi_schema.py`
（W130 / ADR-40 §4）的职责，两边刻意不互相兜底——本块只负责载入。

为什么下沉到 Python
------------------
1. 极快没有 CSV 解析动词，手写字段切分要处理引号内逗号/换行，属于重造轮子。
2. 内建 `读取` 有两条硬约束：路径必须落在 CWD 内、单文件 10 MiB 上限
   （`docs/语法参考.md` §10.1，诊断码 JK-E4002 / JK-E4003）。BI 数据集通常
   放在仓库/项目里的固定位置，不在运行时 cwd 下。

**代价必须说清**：走 `蟒:` 桥读文件，本块因此**不受那道 CWD 闸约束**，
路径给什么就读什么（含绝对路径与 `..`）。这是 §10.1 里「要越出 CWD 就在宿主
侧显式封装」那条出口的正当用法，不是绕闸——但调用方要自己对路径来源负责。

`encoding='utf-8-sig'` 不是防御性写法
------------------------------------
2026-08-18 实测 `赛题/chatbi/数据集/`：8 张事实/维表 + 2 份问题集
（`question_public.csv` / `question_hidden.csv`）**都带 UTF-8 BOM**，而
`schema_relationships.csv` **不带**——同一个目录里两种混着。用 `utf-8` 会让
第一个列名变成 `\ufeffmodel_id`，后续所有按列名做的投影/连接静默失配，
运行期不报错。`utf-8-sig` 两种都吃（无 BOM 时行为与 `utf-8` 等同）。
`scripts/check_chatbi_schema.py` 的 `读表` 也是这个编码，结论直接复用。

类型推断三档
-----------
整数 / 小数 / 字符串，判据是**严格正则**而不是 `try: int(...)`：

- `int('1_000')` 在 Python 里是 1000，`float('nan')` / `float('inf')` 也能过。
  CSV 里出现这些字面量时把它们当数字是错的，正则一律挡在门外。
- **有前导零的纯数字串按字符串**（`007` → `'007'`，不是 `7`）。零填充的编码
  （工单号、批次号）一旦被推成整数就再也还原不回去，而这类损坏在运行期不报错。
  `0` 与 `0.5` 这种合法写法不受影响。

字符串档**原样保留**，不去首尾空白——去空白是规整策略，属于调用方的决定。
唯一的例外是「纯空白等同空值」，见下。

空值策略（ADR-40 §4.3 已冻结，本块照办）
--------------------------------------
空串与纯空白载为 `None`（跨桥后是极快的 `空`），**绝不填 0 也不填空串**。
实测只有 `fact_orders` 的 `actual_delivery_date` 与 `delay_days` 有空值
（未交付时为空），其余七张表零空值。把「未交付」当 0 天延期会直接污染延期
统计——这正是赛题加分项「缺失值提示」要抓的东西，不能自己先犯。

两处「不静默」
------------
- **表头重复列名直接报错**。`列表<字典<字符串,任意>>` 这个表示下同名列只能
  留一个，`csv.DictReader` 的默认行为是后者覆盖前者。`production_date` 与
  `usage_date` 这类近义列悄悄丢一个，比当场报错糟得多。
- **行字段数与表头不符直接报错**，不补 `None` 也不丢行。

零第三方依赖：只用标准库 `csv` 与 `re`。
"""

from __future__ import annotations

import csv
import re

#: 无前导零的十进制整数部分。`0` 单独合法，`007` 不合法（见模块头「类型推断三档」）。
_无前导零 = r'(?:0|[1-9][0-9]*)'

#: 整数档：可带符号，整数部分不许有前导零。
_整数正则 = re.compile(r'^[+-]?' + _无前导零 + r'$')

#: 小数档：定点（`12.5` / `0.5` / `.5`）或科学计数（`1e3` / `1.5E-2`）。
#: 整数部分同样不许前导零；`nan` / `inf` / `1_000` 都匹配不上，刻意如此。
_小数正则 = re.compile(
    r'^[+-]?(?:' + _无前导零 + r'\.[0-9]*|\.[0-9]+|' + _无前导零 + r')'
    r'(?:[eE][+-]?[0-9]+)?$'
)


def _推断(原值):
    """把一个 CSV 单元格文本推断成 整数 / 小数 / 字符串 / `None`。

    顺序固定：空值 → 整数 → 小数 → 字符串原样。`_整数正则` 先判，所以不带
    指数的纯整数不会退化成 float（`8` 是 `8` 而不是 `8.0`）。
    """
    if 原值 is None:
        return None
    文本 = 原值.strip()
    if 文本 == '':
        return None
    if _整数正则.match(文本):
        return int(文本)
    if _小数正则.match(文本):
        return float(文本)
    return 原值


def _校验表头(表头, 路径):
    """表头必须非空、每列有名、且列名互不重复。违规即抛，不静默。"""
    if not 表头:
        raise ValueError('表载入：%s 的表头是空的，没有任何列' % 路径)
    见过 = {}
    for 位置, 列 in enumerate(表头, start=1):
        名 = 列 if isinstance(列, str) else ''
        if 名.strip() == '':
            raise ValueError(
                '表载入：%s 表头第 %d 列没有列名 —— 无名列在「列名→值」的字典'
                '表示下无法引用，请先在源数据里补名' % (路径, 位置))
        if 名 in 见过:
            raise ValueError(
                '表载入：%s 表头有重复列名「%s」（第 %d 列与第 %d 列）—— 字典'
                '表示下同名列只能留一个，静默覆盖会让近义列悄悄丢掉一个，故直接'
                '拒绝，请先在源数据里改名或先做投影' % (路径, 名, 见过[名], 位置))
        见过[名] = 位置


def 读表(路径):
    """把一张 CSV 载成 `列表<字典<字符串,任意>>`：行的列表，每行是列名→值。

    - 列序 = 表头顺序，逐行一致（ADR-40 §4 把列序也当契约）。
    - 只有表头没有数据行 → 返回空列表（合法的空表）。
    - 连表头都没有（0 字节文件）→ 报错，这是文件坏了而不是空表。
    - 尾部空行按 CSV 惯例忽略。

    不校验 schema、不判断业务口径；错误一律抛 `ValueError`，经桥翻译成极快的
    运行错误诊断。
    """
    if not isinstance(路径, str) or 路径.strip() == '':
        raise ValueError('表载入：路径必须是非空字符串，得到 %r' % (路径,))

    try:
        句柄 = open(路径, 'r', encoding='utf-8-sig', newline='')
    except FileNotFoundError:
        raise ValueError('表载入：CSV 文件不存在：%s' % 路径) from None
    except IsADirectoryError:
        raise ValueError('表载入：路径是目录不是文件：%s' % 路径) from None
    except PermissionError:
        raise ValueError('表载入：没有读取权限：%s' % 路径) from None

    with 句柄 as f:
        读者 = csv.reader(f)
        try:
            表头 = next(读者)
        except StopIteration:
            raise ValueError(
                '表载入：%s 连表头都没有（空文件）—— 只有表头没有数据行才是'
                '合法的空表，那种情况会得到空列表' % 路径) from None
        _校验表头(表头, 路径)

        行表 = []
        for 行号, 原行 in enumerate(读者, start=2):
            if not 原行:
                continue
            if len(原行) != len(表头):
                raise ValueError(
                    '表载入：%s 第 %d 行有 %d 个字段，表头有 %d 个 —— 既不补齐'
                    '也不丢弃这一行，请先修数据'
                    % (路径, 行号, len(原行), len(表头)))
            行表.append({列: _推断(值) for 列, 值 in zip(表头, 原行)})

    return 行表
