# -*- coding: utf-8 -*-
"""制造.质量体检 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

引擎层数据质量算子（ADR-40 §3.1）。给一张 `列表<字典<字符串,任意>>`（`表载入.读表`
的产物）返回四件事的**计数**：

    [行数, 空值列与计数, 主键重复数, 外键孤儿行数]

它是赛题加分项「缺失值、异常值提示」的落点，也是「我们没拿脏数据算数」的自证。
**不含任何业务口径**：不认识产量、达成率、缺陷率，不做汇总、不算分母、不加权、
不判现成比率列、不重算指标、不切时间窗口。它只数格子。

为什么下沉到 Python
------------------
1. **要按运行时类型判空**。空值判定（`空` 与 `0`/空串的区分）在极快侧没有内建
   的类型判定动词，同 `制造.选取` 的第 1 条理由。
2. **主键重复与外键孤儿都要哈希集合**。极快侧没有集合类型，纯 `.jk` 只能写
   O(n²) 的双层 `遍历`——`fact_quality_defects` 2992 行 × `dim_model` 8 行还能忍，
   但 `fact_production_actual.plan_id → fact_production_plan.plan_id` 是
   2896 × 2896，纯 `.jk` 会慢到没法当门禁跑。

ADR-40 §3.1 已写明 `值类型: 任意` 会让 `glue.py` 的 `type_feeds` 双向放行，
**类型图在引擎层不起作用**，本块的正确性由 `测试.jk` 与
`tests/test_v0_26_0_w139_质量体检.py` 保证，不由粘合器保证。

═══════════════════════════════════════════════════════════════════════
五条刻意做出的语义决定（全部写进了 `块.json` 的 `描述`，调用方看得见）
═══════════════════════════════════════════════════════════════════════

**一、只有极快的 `空`（Python `None`）算空值。**

`0`、空串 `""`、字符串 `"NULL"` / `"NA"` / `"-"` 都**不算**空值。理由：`表载入`
已经在载入那一步把空串与纯空白折成 `空`（ADR-40 §4.3），到本块时空串只可能是
调用方自己造的数据；而把 `0` 算空值会直接毁掉「当天产量 0」这种合法事实。
哨兵值（`"NULL"` 当文本存）是**上游数据字典的问题**，本块不猜。

**二、`空值列与计数` 只报有空值的列。**

零空值的列不出现在结果里，所以「结果是空字典」= 这张表零空值。要拿全部列名请用
`制造.表元信息`（导出 `表况`）。这样做是为了让输出对人可读——8 张表里 7 张零空值，
逐列列出一串 0 只会把 `fact_orders` 那两列真空值淹掉。

**三、`主键重复数` 的口径是「多出来的行数」= 行数 − 不同主键组合数。**

不是「参与重复的行数」。两种口径在「3 行同键」上给出不同的数（本口径 2，另一
口径 3）。选前者是因为它直接回答「要去重得删掉几行」。`主键组` 传空列表表示
**不做主键检查**，返回 0——不是「零重复」的断言，见描述里的原话。

**四、外键列的值是 `空` 时不算孤儿。**

孤儿 = 「指向了一个不存在的父行」。`空` 是「没指向任何父行」，那是缺失值，归
第二项 `空值列与计数` 管。两件事混算会让「未填」和「填错」分不开。

**五、外键比对是值相等，不做类型转换：`"8"` 与 `8` 不匹配。**

同 `制造.选取` 的 `=` 口径。**这条有个实战陷阱**：CSV 两侧列的类型推断档不一致时
（一边 `L001` 是字符串、另一边被推成整数），非空行会**全部**变成孤儿，孤儿数
恰好等于非空行数。本块照实报这个数而不替你猜——看到「孤儿数 = 非空行数」应当
先怀疑类型档，不要直接当数据质量事故上报。

一处「不静默」
------------
**各行列名集合必须完全一致，不一致直接报错**。参差表下「这列在这行没有」与
「这列在这行是空」分不开，随便挑一个口径都会把另一种情况静默算错。`表载入` 的
产物天然齐整（它自己就拒绝字段数不符的行），所以这条只会在手搭数据时触发。

零第三方依赖：纯标准库（一个都没 import）。
"""

from __future__ import annotations


# ═══════════════════════════════════════════════════════════════════════
# 外键检查项的键名（契约的一部分，写死在这里，别在别处手打字面量）
# ═══════════════════════════════════════════════════════════════════════

_本列键 = '本列'
_目标表键 = '目标表'
_目标列键 = '目标列'
_外键项键集 = frozenset({_本列键, _目标表键, _目标列键})


def _类型档(值):
    """把值归到一个粗类型档，只用于报错文案（与 `制造.选取` / `制造.连接` 同口径）。

    `bool` 单独一档——它在 Python 里是 int 的子类，不先判就会被误归成 `数`。
    """
    if 值 is None:
        return '空'
    if isinstance(值, bool):
        return '布尔'
    if isinstance(值, (int, float)):
        return '数'
    if isinstance(值, str):
        return '字符串'
    return '其它(%s)' % type(值).__name__


def _校验表(表, 标签):
    """表必须是「行的列表」，且**各行列名集合完全一致**（见模块头「一处不静默」）。

    返回列名列表，按第一行的插入序——列序也是契约（ADR-40 §4）。
    """
    if not isinstance(表, list):
        raise ValueError(
            '质量体检：%s必须是「行的列表」（列表<字典<字符串,任意>>），实际收到 %s'
            % (标签, _类型档(表)))
    if not 表:
        return []

    for 序, 行 in enumerate(表):
        if not isinstance(行, dict):
            raise ValueError(
                '质量体检：%s第 %d 行不是「列名→值」的字典，实际是 %s'
                % (标签, 序 + 1, _类型档(行)))
        for 名 in 行:
            if not isinstance(名, str):
                raise ValueError(
                    '质量体检：%s第 %d 行有非字符串列名（%r），列名必须是字符串'
                    % (标签, 序 + 1, 名))

    列名 = list(表[0].keys())
    首行键集 = set(列名)
    for 序, 行 in enumerate(表[1:], start=2):
        if set(行.keys()) != 首行键集:
            缺 = sorted(首行键集 - set(行.keys()))
            多 = sorted(set(行.keys()) - 首行键集)
            raise ValueError(
                '质量体检：%s第 %d 行的列名集合与第 1 行不一致（缺 %s；多 %s）。'
                '参差表下「这列在这行没有」与「这列在这行是空」分不开，任选一个'
                '口径都会把另一种情况静默算错，故直接报错'
                % (标签, 序, '、'.join(缺) or '（无）', '、'.join(多) or '（无）'))
    return 列名


def _校验列存在(列名集, 列, 标签, 全部列名):
    """列必须在表里存在。绝不静默——静默会让「列名打错」被读成「零问题」。

    `列名集` 传 `None` 表示「这张表是空表、运行时没有列可查」，此时只校验类型。
    """
    if not isinstance(列, str):
        raise ValueError(
            '质量体检：%s必须是字符串，实际收到 %s（%r）'
            % (标签, _类型档(列), 列))
    if 列名集 is None:
        return
    if 列 not in 列名集:
        raise ValueError(
            '质量体检：%s「%s」在表里不存在。表实际的列是：%s。'
            '本块选择报错而不是当零处理——静默给 0 会让「列名打错」被读成'
            '「这张表没问题」，那是最恶劣的失败模式'
            % (标签, 列, '、'.join(全部列名) or '（无列）'))


def _可哈希(值, 列, 标签):
    """键值必须可哈希（CSV 载入只产出 数/字符串/空，都可哈希）。"""
    try:
        hash(值)
    except TypeError:
        raise ValueError(
            '质量体检：%s「%s」里出现不可哈希的值（%s），键比对要靠哈希集合。'
            '本块只吃 数 / 字符串 / 布尔 / 空 这些标量键'
            % (标签, 列, _类型档(值))) from None
    return 值


def _校验主键组(主键组, 列名集, 全部列名):
    if not isinstance(主键组, list):
        raise ValueError(
            '质量体检：主键组必须是列名的列表（列表<字符串>），传空列表表示'
            '不做主键检查，实际收到 %s' % _类型档(主键组))
    for 列 in 主键组:
        _校验列存在(列名集, 列, '主键列', 全部列名)
    if len(set(主键组)) != len(主键组):
        raise ValueError(
            '质量体检：主键组有重复列名（%s）。同一列写两遍不会让主键更严格，'
            '只会让人以为这是个复合键' % '、'.join(主键组))


def _校验外键检查(外键检查, 列名集, 全部列名):
    """校验每一项的形状，并返回 `[(本列, 目标值集, 目标列), ...]`。

    `目标表` 在这里就折成**值集合**：孤儿判定只需要「父键的取值集合」，
    早折一步能让 2896 × 2896 那条关系从 O(n·m) 降到 O(n+m)。
    """
    if not isinstance(外键检查, list):
        raise ValueError(
            '质量体检：外键检查必须是列表（每项一条外键关系），传空列表表示'
            '不做外键检查，实际收到 %s' % _类型档(外键检查))

    计划 = []
    见过本列 = {}
    for 序, 项 in enumerate(外键检查, start=1):
        if not isinstance(项, dict):
            raise ValueError(
                '质量体检：外键检查第 %d 项不是字典，实际是 %s。每项形如 '
                '{"本列": "model_id", "目标表": <父表>, "目标列": "model_id"}'
                % (序, _类型档(项)))
        键集 = set(项.keys())
        if 键集 != _外键项键集:
            缺 = sorted(_外键项键集 - 键集)
            多 = sorted(键集 - _外键项键集)
            raise ValueError(
                '质量体检：外键检查第 %d 项的键不对（缺 %s；多 %s）。'
                '必须恰好是「本列 / 目标表 / 目标列」三个键，多一个键就报错——'
                '静默忽略未知键会让拼错的键名（如「目标表名」）变成一条根本没跑的检查'
                % (序, '、'.join(缺) or '（无）', '、'.join(多) or '（无）'))

        本列 = 项[_本列键]
        _校验列存在(列名集, 本列, '外键检查第 %d 项的本列' % 序, 全部列名)
        if 本列 in 见过本列:
            raise ValueError(
                '质量体检：外键检查里「%s」出现两次（第 %d 项与第 %d 项）。'
                '结果按本列名索引，同名会让后一条静默盖掉前一条'
                % (本列, 见过本列[本列], 序))
        见过本列[本列] = 序

        父表 = 项[_目标表键]
        父列名 = _校验表(父表, '外键检查第 %d 项的目标表' % 序)
        目标列 = 项[_目标列键]
        _校验列存在(
            set(父列名) if 父表 else None, 目标列,
            '外键检查第 %d 项的目标列' % 序, 父列名)

        目标值集 = set()
        for 行 in 父表:
            值 = 行[目标列]
            if 值 is None:
                # 父表键里的空值不进值集：`空` 不是一个可被引用的父键，
                # 否则子表的空值会「匹配上」父表的空值，孤儿数被兜掉。
                continue
            目标值集.add(_可哈希(值, 目标列, '外键检查第 %d 项的目标列' % 序))
        计划.append((本列, 目标值集, 目标列))
    return 计划


def 体检(表, 主键组, 外键检查):
    """给一张表返回 `[行数, 空值列与计数, 主键重复数, 外键孤儿行数]`。

    参数
    ----
    表       : 行的列表（列表<字典<字符串,任意>>），`表载入.读表` 的产物
    主键组   : 主键列名的列表；**传空列表 = 不做主键检查**（返回 0，不是零重复的断言）
    外键检查 : 外键关系的列表；每项恰好三个键
               `{"本列": <本表列名>, "目标表": <父表的行列表>, "目标列": <父表列名>}`
               传空列表 = 不做外键检查

    返回
    ----
    四元组（极快元组的运行时表示是列表，同 `财务.税单` / `制造.表元信息`）：

    0. `行数`           : 数
    1. `空值列与计数`   : 字典<字符串,数>，**只含有空值的列**，按原始列序
    2. `主键重复数`     : 数 = 行数 − 不同主键组合数（「要去重得删几行」）
    3. `外键孤儿行数`   : 字典<字符串,数>，键是**本表列名**，按 `外键检查` 传入序

    输入表与目标表都不被改动。空表（行数 0）返回
    `[0, {}, 0, {每个本列: 0}]`——此时不校验本表列名是否存在（表就是行的列表，
    没有独立 schema，空表运行时没有列可查），但外键检查项的形状照校验。
    """
    列名 = _校验表(表, '表')
    列名集 = set(列名)

    if 表:
        _校验主键组(主键组, 列名集, 列名)
        计划 = _校验外键检查(外键检查, 列名集, 列名)
    else:
        # 空表：本表列名无从校验，故对本列放行；其余形状照查。
        if not isinstance(主键组, list):
            raise ValueError(
                '质量体检：主键组必须是列名的列表（列表<字符串>），实际收到 %s'
                % _类型档(主键组))
        计划 = _校验外键检查(外键检查, None, [])
        return [0, {}, 0, {本列: 0 for 本列, _值集, _目标列 in 计划}]

    行数 = len(表)

    # ---- 1. 空值列与计数：一次遍历，只有 None 算空 -----------------------
    空值计数 = {列: 0 for 列 in 列名}
    for 行 in 表:
        for 列 in 列名:
            if 行[列] is None:
                空值计数[列] += 1
    空值列与计数 = {列: 空值计数[列] for 列 in 列名 if 空值计数[列]}

    # ---- 2. 主键重复数 = 行数 − 不同主键组合数 --------------------------
    if 主键组:
        键集 = set()
        for 行 in 表:
            键集.add(tuple(
                _可哈希(行[列], 列, '主键列') for 列 in 主键组))
        主键重复数 = 行数 - len(键集)
    else:
        主键重复数 = 0

    # ---- 3. 外键孤儿行数：本列非空且不在父表值集里 ----------------------
    外键孤儿行数 = {}
    for 本列, 目标值集, 目标列 in 计划:
        孤儿 = 0
        for 行 in 表:
            值 = 行[本列]
            if 值 is None:
                # 空值不算孤儿（模块头决定四）：它归 `空值列与计数` 管。
                continue
            if _可哈希(值, 本列, '外键检查的本列') not in 目标值集:
                孤儿 += 1
        外键孤儿行数[本列] = 孤儿

    return [行数, 空值列与计数, 主键重复数, 外键孤儿行数]
