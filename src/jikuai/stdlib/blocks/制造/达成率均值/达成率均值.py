# -*- coding: utf-8 -*-
"""制造.达成率均值 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层**块（ADR-40 §3.2）。达成率的**行级算术平均**口径，ADR-40 §5.1 的另一
口径：

    达成率 = sum(achievement_rate) / 参与行数      （每条记录等权）

一个只产 20 台的班次和一个产 200 台的班次对结果贡献相同。

口径分歧点 1（与兄弟块 达成率权重 / 导出 `达权` 的关系）
------------------------------------------------------
- 本块（`达均`）：mean(achievement_rate)，行级算术平均、每条记录等权
- `达权`：sum(actual_quantity)/sum(planned_quantity)，产量加权，
  是 ADR-40 §5.1 的**默认口径**

实测（L003）：白班 均值 0.970209 vs 加权 0.969950（差 +0.000259）；
夜班 均值 0.850028 vs 加权 0.849740（差 +0.000288）。**两个数不相等**——这是
「口径可审计」的实证。本数据集上差值只有万分之几，但班次产量悬殊时会放大。

两块描述互相点名，是为了让 `jk 块 选` 的候选列表里就暴露「还有另一种算法」，
而不是等调用方自己发现口径差一档（AGENTS.md 第四节）。

用现成列，不重算
----------------
`achievement_rate` 是 CSV 里就有的现成比率列，实测逐行等于
`actual_quantity / planned_quantity`（2896/2896 行，容差 1e-4）。本块直接平均
这一列，**不联 `fact_production_plan` 重算**——要走原始量的路径请用 `达权`。

量纲
----
返回 0-1 区间的**小数，不是百分数**，且**可以大于 1**（实测行级值域
0.7619~1.0385）。不乘 100、不舍入。

分母为 0 → 报错（决议）
----------------------
参与行数为 0（空表）时抛中文错误，绝不返回 0 或 None。理由与 `达权` 一致：
0 会被读成「达成率极低」，真相是「一行数据都没有、平均值无定义」；None 会顺着
打印/拼接飘进报表。两个口径块在同样的坏输入上以同样方式失败。

空值 → 报错（不跳过）
--------------------
达成率列出现 None（极快 `空`）即报错。该表实测零空值（ADR-40 §4.3）；静默跳过
会让分母（参与行数）变小而平均值看着依然正常——这是行级平均口径最隐蔽的坑。

另有两条**量纲护栏**（本块特有，`达权` 拿原始台数算，没有这个风险）：
负值直接报错（达成率不可能为负）；大于 10 也报错并提示「疑似把百分数当小数
传进来了」——`95.5` 这种值混进来会把平均值抬高两个数量级，且不会报任何错。

零第三方依赖（WBS 执行原则第 6 条）：只用 Python 内置类型。
"""

#: 疑似百分数的判定阈值。实测行级达成率值域 0.7619~1.0385，正常数据离 10 极远；
#: 传进 95.5 这类百分数值不该被静默平均。
_疑似百分数阈值 = 10


def 达均(表, 达成率列):
    """行级算术平均达成率 = sum(达成率) / 参与行数。

    入参：
      表        —— 列表<字典<字符串,任意>>，行的列表（ADR-40 §3.1 的表表示）
      达成率列  —— 现成比率列名，通常是 `achievement_rate`

    出参：三元组 (平均达成率, 达成率合计, 参与行数)。
      平均达成率是 0-1 小数（可 > 1），后两项是给人复核分子分母的审计痕迹。

    报错口径：
      * 达成率列在任一行不存在 → 报错，不静默返回 0
      * 出现空值 / 非数值 → 报错，不跳过
      * 负值、或大于 10（疑似百分数） → 报错
      * 参与行数为 0（空表） → 报错，绝不返回 0 或 空
    """
    if not isinstance(达成率列, str):
        raise ValueError('达成率均值：达成率列必须是列名字符串，得到 %s'
                         % type(达成率列).__name__)
    if not isinstance(表, list):
        raise ValueError('达成率均值：表必须是行的列表，得到 %s' % type(表).__name__)

    # 空表：参与行数 0，分母为 0，平均值无定义 → 报错。
    if not 表:
        raise ValueError(
            '达成率均值：入参表为空，参与行数为 0，平均达成率无定义。'
            '本块不返回 0 也不返回 空——0 会被读成「达成率极低」，'
            '而真相是「一行数据都没有」。请确认上游筛选/连接是否把行滤空了。')

    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('达成率均值：表的第 %d 行不是字典（表必须是行的列表，'
                             '每行是列名→值的字典），得到 %s'
                             % (序, type(行).__name__))
        if 达成率列 not in 行:
            raise ValueError(
                '达成率均值：达成率列「%s」在表的第 %d 行不存在（该行的列：%s）；'
                '不静默返回 0，请核对列名'
                % (达成率列, 序, sorted(行.keys())))

    合计 = 0
    for 序, 行 in enumerate(表, start=1):
        值 = 行[达成率列]
        if 值 is None:
            raise ValueError(
                '达成率均值：达成率列「%s」在第 %d 行是空值。本块**不跳过也不填 0**：'
                'fact_production_actual 实测零空值（ADR-40 §4.3），出现空值意味着'
                '数据源不对或上游连接漏配；跳过会让分母（参与行数）变小而平均值'
                '看着依然正常。确实要排除这些行，请先用 制造/选取(筛行) 显式筛掉。'
                % (达成率列, 序))
        if isinstance(值, bool) or not isinstance(值, (int, float)):
            raise ValueError(
                '达成率均值：达成率列「%s」在第 %d 行是非数值 %r（类型 %s），'
                '无法求平均' % (达成率列, 序, 值, type(值).__name__))
        if 值 < 0:
            raise ValueError(
                '达成率均值：达成率列「%s」在第 %d 行是负值 %r，达成率不可能为负；'
                '请核对数据来源' % (达成率列, 序, 值))
        if 值 > _疑似百分数阈值:
            raise ValueError(
                '达成率均值：达成率列「%s」在第 %d 行的值是 %r，超过 %d。'
                '本块口径是 **0-1 小数、不是百分数**（实测行级值域 0.7619~1.0385，'
                '可以大于 1 但不会到 %d）——这个值疑似把百分数当小数传进来了。'
                '本块拒绝静默平均：百分数混进来会把结果抬高两个数量级而不报任何错。'
                % (达成率列, 序, 值, _疑似百分数阈值, _疑似百分数阈值))
        合计 += 值

    行数 = len(表)
    return (合计 / 行数, 合计, 行数)
