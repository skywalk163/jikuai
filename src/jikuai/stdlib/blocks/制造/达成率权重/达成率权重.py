# -*- coding: utf-8 -*-
"""制造.达成率权重 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**口径层**块（ADR-40 §3.2）。达成率的**产量加权**口径，ADR-40 §5.1 默认口径：

    达成率 = sum(actual_quantity) / sum(planned_quantity)

产量大的班次记录权重大，符合「产线整体效率」的业务含义。

目录名注记（ADR-15 §3.7 词法死名）
--------------------------------
WBS/ADR-40 里本块写作「达成率加权」，但「加权」含动词 `加`，
`tokenize('达成率加权')` → 达成率(IDENT)+加(VERB)+权(IDENT) 三段，作点分路径段
会被 `从 blocks.制造.达成率加权 导入` 直接切碎报 ParseError（与 `归组`/`择列`
同一个坑）。故目录名取等义原子名 **达成率权重**（`check_module_segment_atomicity`
过），导出名 `达权` 未变、调用方无感。

口径分歧点 1（与兄弟块 达成率均值 / 导出 `达均` 的关系）
------------------------------------------------------
同一句「平均达成率」有两个都对、数值不等的口径：

- 本块（`达权`）：产量加权 sum(actual)/sum(planned)
- `达均`：mean(achievement_rate)，行级算术平均，每条记录等权

实测（L003 白班 181 行）：加权 0.969950 vs 均值 0.970209，差 -0.000259。
两块描述互相点名，让 `jk 块 选` 的候选列表里就暴露「还有另一个口径」——这是
AGENTS.md 第四节「兄弟能力缺位」的主动解法。

量纲
----
返回 0-1 区间的**小数，不是百分数**，且**可以大于 1**（实测行级值域
0.7619~1.0385）。不乘 100、不舍入。

分母为 0 → 报错（决议）
----------------------
计划产量合计为 0（含空表）时抛中文错误，绝不返回 0 或 None：
- 返回 0 会被读成「一台没产出」，真相是「没有排产、比率无定义」；
- 返回 None 会顺着 打印/拼接 飘进报表，或在后续算术里抛出离现场很远的错误；
- 与兄弟块 `达均` 保持同一条规则，口径对比不掺杂行为差异。

空值 → 报错（不跳过）
--------------------
两列任一出现 None（极快 `空`）即报错。两表实测零空值（ADR-40 §4.3），空值只
可能来自数据源换了或上游 `联表` 漏配；静默跳过会让分子分母一起变小、比率看着
依然正常。

零第三方依赖（WBS 执行原则第 6 条）：只用 Python 内置类型。
"""


def _数值(值, 列名, 序):
    """产量列的值必须是非空数值（布尔显式排除），否则抛可读中文错误。"""
    if 值 is None:
        raise ValueError(
            '达成率权重：列「%s」在第 %d 行是空值。本块**不跳过也不填 0**：'
            'fact_production_actual/plan 实测零空值（ADR-40 §4.3），出现空值意味着'
            '数据源不对或上游连接漏配；跳过会让分子分母一起变小而比率看着正常。'
            % (列名, 序))
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise ValueError(
            '达成率权重：列「%s」在第 %d 行是非数值 %r（类型 %s），无法汇总；'
            '产量只接受数值' % (列名, 序, 值, type(值).__name__))
    return 值


def 达权(表, 实际产量列, 计划产量列):
    """产量加权达成率 = sum(实际) / sum(计划)。

    入参：
      表          —— 列表<字典<字符串,任意>>，行的列表（ADR-40 §3.1 的表表示）
      实际产量列  —— 通常是 `actual_quantity`
      计划产量列  —— 通常是 `planned_quantity`

    出参：四元组 (达成率, 实际产量合计, 计划产量合计, 参与行数)。
      达成率是 0-1 小数（可 > 1），后三项是给人复核分子分母的审计痕迹。

    报错口径：
      * 两列在任一行不存在 → 报错，不静默返回 0
      * 两列任一出现空值 / 非数值 → 报错
      * 计划产量合计为 0（含空表） → 报错，绝不返回 0 或 空
    """
    if not isinstance(实际产量列, str):
        raise ValueError('达成率权重：实际产量列必须是列名字符串，得到 %s'
                         % type(实际产量列).__name__)
    if not isinstance(计划产量列, str):
        raise ValueError('达成率权重：计划产量列必须是列名字符串，得到 %s'
                         % type(计划产量列).__name__)
    if 实际产量列 == 计划产量列:
        raise ValueError('达成率权重：实际产量列与计划产量列不能是同一列「%s」，'
                         '那样算出来恒等于 1，是口径错误' % 实际产量列)
    if not isinstance(表, list):
        raise ValueError('达成率权重：表必须是行的列表，得到 %s' % type(表).__name__)

    # 空表：没有分母，比率无定义 → 报错（分母为 0 决议的一种）。
    if not 表:
        raise ValueError(
            '达成率权重：入参表为空，计划产量合计为 0，达成率无定义。'
            '本块不返回 0 也不返回 空——0 会被读成「一台没产出」，'
            '而真相是「没有数据、比率无从算起」。请确认上游筛选/连接是否把行滤空了。')

    for 序, 行 in enumerate(表, start=1):
        if not isinstance(行, dict):
            raise ValueError('达成率权重：表的第 %d 行不是字典（表必须是行的列表，'
                             '每行是列名→值的字典），得到 %s'
                             % (序, type(行).__name__))
    for 列 in (实际产量列, 计划产量列):
        for 序, 行 in enumerate(表, start=1):
            if 列 not in 行:
                raise ValueError(
                    '达成率权重：列「%s」在表的第 %d 行不存在（该行的列：%s）；'
                    '不静默返回 0，请核对列名'
                    % (列, 序, sorted(行.keys())))

    实际合计 = 0
    计划合计 = 0
    for 序, 行 in enumerate(表, start=1):
        实际合计 += _数值(行[实际产量列], 实际产量列, 序)
        计划合计 += _数值(行[计划产量列], 计划产量列, 序)

    if 计划合计 == 0:
        raise ValueError(
            '达成率权重：计划产量合计为 0（参与 %d 行），达成率的分母为 0、无定义。'
            '本块不返回 0 也不返回 空——0 会被读成「一台没产出」，'
            '而真相是「没有排产、比率无从算起」。请核对计划产量列「%s」的取值。'
            % (len(表), 计划产量列))

    达成率 = 实际合计 / 计划合计
    return (达成率, 实际合计, 计划合计, len(表))
