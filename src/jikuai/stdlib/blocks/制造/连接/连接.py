# -*- coding: utf-8 -*-
"""制造.连接 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**这是引擎层关系算子，不含任何业务口径**（ADR-40 §3.1）。它只做等值内连接：
不过滤、不汇总、不做时间窗口对齐、不改任何数值。口径判断全部留给口径层。

为什么下沉到 Python 背衬（而不是纯 `.jk`）：

1. **复合键必须用元组做哈希键**。极快字典的键只接受字符串/整数
   （`pybridge._check_dict_key`），纯 `.jk` 实现只能把复合键的各段拼成一个
   字符串当键——那就得挑一个分隔符，而任何分隔符都可能出现在真实数据里
   （`("a|b", "c")` 与 `("a", "b|c")` 会撞成同一个键）。撞键的后果是**多连出
   行来、数还是错的**，正是本块最该防的那类故障。Python 侧 `tuple` 做键没有
   这个问题。
2. **哈希连接需要一次建索引**。2896 × 2896 的嵌套双循环有 838 万次比较，
   演示时会卡住；哈希连接是 O(左 + 右 + 命中)。

ADR-40 §3.1 已写明：`值类型: 任意` 会让 `glue.py` 的 `type_feeds` 双向放行，
所以**类型图在引擎层不起作用**，本块的正确性完全由 `测试.jk` 保证。

三条刻意做出的语义决定（都写进了 `块.json` 的 `描述`，调用方看得见）：

- **键列含空值的行不参与连接**。照 SQL 语义 `NULL = NULL` 不成立。
  `fact_orders.actual_delivery_date` / `delay_days` 就有空值（ADR-40 §4.3），
  复合键里带日期时很容易踩到。
- **同一键位上左右键值的类型档不一致 → 报错**，不是静默不命中。
  `"8"` 与 `8` 连不上，通常是载入时类型推断出了错；静默不命中会把那个 bug
  藏起来，让人对着 0 行结果查半天连接逻辑。
- **右表列名与左表冲突时必须由调用方给前缀**，缺前缀就报错。绝不静默覆盖：
  `production_date` 与 `usage_date` 这类近义列一旦被覆盖掉一个，结果跑得通、
  数是错的。本块也**不自造默认前缀**——前缀是溯源说明里要写给人看的东西。

零第三方依赖，只用 Python 标准语法。
"""


# ═══════════════════════════════════════════════════════════════════════
# 类型档
# ═══════════════════════════════════════════════════════════════════════

def _类型档(值):
    """把键值归到一个粗类型档，用于左右键位的一致性核对。

    刻意把 int 与 float 归进同一档 `数`：CSV 载入把 `"8"` 推成 int、`"8.0"`
    推成 float 是正常的，为此报错属于误伤。真正要抓的是 `数` ↔ `字符串`
    这种跨档不一致。`bool` 单独一档——它在 Python 里是 int 的子类，若不先判
    就会被误归成 `数`。
    """
    if isinstance(值, bool):
        return '布尔'
    if isinstance(值, (int, float)):
        return '数'
    if isinstance(值, str):
        return '字符串'
    return '其它(%s)' % type(值).__name__


def _列序(行表):
    """表的列名，按各行键的出现顺序取并集（dict 保序）。"""
    列 = {}
    for 行 in 行表:
        for 名 in 行:
            列[名] = True
    return list(列)


# ═══════════════════════════════════════════════════════════════════════
# 入参校验
# ═══════════════════════════════════════════════════════════════════════

def _校验表(表, 表名):
    """表必须是「行的列表」：列表<字典<字符串,任意>>。"""
    if not isinstance(表, list):
        raise ValueError(
            '连接：%s 必须是「行的列表」（列表<字典<字符串,任意>>），'
            '实际收到 %s' % (表名, _类型档(表)))
    for 序, 行 in enumerate(表):
        if not isinstance(行, dict):
            raise ValueError(
                '连接：%s 第 %d 行不是「列名→值」的字典，实际是 %s'
                % (表名, 序 + 1, _类型档(行)))
        for 名 in 行:
            if not isinstance(名, str):
                raise ValueError(
                    '连接：%s 第 %d 行有非字符串列名（%r），表的列名必须是字符串'
                    % (表名, 序 + 1, 名))
    return 表


def _校验键(键, 键名):
    """键列清单必须是非空、无重复的字符串列表。"""
    if not isinstance(键, list):
        raise ValueError(
            '连接：%s 必须是列名的列表（列表<字符串>），实际收到 %s'
            % (键名, _类型档(键)))
    if not 键:
        raise ValueError(
            '连接：%s 是空列表——内连接至少要一个键列，本块不做无键的笛卡尔积'
            % 键名)
    for 名 in 键:
        if not isinstance(名, str):
            raise ValueError(
                '连接：%s 里有非字符串项（%r），键列名必须是字符串' % (键名, 名))
    if len(set(键)) != len(键):
        重复 = sorted({名 for 名 in 键 if 键.count(名) > 1})
        raise ValueError(
            '连接：%s 里有重复列名（%s）。复合键的每一位应当是不同的列，'
            '重复通常是复制粘贴漏改，故本块直接拒绝' % (键名, '、'.join(重复)))
    return list(键)


def _校验键列存在(行表, 键名清单, 表名):
    """键列必须在表里存在，而且**每一行都有**。"""
    列集 = set(_列序(行表))
    缺列 = [名 for 名 in 键名清单 if 名 not in 列集]
    if 缺列:
        raise ValueError(
            '连接：%s 里没有键列「%s」。%s 实际的列是：%s'
            % (表名, '、'.join(缺列), 表名, '、'.join(_列序(行表)) or '（无列）'))
    for 序, 行 in enumerate(行表):
        for 名 in 键名清单:
            if 名 not in 行:
                raise ValueError(
                    '连接：%s 第 %d 行缺少键列「%s」。键列必须每行都有，'
                    '否则连接口径不成立——本块不替缺列的行编一个空键'
                    % (表名, 序 + 1, 名))


def _校验键类型(左行, 左键名, 右行, 右键名):
    """逐个键位核对左右键值的类型档，跨档即报错。

    连空值一起跳过：空值键的行本来就不参与连接，拿它的类型说事没有意义。
    """
    for 位 in range(len(左键名)):
        档表 = {}
        for 表名, 行表, 列名 in (('左表', 左行, 左键名[位]),
                                 ('右表', 右行, 右键名[位])):
            for 行 in 行表:
                值 = 行.get(列名)
                if 值 is None:
                    continue
                档表.setdefault(_类型档(值), set()).add('%s.%s' % (表名, 列名))
        if len(档表) > 1:
            明细 = '；'.join(
                '%s ← %s' % (档, '/'.join(sorted(档表[档])))
                for 档 in sorted(档表))
            raise ValueError(
                '连接：第 %d 个键位上键值类型档不一致（%s）。本块选择报错而不是'
                '静默不命中——"8" 与 8 连不上通常是载入时类型推断出了错，'
                '静默不命中会把那个 bug 藏起来' % (位 + 1, 明细))


def _算列名映射(左列, 右列序, 前缀):
    """右表列名 → 输出列名。冲突列加前缀；缺前缀或前缀仍撞车都报错。"""
    左列集 = set(左列)
    冲突 = [名 for 名 in 右列序 if 名 in 左列集]
    if 冲突 and not (isinstance(前缀, str) and 前缀 != ''):
        raise ValueError(
            '连接：右表这些列名与左表冲突（%s），必须显式给出「右表列名冲突'
            '前缀」。本块既不静默覆盖（覆盖会让 production_date / usage_date '
            '这类近义列悄悄丢一个，结果跑得通、数是错的），也不自造默认前缀'
            '（前缀要写进溯源说明，得由调用方决定）' % '、'.join(冲突))

    映射 = {}
    for 名 in 右列序:
        映射[名] = (前缀 + 名) if 名 in 左列集 else 名

    # 二阶冲突：加了前缀之后仍可能撞上左表列或另一个右表列
    # （前缀 "甲_" + 右列 "乙" 撞上右列 "甲_乙"）。这条不查就等于留了后门。
    已占 = dict.fromkeys(左列)
    for 名 in 右列序:
        输出名 = 映射[名]
        if 输出名 in 已占:
            raise ValueError(
                '连接：右表列「%s」加前缀后变成「%s」，与已有列撞车。'
                '换一个前缀——本块拒绝在这里静默覆盖' % (名, 输出名))
        已占[输出名] = True
    return 映射


# ═══════════════════════════════════════════════════════════════════════
# 主体：哈希内连接
# ═══════════════════════════════════════════════════════════════════════

def 联表(左表, 右表, 左键, 右键, 前缀):
    """等值内连接（inner join），支持 1:1、1:N 与复合键。

    参数
    ----
    左表 / 右表 : 行的列表（列表<字典<字符串,任意>>）
    左键 / 右键 : 键列名的列表，**长度必须相等**，按位一一对应
    前缀        : 右表冲突列的列名前缀；无冲突时可传空串或 `空`

    返回
    ----
    行的列表。左表顺序稳定，同一左行的多个命中按右表原顺序排列。
    输入的两张表都不被改动（每个输出行是新字典）。

    行数关系：结果行数 = Σ（每个左行在右表命中的行数）。1:1 时等于左表行数；
    1:N 时会放大——这是内连接的正常语义，不是 bug，调用方要自己知道。
    """
    左行 = _校验表(左表, '左表')
    右行 = _校验表(右表, '右表')
    左键名 = _校验键(左键, '左键')
    右键名 = _校验键(右键, '右键')

    if len(左键名) != len(右键名):
        raise ValueError(
            '连接：左键 %d 个列、右键 %d 个列，长度必须相等（按位一一对应）。'
            '左键=%s，右键=%s'
            % (len(左键名), len(右键名), '、'.join(左键名), '、'.join(右键名)))

    # 空表短路。空表在运行时没有列（表就是行的列表，没有独立 schema），
    # 键列存在性、类型档、列名冲突三项都无从判定；而任一侧为空时内连接
    # 结果必然为空，短路不会产出任何错数。此行为写进了 `块.json` 的 `描述`。
    if not 左行 or not 右行:
        return []

    _校验键列存在(左行, 左键名, '左表')
    _校验键列存在(右行, 右键名, '右表')
    _校验键类型(左行, 左键名, 右行, 右键名)

    右列序 = _列序(右行)
    映射 = _算列名映射(_列序(左行), 右列序, 前缀)

    # 建索引：右表按键元组分桶。键含空值的行**不入桶**（空 = 空 不成立）。
    桶表 = {}
    for 行 in 右行:
        键值 = tuple(行.get(名) for 名 in 右键名)
        if None in 键值:
            continue
        桶表.setdefault(键值, []).append(行)

    # 扫左表。键含空值的左行同样不参与，直接跳过。
    结果 = []
    for 左项 in 左行:
        键值 = tuple(左项.get(名) for 名 in 左键名)
        if None in 键值:
            continue
        命中 = 桶表.get(键值)
        if not 命中:
            continue
        for 右项 in 命中:
            新行 = dict(左项)
            # 只搬该右行**实际存在**的列，不给缺列补空——补空等于凭空造数据。
            for 名 in 右项:
                新行[映射[名]] = 右项[名]
            结果.append(新行)
    return 结果
