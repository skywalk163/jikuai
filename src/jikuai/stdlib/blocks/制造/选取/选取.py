# -*- coding: utf-8 -*-
"""制造.选取 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

**这是引擎层关系算子，不含任何业务口径**（ADR-40 §3.1）。它只按「列名 + 比较符
+ 值」逐行判命中：不汇总、不加权、不做时间窗口对齐、不碰任何现成比率列、
不改任何数值。口径判断全部留给口径层（产量 / 达成率 / 缺陷率是 W140-W142 的事）。

为什么下沉到 Python 背衬（而不是纯 `.jk`）：

1. **要按运行时类型分流**。空值 / 数值 / 字符串三档的判定，极快侧没有内建的
   类型判定动词（`类名` 只吃用户类实例），纯 `.jk` 要么绕 `蟒:` 桥、要么给一个
   层级 0 的引擎块加跨块依赖（`工具.型名`），两条都比下沉更别扭。
2. **副词 `只` 不接用户函数**，纯 `.jk` 过滤必须写显式 `遍历` 循环；本块的判命中
   逻辑有七个比较符 × 三档类型，写在 `.jk` 里会摊成上百行分支，正确性更难守。

ADR-40 §3.1 已写明：`值类型: 任意` 会让 `glue.py` 的 `type_feeds` 双向放行，
所以**类型图在引擎层不起作用**，本块的正确性完全由 `测试.jk` 保证。

═══════════════════════════════════════════════════════════════════════
四条刻意做出的语义决定（全部写进了 `块.json` 的 `描述`，调用方看得见）
═══════════════════════════════════════════════════════════════════════

**一、含空值的行在任何比较符下都不命中——`≠` 也不命中。**

这条照 SQL 三值逻辑：`NULL ≠ 'x'` 的结果是 UNKNOWN 而不是 TRUE，所以
`WHERE 列 ≠ 'x'` 不会捞出空值行。它**反直觉**：中文读「实际交付日期 ≠ 空」
听起来就该把空的那些排除、把非空的留下，但读「订单状态 ≠ 已完成」时，很多人
会以为空状态的行算「不等于已完成」而被留下——本块不留。

不点明这一条，它就是 AGENTS.md 第四节所说的「兄弟能力缺位」陷阱：代码跑得通、
数是错的。`fact_orders` 的 `actual_delivery_date` / `delay_days` 正好有空值
（ADR-40 §4.3），一做延期筛选就会踩上。

**二、比较值不许传空。**

既然含空值的行永不命中，`筛行(表, "列", "=", 空)` 必然返回空表——一个「永远
返回空表」的调用就是纯粹的误用，而静默返回空表是最恶劣的失败模式（调用方会
以为「确实没有满足条件的行」）。所以直接报错，并在文案里指路：要挑空值行是
数据质量检查的活，不是选取算子的活。

**三、`>` `≥` `<` `≤` 只支持数值，字符串一律报错，不做字典序。**

BI 语境下「字符串的大于」几乎总是误用：`order_status > "已完成"` 会按 Unicode
码点比出一个没有业务含义的真假；日期列若被载成字符串，`"2026-06-1" < "2026-06-9"`
碰上 `"2026-06-10"` 就会给出错答案（字典序里 `"2026-06-10" < "2026-06-9"`）。
静默按字典序比 = 跑得通、数是错的。报错则当场暴露「这列不是数值」这个真问题。

**四、`含` 只支持字符串，非字符串单元格报错而不是不命中。**

同一条理由的镜像：`含` 遇到数值单元格若静默判不命中，就把「这列的类型推断出了
错」藏成了一个少几行的结果。与 `制造.连接` 对键值类型档不一致选择报错同源。

`=` / `≠` 是唯一放行跨类型的一对：它们只问相等，不问大小。**但不做类型转换**
——`"20" = 20` 为假。这一条也要写进描述，否则 CSV 把数字列载成字符串时，
调用方会对着 0 行结果查半天筛选条件。

零第三方依赖，只用 Python 标准语法。
"""


# ═══════════════════════════════════════════════════════════════════════
# 比较符表
# ═══════════════════════════════════════════════════════════════════════

#: 全部合法比较符。全角符号是刻意的：极快源码里 `>=` 没有意义（无中缀运算符），
#: 而 `≥` 单字符在中文语境里读起来也顺。
_比较符清单 = ('=', '≠', '>', '≥', '<', '≤', '含')

#: 需要「大小」语义的四个，只对数值成立。
_序比较符 = ('>', '≥', '<', '≤')


# ═══════════════════════════════════════════════════════════════════════
# 类型档
# ═══════════════════════════════════════════════════════════════════════

def _类型档(值):
    """把值归到一个粗类型档，只用于报错文案（与 `制造.连接` 同口径）。

    `bool` 单独一档——它在 Python 里是 int 的子类，不先判就会被误归成 `数`。
    """
    if 值 is None:
        return '空'
    if isinstance(值, bool):
        return '布尔'
    if isinstance(值, (int, float)):
        return '数'
    if isinstance(值, str):
        return '字符串'
    return '其它(%s)' % type(值).__name__


def _是数(值):
    """是否可参与大小比较。`bool` 不算——`真 > 0` 是个没有业务含义的问题。"""
    return not isinstance(值, bool) and isinstance(值, (int, float))


def _列序(行表):
    """表的列名，按各行键的出现顺序取并集（dict 保序）。"""
    列 = {}
    for 行 in 行表:
        for 名 in 行:
            列[名] = True
    return list(列)


# ═══════════════════════════════════════════════════════════════════════
# 入参校验
# ═══════════════════════════════════════════════════════════════════════

def _校验表(表):
    """表必须是「行的列表」：列表<字典<字符串,任意>>。"""
    if not isinstance(表, list):
        raise ValueError(
            '选取：表必须是「行的列表」（列表<字典<字符串,任意>>），'
            '实际收到 %s' % _类型档(表))
    for 序, 行 in enumerate(表):
        if not isinstance(行, dict):
            raise ValueError(
                '选取：表第 %d 行不是「列名→值」的字典，实际是 %s'
                % (序 + 1, _类型档(行)))
        for 名 in 行:
            if not isinstance(名, str):
                raise ValueError(
                    '选取：表第 %d 行有非字符串列名（%r），表的列名必须是字符串'
                    % (序 + 1, 名))
    return 表


def _校验列存在(行表, 列名):
    """列名必须在表里存在，而且**每一行都有**。

    这里绝不能静默返回空表——那是最恶劣的失败模式：调用方会把「列名打错了」
    读成「确实没有满足条件的行」，然后拿 0 当结论写进日报。
    """
    列集 = set(_列序(行表))
    if 列名 not in 列集:
        raise ValueError(
            '选取：表里没有列「%s」。表实际的列是：%s。'
            '本块选择报错而不是返回空表——静默返回空表会让调用方把「列名打错」'
            '误读成「确实没有满足条件的行」'
            % (列名, '、'.join(_列序(行表)) or '（无列）'))
    for 序, 行 in enumerate(行表):
        if 列名 not in 行:
            raise ValueError(
                '选取：表第 %d 行缺少列「%s」。筛选列必须每行都有，'
                '否则「不命中」和「没这一列」分不开——本块不替缺列的行编一个空值'
                % (序 + 1, 列名))


def _校验比较符(比较符):
    if not isinstance(比较符, str):
        raise ValueError(
            '选取：比较符必须是字符串，实际收到 %s' % _类型档(比较符))
    if 比较符 not in _比较符清单:
        raise ValueError(
            '选取：不认识比较符「%s」。合法的只有这七个：%s'
            % (比较符, ' '.join(_比较符清单)))


def _校验比较值(比较符, 值):
    """比较值的前置校验：与单元格无关、只看调用方给了什么。

    放在行循环之前做，是为了让误用的报错**不依赖数据**：否则「表里恰好一行
    都没命中」与「参数类型给错了」会表现成同一个结果。
    """
    if 值 is None:
        raise ValueError(
            '选取：比较值不能是空。本块的空值语义是「含空值的行在任何比较符下'
            '都不命中」，所以拿空当比较值必然返回空表，这是纯粹的误用。'
            '要挑出空值行属于数据质量检查，不是选取算子的职责')
    if 比较符 in _序比较符 and not _是数(值):
        raise ValueError(
            '选取：比较符「%s」只支持数值，比较值却是 %s（%r）。'
            '本块不做字符串的字典序比较——BI 语境下「字符串的大于」几乎总是误用，'
            '日期列被载成字符串时字典序还会给出错答案'
            % (比较符, _类型档(值), 值))
    if 比较符 == '含' and not isinstance(值, str):
        raise ValueError(
            '选取：比较符「含」是子串包含，比较值必须是字符串，'
            '实际收到 %s（%r）' % (_类型档(值), 值))


# ═══════════════════════════════════════════════════════════════════════
# 主体：逐行判命中
# ═══════════════════════════════════════════════════════════════════════

def _判命中(单元, 比较符, 值, 列名, 行号):
    """单个单元格是否命中。返回 True/False，或为类型误用抛错。

    **空值优先短路**：空值行在任何比较符下都不命中，`≠` 也不命中（SQL 三值
    逻辑）。它排在类型检查之前，所以「列里有空值」本身永远不会引发报错——
    空值是数据的正常状态（`fact_orders` 未交付时就是空），不是错误。
    """
    if 单元 is None:
        return False

    if 比较符 == '=':
        # 跨类型不报错，只是判不相等。**不做类型转换**：`"20" = 20` 为假。
        return 单元 == 值
    if 比较符 == '≠':
        return 单元 != 值

    if 比较符 == '含':
        if not isinstance(单元, str):
            raise ValueError(
                '选取：比较符「含」只适用于字符串列，但列「%s」第 %d 行的值是'
                ' %s（%r）。本块选择报错而不是判不命中——静默不命中会把「这列的'
                '类型推断出了错」藏成一个少几行的结果'
                % (列名, 行号, _类型档(单元), 单元))
        return 值 in 单元

    if not _是数(单元):
        raise ValueError(
            '选取：比较符「%s」只支持数值列，但列「%s」第 %d 行的值是 %s（%r）。'
            '本块不做字典序比较——静默按码点比会给出没有业务含义的真假，'
            '报错才能当场暴露「这列不是数值」这个真问题'
            % (比较符, 列名, 行号, _类型档(单元), 单元))

    if 比较符 == '>':
        return 单元 > 值
    if 比较符 == '≥':
        return 单元 >= 值
    if 比较符 == '<':
        return 单元 < 值
    return 单元 <= 值


def 筛行(表, 列名, 比较符, 值):
    """按「列名 + 比较符 + 值」过滤行，返回命中的行组成的新表。

    参数
    ----
    表     : 行的列表（列表<字典<字符串,任意>>）
    列名   : 要筛的列名（字符串）
    比较符 : `=` `≠` `>` `≥` `<` `≤` `含` 之一
    值     : 比较值；不许是空

    返回
    ----
    行的列表，**保持原表的行序**（本块不排序）。命中的行是原行对象本身
    （行内容不被改动），输入表不被改动。

    空表短路：表为空则直接返回空表，此时不校验列名——空表在运行时没有列
    （表就是行的列表，没有独立 schema），无从判定；而空表过滤出来必然是空表，
    短路不会产出任何错数。
    """
    行表 = _校验表(表)
    if not isinstance(列名, str):
        raise ValueError(
            '选取：列名必须是字符串，实际收到 %s（%r）' % (_类型档(列名), 列名))
    _校验比较符(比较符)
    _校验比较值(比较符, 值)

    if not 行表:
        return []

    _校验列存在(行表, 列名)

    结果 = []
    for 序, 行 in enumerate(行表):
        if _判命中(行[列名], 比较符, 值, 列名, 序 + 1):
            结果.append(行)
    return 结果
