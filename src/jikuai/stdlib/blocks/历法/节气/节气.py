"""历法.节气 的 Python 背衬实现。

用中国天文年历的通用近似公式（适用 1900-2100，误差 ≤1 天）：

    日 = int(年后两位 × 0.2422 + C) − int((年后两位 − 1) ÷ 4)

`C` 是每个节气在 21 世纪的特征常数。这个公式是气象/农业口径的标准近似，
不做真太阳黄经积分——后者要天文历表，远超块生态的合理复杂度。

序号 1-24 按小寒起算（农历节气年的起点），与《月令七十二候》顺序一致。
"""

#: (节气名, 所在公历月, 21 世纪特征常数 C)
_节气表 = [
    ('小寒', 1, 5.4055), ('大寒', 1, 20.12),
    ('立春', 2, 3.87), ('雨水', 2, 18.73),
    ('惊蛰', 3, 5.63), ('春分', 3, 20.646),
    ('清明', 4, 4.81), ('谷雨', 4, 20.1),
    ('立夏', 5, 5.52), ('小满', 5, 21.04),
    ('芒种', 6, 5.678), ('夏至', 6, 21.37),
    ('小暑', 7, 7.108), ('大暑', 7, 22.83),
    ('立秋', 8, 7.5), ('处暑', 8, 23.13),
    ('白露', 9, 7.646), ('秋分', 9, 23.042),
    ('寒露', 10, 8.318), ('霜降', 10, 23.438),
    ('立冬', 11, 7.438), ('小雪', 11, 22.36),
    ('大雪', 12, 7.18), ('冬至', 12, 21.94),
]


def 气候(年, 序号):
    """返回 [节气名, 月, 日]。序号 1-24，1 为小寒。"""
    n = int(序号)
    if n < 1 or n > 24:
        raise ValueError('节气序号须在 1..24 之间，收到 %s' % 序号)
    名, 月, C = _节气表[n - 1]
    Y = int(年) % 100
    日 = int(Y * 0.2422 + C) - int((Y - 1) / 4)
    return [名, 月, 日]
