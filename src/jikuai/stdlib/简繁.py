def _build_table():
    """构建 简→繁 映射表。二字组格式在此做机械自检。"""
    table = {}
    for group in _ALL_GROUPS:
        for pair in group.split():
            if len(pair) != 2:
                raise ValueError("对照表条目必须是两个字符：%r" % (pair,))
            table[pair[0]] = pair[1]
    return table


S2T = _build_table()

# 繁→简：反转 S2T 并叠加补充表。同一繁体字若被多个简体映射到，
# 先登记者胜（S2T 迭代序即声明序），保证结果稳定可复现。
T2S = {}
for _s, _t in S2T.items():
    if _t not in T2S:
        T2S[_t] = _s
for _t, _s in _EXTRA_TO_SIMPLIFIED.items():
    T2S[_t] = _s


