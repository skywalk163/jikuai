def to_traditional(text):
    """简体 → 繁体。逐字符映射，表外字符原样保留。

    无可转换字符（纯 ASCII / 数字 / 标点）时输出与输入完全相同
    （AC-M4-04-03）。
    """
    if text is None:
        return ""
    if not isinstance(text, str):
        text = str(text)
    if not text:
        return text
    return "".join(S2T.get(ch, ch) for ch in text)


def to_simplified(text):
    """繁体 → 简体。逐字符映射，表外字符原样保留。"""
    if text is None:
        return ""
    if not isinstance(text, str):
        text = str(text)
    if not text:
        return text
    return "".join(T2S.get(ch, ch) for ch in text)


def mapping_size():
    """返回对照表规模 (简→繁 条目数, 繁→简 条目数)。供契约测试与文档引用。"""
    return (len(S2T), len(T2S))


def ambiguous_choices():
    """返回一简多繁的选定口径表（浅拷贝，防止调用方改写内部状态）。"""
    return {k: dict(v) for k, v in AMBIGUOUS_CHOICES.items()}


