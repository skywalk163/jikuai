# 与关键字/动词冲突的姓氏字（在此集合中的字不作为姓氏识别）
CONFLICTING_SURNAMES = frozenset({'空', '非', '真', '假', '长', '大', '小', '于'})

# 实际可用的单字姓氏
USABLE_SURNAMES = SINGLE_SURNAMES - CONFLICTING_SURNAMES


def is_surname(char):
    """判断单个字符是否为可用的百家姓姓氏。"""
    return char in USABLE_SURNAMES


def is_compound_surname(text):
    """判断前两个字符是否为复姓。"""
    return len(text) >= 2 and text[:2] in COMPOUND_SURNAMES
