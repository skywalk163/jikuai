# -*- coding: utf-8 -*-
"""中文.地址剖解 的 Python 背衬实现。

基于正则做中国地址四级拆分：[省, 市, 区, 街道]。
仅处理常见格式，不依赖行政区划数据库。未匹配部分用空串填充。
"""
import re

# 匹配省/自治区/直辖市
_省 = re.compile(
    r'^([\u4e00-\u9fff]{2,8}?(?:省|自治区|特别行政区))'
    r'|^(北京|上海|天津|重庆)(?:市)?'
)
# 匹配市/地区/自治州
_市 = re.compile(r'^([\u4e00-\u9fff]{2,6}?(?:市|地区|自治州|盟))')
# 匹配区/县/旗
_区 = re.compile(r'^([\u4e00-\u9fff]{2,8}?(?:区|县|旗|市))')


def 拆址(地址):
    """中国地址 → [省, 市, 区, 街道]。

    直辖市（北京/上海/天津/重庆）省、市两级同值，且统一补 `市` 后缀，
    与非直辖市的 `广东省` / `深圳市` 保持带后缀的风格一致。
    """
    省 = ''
    市 = ''
    区 = ''
    剩余 = 地址.strip()

    # 直辖市特判：省市同值，统一补「市」后缀
    直辖 = re.match(r'^(北京|上海|天津|重庆)(?:市)?', 剩余)
    if 直辖:
        省 = 直辖.group(1) + '市'
        剩余 = 剩余[直辖.end():]
        市 = 省
    else:
        m = _省.match(剩余)
        if m:
            省 = m.group(1) or m.group(2)
            剩余 = 剩余[m.end():]
        m = _市.match(剩余)
        if m:
            市 = m.group(1)
            剩余 = 剩余[m.end():]

    m = _区.match(剩余)
    if m:
        区 = m.group(1)
        剩余 = 剩余[m.end():]

    return [省, 市, 区, 剩余]
