# -*- coding: utf-8 -*-
"""中文.姓名拆分 的 Python 背衬实现。

基于常见复姓表做前缀匹配：命中则姓=前两字，否则姓=首字。
返回 [姓, 名]。
"""

_复姓 = frozenset([
    '欧阳', '司马', '上官', '诸葛', '皇甫', '令狐', '公孙', '宇文',
    '长孙', '慕容', '南宫', '东方', '西门', '百里', '端木', '独孤',
    '轩辕', '司徒', '尉迟', '澹台', '赫连', '夏侯',
])


def 析名(全称):
    """中文姓名 → [姓, 名]。基于复姓表做前缀匹配。"""
    if len(全称) >= 3 and 全称[:2] in _复姓:
        return [全称[:2], 全称[2:]]
    if len(全称) >= 2:
        return [全称[0], 全称[1:]]
    return [全称, '']
