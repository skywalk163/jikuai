# -*- coding: utf-8 -*-
"""中文.简称 的 Python 背衬实现。

基于常见映射表做「全称→简称」查表，未命中则截前两字作简称。
扩展方式：往 _映射 字典加条目即可。
"""

_映射 = {
    '中华人民共和国': '中国',
    '中国共产党': '中共',
    '人民代表大会': '人大',
    '政治协商会议': '政协',
    '中国人民解放军': '解放军',
    '中央电视台': '央视',
    '北京大学': '北大',
    '清华大学': '清华',
    '复旦大学': '复旦',
    '浙江大学': '浙大',
    '上海交通大学': '上交',
    '中国科学院': '中科院',
    '中国工程院': '工程院',
    '信息技术': 'IT',
    '人工智能': 'AI',
    '物联网': 'IoT',
}


def 缩名(全称):
    """全称→简称。命中映射表返回简称，否则截取前两字。"""
    if 全称 in _映射:
        return _映射[全称]
    # 回退策略：前两字
    return 全称[:2] if len(全称) > 2 else 全称
