"""历法.日序 的 Python 背衬实现（ADR-16 §3.3 混合模块）。

绝对日序 = 从公历 0001-01-01 起算的天数（等价 `datetime.date.toordinal`）。
纯 .jk 实现要自己累加年月天数并处理闰年，几十行且容易在世纪闰年上出错；
`datetime` 是标准库，不破坏零运行时依赖，所以下沉到背衬。

有了绝对日序，日期相减、加减天数、算周岁全都退化成整数运算——这就是
把它单独做成一个块的理由。
"""

from datetime import date


def 序日(年, 月, 日):
    """返回该公历日期的绝对日序（0001-01-01 为第 1 天）。"""
    return date(int(年), int(月), int(日)).toordinal()
