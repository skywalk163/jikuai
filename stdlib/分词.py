_ALL_RAW = (
    _RAW_PLACE, _RAW_TECH, _RAW_LANG, _RAW_LIFE,
    _RAW_ECON, _RAW_VERB, _RAW_ABSTRACT,
)


def _build_dictionary():
    """构建词典 frozenset。机械自检：长度 >= 2 且全为汉字。

    单字词一律剔除（由兜底策略 B3 处理），非汉字条目剔除
    （ASCII 由兜底策略 B2 处理）。
    """
    words = set()
    for block in _ALL_RAW:
        for token in block.split():
            if len(token) < 2:
                continue
            if not all("\u4e00" <= ch <= "\u9fff" for ch in token):
                continue
            words.add(token)
    return frozenset(words)


#: 词典。模块级不可变常量，运行期只读（G12 前提）。
WORDS = _build_dictionary()

#: 词典中最长条目的长度。FMM 的窗口上界。
MAX_WORD_LEN = max((len(w) for w in WORDS), default=0)


# ---------------------------------------------------------------------------
# 内部字符判定（纯函数）
# ---------------------------------------------------------------------------

def _is_space(ch):
    """空白字符（B1）。"""
    return ch in " \t\r\n\u3000\v\f"


def _is_ascii_alnum(ch):
    """半角字母或数字（B2）。"""
    return ("0" <= ch <= "9") or ("a" <= ch <= "z") or ("A" <= ch <= "Z")


# ---------------------------------------------------------------------------
# 公共 API
# ---------------------------------------------------------------------------

def segment(text):
    """正向最大匹配分词。返回**新建**的词项 list。

    纯函数：只读模块级常量 WORDS / MAX_WORD_LEN，不写任何外部状态。
    """
    if text is None:
        return []
    if not isinstance(text, str):
        text = str(text)
    if not text:
        return []

    result = []
    i = 0
    n = len(text)
    max_len = MAX_WORD_LEN
    words = WORDS
    while i < n:
        # --- FMM 主路径：长词优先 ---
        window = max_len if n - i > max_len else n - i
        hit = 0
        while window >= 2:
            if text[i:i + window] in words:
                hit = window
                break
            window -= 1
        if hit:
            result.append(text[i:i + hit])
            i += hit
            continue

        ch = text[i]
        # --- B1 空白：吞掉但不产出 ---
        if _is_space(ch):
            i += 1
            continue
        # --- B2 半角字母数字：整段作为一个词项 ---
        if _is_ascii_alnum(ch):
            j = i + 1
            while j < n and _is_ascii_alnum(text[j]):
                j += 1
            result.append(text[i:j])
            i = j
            continue
        # --- B3 其余（汉字/标点/符号）：单字成词 ---
        result.append(ch)
        i += 1
    return result


def dictionary_size():
    """返回内置词典条数。"""
    return len(WORDS)


def max_word_length():
    """返回词典最长条目长度（FMM 窗口上界）。"""
    return MAX_WORD_LEN


def all_words():
    """返回词典集合（frozenset，不可变，调用方无法污染内部状态）。"""
    return WORDS


# ---------------------------------------------------------------------------
# 极快侧门面名（由加载器注入 分词.jk 的模块环境，再经 `导出` 对外可见）
# ---------------------------------------------------------------------------

def 分词(文本):
    """把中文文本切分成词序列（列表）。空输入返回空列表。"""
    return segment(文本)