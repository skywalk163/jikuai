def is_idiom(word):
    """判断是否为库内成语。非字符串/空输入返回 False，不抛错。"""
    if not isinstance(word, str):
        return False
    word = word.strip()
    if not word:
        return False
    return word in IDIOM_SET


def explain(word):
    """返回成语释义；不在库内返回 None（极快侧显示为「空」）。"""
    if not isinstance(word, str):
        return None
    word = word.strip()
    if not word:
        return None
    return IDIOMS.get(word)


