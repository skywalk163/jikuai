"""极快语言标准库 — 成语断言（内部 Python 实现）。

本文件是 `成语.jk` 的内部实现（ADR-16 §3.3 混合模块）。`.jk` 是唯一对外
门面，本文件不参与模块名解析，只由加载器在加载 `成语.jk` 时隔离导入。

设计取舍
========
1. **零依赖**：成语库以字面量形式内置在本文件里，不读外部数据文件、不依赖
   任何 pip 包。代价是文件较大，收益是分发简单、无 IO、无路径问题。
2. **性能**：模块导入时一次性构建 `dict`（成语→释义）与 `frozenset`
   （成语集合），查找为 O(1) 哈希查表。
3. **不可变**：对外暴露的集合是 `frozenset`，映射是模块级 `dict` 但公共
   API 从不写入；`成语释义` 只读取。故本模块调用无副作用、天然幂等。
4. **规模口径**：内置常用成语 300+ 条（实际数字见 `库规模()`），只覆盖
   四字成语，不含谚语、歇后语、俗语。文档声明版本与规模。

数据格式
========
`_RAW_*` 为多行字符串，每行 `成语|释义`。选此格式的理由：
  1. 一眼可读，便于人工审校与后续增补
  2. 可用「恰好一个竖线 + 成语非空 + 释义非空」做机械自检（见 _build_table）
"""

