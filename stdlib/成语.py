def _build_table():
    """把 `_RAW_*` 解析为 {成语: 释义}。

    机械自检（只做剔除，不抛错，避免一条脏数据把整个模块打死）：
    - 必须恰好一个竖线分隔
    - 成语与释义都非空
    - 成语必须全为汉字（U+4E00–U+9FFF），长度 3–8（主体是四字，容忍少量变体）
    重复条目按「先声明者胜」，保证结果稳定可复现。
    """
    table = {}
    for block in _ALL_RAW:
        for line in block.splitlines():
            line = line.strip()
            if not line:
                continue
            if line.count("|") != 1:
                continue
            word, meaning = line.split("|", 1)
            word, meaning = word.strip(), meaning.strip()
            if not word or not meaning:
                continue
            if not (3 <= len(word) <= 8):
                continue
            if not all("\u4e00" <= ch <= "\u9fff" for ch in word):
                continue
            if word in table:
                continue
            table[word] = meaning
    return table


#: 成语 → 释义。模块级常量，公共 API 只读不写。
IDIOMS = _build_table()

#: 成语集合。frozenset 保证不可变 + O(1) 成员判定。
IDIOM_SET = frozenset(IDIOMS)


# ---------------------------------------------------------------------------
# 公共 API（英文别名，供 Python 侧单测直接调用）
