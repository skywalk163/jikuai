import pytest

_REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_GLUE = os.path.join(_REPO, 'tools', 'ai-bridge', 'glue.py')


def _load_glue():
    spec = importlib.util.spec_from_file_location('_glue_w43', _GLUE)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


glue = _load_glue()


