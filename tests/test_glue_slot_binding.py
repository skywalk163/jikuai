def test_同变量不在同步骤内复用_留空而非硬塞(图):
    """只给一个 `数` 常量，报销单 7 个 `数` 槽不许全填同一个变量。

    这是 W42 归因里的 D 类缺陷：旧实现会把 `赵甲` 塞进全部 7 个同型槽，
    生成「月薪 = 生年 = 生月 = 同一个数」的荒谬代码且不报警。
    """
    共享 = [{'名': '赵明细', '值': '列 1 2'}, {'名': '赵甲', '值': '7'}]
    steps = [{'块': '报销单', '领域': '财务', '导出名': '报单'}]
    实参, 未匹配, _拒绝 = 图.plan(steps, 共享)
    # 整步推不齐 → None，且未匹配里必须点名剩下的槽
    assert 实参[0] is None
    assert len(未匹配) >= 6
    理由 = [r for _步, _槽, r in 未匹配]
    assert any('同型静默复用' in r for r in 理由)


def test_槽名匹配不上时不乱填(图):
    """常量名与槽名毫无字面关系时，不许把随便一个数硬塞进 7 个槽。"""
    共享 = [{'名': '赵明细', '值': '列 1 2'},
            {'名': '赵甲', '值': '1'}, {'名': '赵乙', '值': '2'}]
    steps = [{'块': '报销单', '领域': '财务', '导出名': '报单'}]
    实参, 未匹配, _拒绝 = 图.plan(steps, 共享)
    assert 实参[0] is None            # 槽多于可用常量 → 留空
    assert 未匹配                      # 且明确报出哪些槽没填上


def test_手写参数仍被尊重且计入已用(图):
    """方案手写的实参优先，且要计入『本步已用』防后续槽复用它。"""
    共享 = [{'名': '赵明细', '值': '列 1 2'}, {'名': '赵甲', '值': '7'}]
    steps = [{'块': '报销单', '领域': '财务', '导出名': '报单',
              '参数': ['赵明细', '赵甲']}]
    实参, 未匹配, _拒绝 = 图.plan(steps, 共享)
    assert 实参[0] is None            # 手写只给了 2 个，其余 6 槽无常量可用
    # 赵甲 已被手写位消费，不许再出现在自动填的位置
    assert 未匹配


def test_单候选场景零回归(图):
    """池里只有一个类型兼容变量时行为不变（线性链路不受 ADR-30 影响）。"""
    共享 = [{'名': '赵料', '值': '列 3 1 2'}]
    steps = [{'块': '升序', '领域': '数据', '导出名': '顺排', '参数': ['赵料']},
             {'块': '求和', '领域': '数据', '导出名': '汇总'}]
    实参, 未匹配, _拒绝 = 图.plan(steps, 共享)
    assert 未匹配 == []
    assert 实参[1] == ['赵果1']


def test_类型冲突仍给可读拒绝理由(图):
    """元组不喂列表的既有硬门槛不因 ADR-30 而松动。"""
    steps = [{'块': '批量统计', '领域': '数据', '导出名': '统览', '参数': ['赵料']},
             {'块': '升序', '领域': '数据', '导出名': '顺排'}]
    实参, _未匹配, 拒绝 = 图.plan(steps)
    assert 实参[1] is None
    assert any('人工拆包' in r for r in 拒绝)
