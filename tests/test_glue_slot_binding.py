# 2. match_slot_name 三级递进
# ---------------------------------------------------------------------------

def test_精确匹配_剥前缀后完全相等():
    命中, 置信 = glue.match_slot_name('月薪', ['赵明细', '赵月薪', '赵年'])
    assert (命中, 置信) == ('赵月薪', 1.0)


def test_精确匹配区分生年与今年():
    候选 = ['赵生年', '赵今年', '赵生月']
    assert glue.match_slot_name('生年', 候选)[0] == '赵生年'
    assert glue.match_slot_name('今年', 候选)[0] == '赵今年'


def test_后缀匹配():
    # 形参「年」：无精确项（生年/今年 都不等于 年），退到后缀级仍有 2 个 → 歧义留空
    命中, 置信 = glue.match_slot_name('年', ['赵生年', '赵今年'])
    assert 命中 is None and 置信 == 0.0
    # 只有一个后缀命中时才落地
    命中, 置信 = glue.match_slot_name('年', ['赵生年', '赵月'])
    assert (命中, 置信) == ('赵生年', 0.8)


def test_包含匹配():
    # 「率」不在「年利率表」末尾 → 落到第 3 级包含匹配（0.6）
    命中, 置信 = glue.match_slot_name('率', ['赵年利率表', '赵额'])
    assert (命中, 置信) == ('赵年利率表', 0.6)


def test_多项同级命中即歧义_返回留空():
    命中, 置信 = glue.match_slot_name('月', ['赵月', '赵月'])
    assert 命中 is None and 置信 == 0.0


def test_无候选或无名字_返回留空():
    assert glue.match_slot_name('月薪', []) == (None, 0.0)
    assert glue.match_slot_name('', ['赵月薪']) == (None, 0.0)


def test_完全不匹配_返回留空():
    命中, 置信 = glue.match_slot_name('月薪', ['赵料', '赵组'])
    assert 命中 is None and 置信 == 0.0


