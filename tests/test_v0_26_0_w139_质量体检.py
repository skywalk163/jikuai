@pytest.fixture(scope="module")
def 外键清单():
    """从 `schema_relationships.csv` 现读 11 条 FK，**不手抄**。

    返回 `[(子表, 子列, 父表, 父列), ...]`。注意方向：CSV 里 `source_*` 是
    「1」那一侧（维表/父表），`target_*` 是「N」那一侧（事实表/子表），
    **外键列长在 target 上**。3 条 `业务关联`（复合键、`a+b` 写法）不是外键，
    按 ADR-40 §4 的口径排除。
    """
    关系 = 读表(str(数据集 / "schema_relationships.csv"))
    清单 = [
        (条["target_table"], 条["target_key"], 条["source_table"], 条["source_key"])
        for 条 in 关系
        if 条["relationship_type"] in ("1:N", "1:1")
    ]
    assert len(清单) == 11, (
        "schema_relationships.csv 的 FK 条数应为 11（11 条 FK + 3 条业务关联），"
        "实际 %d 条——数据集或本测试的口径有一方漂了" % len(清单)
    )
    return 清单


def _按子表归组(外键清单, 八表):
    """把 11 条 FK 按子表归组，折成 `体检` 的 `外键检查` 入参形状。"""
    归组 = {}
    for 子表, 子列, 父表, 父列 in 外键清单:
        归组.setdefault(子表, []).append(
            {"本列": 子列, "目标表": 八表[父表], "目标列": 父列})
    return 归组


