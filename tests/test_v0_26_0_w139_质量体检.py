# 3. 11 条 FK 孤儿行数与归档进 ADR-40 §4.5 的值一致
# ---------------------------------------------------------------------------

def test_十一条外键零孤儿(外键清单, 八表):
    """ADR-40 §4.5 归档值：11 条 FK 逐条孤儿行数**全为 0**。

    逐条单独跑（而不是按表批量跑），失败时报错文案能直接指到是哪一条关系。
    """
    实测 = []
    for 子表, 子列, 父表, 父列 in 外键清单:
        项 = [{"本列": 子列, "目标表": 八表[父表], "目标列": 父列}]
        _行数, _空值, _重复, 外键孤儿行数 = 体检(八表[子表], [], 项)
        实测.append(("%s.%s → %s.%s" % (子表, 子列, 父表, 父列),
                     外键孤儿行数[子列]))

    非零 = [(标签, 数) for 标签, 数 in 实测 if 数 != 0]
    assert not 非零, (
        "外键孤儿行数与 ADR-40 §4.5 归档的全 0 不符：%s。"
        "按 W139 DoD，不为 0 要写进 ADR-40 §4 而不是在这里兜掉" % 非零
    )
    assert len(实测) == 11


def test_外键结果按本表列名索引且逐条独立(外键清单, 八表):
    """按表批量跑与逐条单独跑必须给出同一组数（结果键是本表列名）。

    批量跑省一遍父表扫描，但如果实现里把多条外键的值集混到一起，批量与逐条
    就会分叉——这条专门钉住那种混淆。
    """
    归组 = _按子表归组(外键清单, 八表)
    for 子表, 项列 in 归组.items():
        _行数, _空值, _重复, 批量 = 体检(八表[子表], [], 项列)
        for 项 in 项列:
            _行数二, _空值二, _重复二, 单条 = 体检(八表[子表], [], [项])
            assert 单条[项["本列"]] == 批量[项["本列"]]


