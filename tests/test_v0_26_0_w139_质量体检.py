def test_八张表全部跑通(八表, 外键清单):
    """8 张表 × （行数 + 空值 + 主键 + 该表全部外键）一次跑通，不抛异常。

    这是 W139 DoD 的「质量体检在 8 张表上跑通」那条，顺手把 §4 冻结的行数
    也钉住（体检的第 0 项就是行数）。
    """
    归组 = _按子表归组(外键清单, 八表)
    for 名, 表 in 八表.items():
        行数, 空值列与计数, 主键重复数, 外键孤儿行数 = 体检(
            表, 主键表[名], 归组.get(名, []))

        assert 行数 == 行数表[名], "%s 行数与 ADR-40 §4 不符" % 名
        assert isinstance(空值列与计数, dict)
        assert isinstance(主键重复数, int)
        assert len(外键孤儿行数) == len(归组.get(名, [])), (
            "%s 的外键结果条数应与传入的外键检查条数一致" % 名)


