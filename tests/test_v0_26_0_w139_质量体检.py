def test_fact_orders_两列空值如实报出(八表):
    """ADR-40 §4.3：`actual_delivery_date` / `delay_days` 各 57 个空值。

    这两列必须**恰好**是有空值的全部列——多一列说明数据集变了，少一列说明
    空值被谁兜掉了（把「未交付」填成 0 天延期正是 §4.3 明令禁止的那种污染）。
    """
    _行数, 空值列与计数, _重复, _孤儿 = 体检(
        八表["fact_orders"], 主键表["fact_orders"], [])

    assert 空值列与计数 == 空值基线["fact_orders"]
    assert 空值列与计数["actual_delivery_date"] == 57
    assert 空值列与计数["delay_days"] == 57
    assert sum(空值列与计数.values()) == 114, "§4.3 冻结的空值单元格总数是 114"


def test_其余七张表零空值(八表):
    """§4.3 的另一半：除 `fact_orders` 外七张表零空值，空字典即零空值。"""
    for 名, 表 in 八表.items():
        if 名 in 空值基线:
            continue
        _行数, 空值列与计数, _重复, _孤儿 = 体检(表, 主键表[名], [])
        assert 空值列与计数 == {}, "%s 出现了 §4.3 没记录的空值：%s" % (名, 空值列与计数)


def test_零算合法值不算空值(八表):
    """`0` 不是空值——`fact_orders.delay_days` 同一列里既有 0 也有 `空`。

    实测：977 行 `delay_days == 0`（按期交付，延期 0 天），57 行是 `空`（未交付）。
    这一列是 ADR-40 §4.3 那条纪律的活样本：把「未交付」当 0 天延期会让延期统计
    的分母凭空多出 57 行，而运行期不报错。本块必须只把那 57 个算空值。
    """
    订单 = 八表["fact_orders"]
    零延期行数 = sum(
        1 for 行 in 订单
        if 行["delay_days"] == 0 and not isinstance(行["delay_days"], bool))
    assert 零延期行数 == 977, "delay_days 的 0 值行数变了（数据集换了？）"

    _行数, 空值列与计数, _重复, _孤儿 = 体检(订单, [], [])
    assert 空值列与计数["delay_days"] == 57, (
        "delay_days 有 977 个 0 与 57 个空，只有那 57 个算空值")

    # 反向：downtime_minutes 有 128 个 0、零个空 → 不该出现在空值结果里
    实绩 = 八表["fact_production_actual"]
    零停线行数 = sum(1 for 行 in 实绩 if 行["downtime_minutes"] == 0)
    assert 零停线行数 == 128
    _行数二, 空值二, _重复二, _孤儿二 = 体检(实绩, [], [])
    assert "downtime_minutes" not in 空值二


