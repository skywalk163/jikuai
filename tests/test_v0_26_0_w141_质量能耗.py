# 预置异常：L002 2026-06-10~06-24 单车电耗升高（G22 第 1 条的 5 个异常之一）
# ---------------------------------------------------------------------------

def test_L002单车电耗异常窗口能看出升高(表组):
    能耗 = 表组["fact_energy_usage"]
    产量 = 表组["fact_production_actual"]
    L002 = [行 for 行 in 能耗 if 行["line_id"] == "L002"]
    窗内 = _截期(L002, "usage_date", "2026-06-10", "2026-06-24")
    窗内键 = {行["energy_id"] for 行 in 窗内}
    六月L002 = _截期(L002, "usage_date", "2026-06-01", "2026-06-30")
    六月窗外 = [行 for 行 in 六月L002 if 行["energy_id"] not in 窗内键]

    窗内值 = 车耗现(窗内, ["line_id"])[0]["单车电耗均值"]
    窗外值 = 车耗现(六月窗外, ["line_id"])[0]["单车电耗均值"]
    assert round(窗内值, 2) == 191.10
    assert round(窗外值, 2) == 150.20
    assert 窗内值 > 窗外值 * 1.2, "窗口内单车电耗应显著高于窗口外（实测 +27%）"

    # 重算口径同样看得出升高（交叉校验）
    窗内重算 = 车耗算(窗内, 产量, ["line_id"])[0]["单车电耗"]
    窗外重算 = 车耗算(六月窗外, 产量, ["line_id"])[0]["单车电耗"]
    assert 窗内重算 > 窗外重算 * 1.2


