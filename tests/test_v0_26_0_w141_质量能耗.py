# 单车电耗两口径：逐行（四键）等值复核 —— 独立复核 W138 结论
# ---------------------------------------------------------------------------

def test_单车电耗两口径逐行等值(表组):
    """按 energy_id 一行一组，现列均值 == 重算，独立复核 W138 的等值结论。

    预期（W138 归档 ADR-40 §5.2）：2896/2896 行零漏配，最大绝对差 0.005（现成列
    两位小数舍入），最大相对差 ~5.4e-5。若本断言红，说明等值结论被推翻，是重大
    发现——届时 CI 会当场拦下。
    """
    能耗 = 表组["fact_energy_usage"]
    现 = 车耗现(能耗, ["energy_id"])
    算 = {行["energy_id"]: 行 for 行 in 车耗算(能耗, 表组["fact_production_actual"], ["energy_id"])}
    assert len(现) == 2896

    最大绝对 = 0.0
    最大相对 = 0.0
    漏配 = 0
    for 行 in 现:
        对 = 算[行["energy_id"]]
        if 对["单车电耗"] is None:
            漏配 += 1
            continue
        d = abs(行["单车电耗均值"] - 对["单车电耗"])
        最大绝对 = max(最大绝对, d)
        最大相对 = max(最大相对, d / abs(对["单车电耗"]))
    assert 漏配 == 0, "四键关联应零漏配（ADR-40 §5.2）"
    assert 最大绝对 <= 0.0051, "最大绝对差应 ≈0.005（现成列两位小数舍入）: %.6f" % 最大绝对
    assert 最大相对 < 6e-5, "最大相对差应 ~5.4e-5: %.3g" % 最大相对


def test_单车电耗按产线聚合两口径是口径差非等值(表组):
    """逐行等值不等于聚合等值：按产线聚合时，记录等权 vs 产量加权口径本就不同。

    这条专门防「把逐行等值误读成任意维度都等值」——按 line_id 聚合两口径会有
    可见差（实测 L003 最大约 0.61 kWh/台），是口径差本身，不是 bug。
    """
    能耗 = 表组["fact_energy_usage"]
    现 = {行["line_id"]: 行 for 行 in 车耗现(能耗, ["line_id"])}
    算 = {行["line_id"]: 行 for 行 in 车耗算(能耗, 表组["fact_production_actual"], ["line_id"])}
    最大聚合差 = max(abs(现[k]["单车电耗均值"] - 算[k]["单车电耗"]) for k in 现)
    assert 最大聚合差 > 0.05, "聚合层两口径应有可见差（记录等权≠产量加权）: %.4f" % 最大聚合差


