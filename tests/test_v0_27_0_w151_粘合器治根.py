def _表载入步():
    """`表载入.读表` 只有一个 `字符串` 入参 `路径`。"""
    return [{'块': '表载入', '领域': '制造', '导出名': '读表'}]


def test_多个共享常量竞争同一槽被拒而不是按顺序硬塞():
    """Q_PUB_001 的真实形态：5 个字符串常量，`表载入.路径` 该拒而不是绑 `赵产量列`。"""
    共享 = [{'名': n, '值': 'x'} for n in
            ('赵实绩路', '赵产日列', '赵六月始', '赵六月末', '赵产量列')]
    方案, 未匹配, 拒绝 = glue.TypeGraph().plan(_表载入步(), 共享)
    assert 方案 == [None], ('应拒绝硬塞而不是绑某个常量', 方案)
    assert 未匹配 and 未匹配[0][1] == '路径'
    assert any('共享常量' in r and '不是证据' in r for r in 拒绝), 拒绝
    # 拒绝理由必须可操作：点名 5 个候选 + 指出该显式写参数或改名
    assert any('赵产量列' in r and '显式写 参数' in r for r in 拒绝), 拒绝


def test_同型共享常量即使都声明字符串也拒绝():
    """**本轮核心断言**：判据是「是不是共享常量」，不是「有没有声明类型」。
    5 个常量全声明 `字符串`（合法且正确的类型），照旧该拒——书写顺序不是证据。"""
