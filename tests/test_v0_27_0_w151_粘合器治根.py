def test_步骤产出候选仍走最近产出优先():
    """两步都产出 `列表<数>`，第三步要 `列表<数>`：候选是两个**步骤产出**（非共享
    常量），recency 有语义 → 取最近的 `赵果2`，不拒绝。这是 L13 类既有链式的保命支。"""
    步骤 = [
        {'块': '分组', '领域': '数据', '导出名': '聚簇',
         '参数': ['赵料', '赵每组']},          # 产出 列表<列表<数>>
        {'块': '扁平', '领域': '数据', '导出名': '摊平'},   # 吃 列表<列表<数>> 产 列表<数>
        {'块': '求和', '领域': '数据', '导出名': '汇总'},   # 吃 列表<数>
    ]
    共享 = [{'名': '赵料', '值': '列 1 2 3', '类型': '列表'},
            {'名': '赵每组', '值': '2', '类型': '数'}]
    方案, 未匹配, 拒绝 = glue.TypeGraph().plan(步骤, 共享)
    # 末步 求和 的入参应链到最近的产出 赵果2（扁平的产出），不该被拒
    assert 方案[2] is not None, ('步骤产出间 recency 不应被 W152 波及', 未匹配, 拒绝)
    assert 方案[2] == ['赵果2'], 方案[2]


