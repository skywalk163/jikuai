def test_验名_目录名与导出名都是词法原子():
    from jikuai.pkg.blocks import (check_export_atomicity,
                                   check_module_segment_atomicity)
    行, 词 = check_module_segment_atomicity("窗间对比")
    assert 行 and len(词) == 1, ("目录名会成为点分路径段，非原子就 ParseError", 词)
    行, 词 = check_module_segment_atomicity("基线偏离")
    assert 行 and len(词) == 1, 词
    for 导出 in ("窗比", "基偏"):
        行, 词 = check_export_atomicity(导出)
        assert 行 and len(词) == 1, (导出, 词)


def test_验名_导出名全局唯一():
    索引 = json.loads((块根.parent / "索引.json").read_text(encoding="utf-8"))
    条目 = 索引["块"] if isinstance(索引, dict) and "块" in 索引 else 索引
    计 = {}
    for 条 in 条目:
        for 名 in 条.get("导出", []):
            计[名] = 计.get(名, 0) + 1
    for 导出 in ("窗比", "基偏"):
        assert 计.get(导出) == 1, ("导出名必须全局唯一（G13）", 导出, 计.get(导出))


def test_双块互相点名():
    """ADR-40 §5.4 / G22 断言 3：两侧口径必须互相点名。"""
    assert "基线偏离" in _块描述("窗间对比")
    assert "窗间对比" in _块描述("基线偏离")


