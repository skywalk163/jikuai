def test_某侧维度键重复即报错并点名汇总块():
    坏 = _表(("L001", 1.0), ("L001", 2.0))
    with pytest.raises(ValueError) as e:
        窗比(坏, _表(("L001", 3.0)), 维度, "均值")
    文 = str(e.value)
    assert "不汇总" in 文
    assert "分组汇总" in 文, "报错要告诉人该先用哪个块，不能只说「重复」"


def test_维度列在某行不存在即报错():
    with pytest.raises(ValueError) as e:
        窗比([{"均值": 1.0}], _表(("L001", 2.0)), 维度, "均值")
    assert "line_id" in str(e.value)


def test_两表列名不一致即报错不静默当缺键():
    """比期表把维度列写成了 `line`——按列名对齐，对不上就得报错。"""
    with pytest.raises(ValueError) as e:
        窗比(_表(("L001", 1.0)), [{"line": "L001", "均值": 2.0}], 维度, "均值")
    assert "列名必须一致" in str(e.value)


def test_度量列在某行不存在即报错():
    with pytest.raises(ValueError) as e:
        窗比([{"line_id": "L001"}], _表(("L001", 2.0)), 维度, "均值")
    assert "均值" in str(e.value)


def test_度量列是非空非数值即报错():
    with pytest.raises(ValueError):
        窗比([{"line_id": "L001", "均值": "高"}], _表(("L001", 2.0)), 维度, "均值")


def test_布尔度量值被拒():
    """True + True = 2 在业务度量里没有意义（同 分组汇总._数值）。"""
    with pytest.raises(ValueError):
        窗比([{"line_id": "L001", "均值": True}], _表(("L001", 2.0)), 维度, "均值")


def test_维度列为空即报错():
    with pytest.raises(ValueError):
        窗比(_表(("L001", 1.0)), _表(("L001", 2.0)), [], "均值")


def test_维度列与固定输出列撞名即报错():
    with pytest.raises(ValueError) as e:
        窗比([{"差值": "x", "均值": 1.0}], [{"差值": "x", "均值": 2.0}],
             ["差值"], "均值")
    assert "撞名" in str(e.value)


def test_度量列同时是维度列即报错():
    with pytest.raises(ValueError):
        窗比(_表(("L001", 1.0)), _表(("L001", 2.0)), 维度, "line_id")


def test_表不是列表即报错():
    with pytest.raises(ValueError):
        窗比("不是表", _表(("L001", 1.0)), 维度, "均值")


