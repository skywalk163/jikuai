# -*- coding: utf-8 -*-
"""v0.27.0 W154 · 制造.窗间对比（导出 `窗比`）的 pytest 断言。

`测试.jk` 在极快侧覆盖语义边界；这里做 `.jk` 里做不动的四件事：

1. **手算核对**（不是「跑通就算对」）：最小例上的 `差值` / `变化率` 逐个写死。
2. **三种「空」分得开**：缺一窗 / 两窗齐但值为空 / 分母为 0，各一条断言。
   这三种若并成同一个 `空`，`班间对比` 记录的那条教训就白学了
   （源头是 `fact_orders.delay_days` 的 57 个空 vs 977 个 0）。
3. **两道验名**（v0.26.0 WBS 执行原则 7）：目录名 `窗间对比` 与导出名 `窗比`
   各过一次原子性检查，导出名再验一次全局唯一。v0.26.0 三个块全栽在目录名上。
4. **姊妹块互相点名**：读两份 `块.json` 的 `描述` 断言彼此被点到名
   （ADR-40 §5.4 / G22 断言 3 的双块判法），保证选块的人在候选里看得见另一口径。

零第三方依赖，只用标准库 + pytest。**不依赖 `赛题/` 数据集**（那部分在 W155 的
测试文件里，且有 skipif 兜着）。
"""

import importlib.util
import json
import pathlib

import pytest

_源 = importlib.util.find_spec("jikuai").origin
仓库根 = pathlib.Path(_源).resolve().parent.parent.parent
块根 = 仓库根 / "src" / "jikuai" / "stdlib" / "blocks" / "制造"


def _载背衬(块名):
    路径 = 块根 / 块名 / (块名 + ".py")
    规格 = importlib.util.spec_from_file_location("w154_" + 块名, 路径)
    模块 = importlib.util.module_from_spec(规格)
    规格.loader.exec_module(模块)
    return 模块


def _块描述(块名):
    return json.loads((块根 / 块名 / "块.json").read_text(encoding="utf-8"))["描述"]


_窗间对比 = _载背衬("窗间对比")
窗比 = _窗间对比.窗比

维度 = ["line_id"]


def _表(*对):
    """(line_id, 值) 若干 → 已汇总的一行一组表。"""
    return [{"line_id": 线, "均值": 值} for 线, 值 in 对]


# ---------------------------------------------------------------------------
# 一、正常两窗：差值与变化率手算核对
# ---------------------------------------------------------------------------

def test_正常两窗的差值与变化率手算对得上():
    基 = _表(("L001", 100.0), ("L002", 200.0))
    比 = _表(("L001", 110.0), ("L002", 150.0))
    出 = 窗比(基, 比, 维度, "均值")
    assert [行["line_id"] for 行 in 出] == ["L001", "L002"], "行序按维度键升序"

    assert 出[0]["对齐"] == "两窗齐"
    assert 出[0]["基期值"] == 100.0
    assert 出[0]["比期值"] == 110.0
    assert 出[0]["差值"] == pytest.approx(10.0)
    # 10 / 100 = 0.1（0-1 小数，不是 10）
    assert 出[0]["变化率"] == pytest.approx(0.1)

    assert 出[1]["差值"] == pytest.approx(-50.0)
    assert 出[1]["变化率"] == pytest.approx(-0.25)


def test_变化率是0到1小数而不是百分数():
    """单位钉死：0.2589 表示涨 25.89%。与 achievement_rate 等比率列一致。"""
    出 = 窗比(_表(("L001", 151.8007)), _表(("L001", 191.0953)), 维度, "均值")
    assert 出[0]["变化率"] == pytest.approx(0.2589, abs=1e-4)
    assert 出[0]["变化率"] < 1, "若返回 25.89 就是把单位改成了百分数"


def test_两窗都空返回空表():
    assert 窗比([], [], 维度, "均值") == []


def test_两窗键取并集():
    出 = 窗比(_表(("L001", 1.0)), _表(("L002", 2.0)), 维度, "均值")
    assert [行["line_id"] for 行 in 出] == ["L001", "L002"]


def test_多维度键组合():
    基 = [{"workshop": "总装", "shift": "白班", "均值": 10.0},
          {"workshop": "总装", "shift": "夜班", "均值": 20.0}]
    比 = [{"workshop": "总装", "shift": "白班", "均值": 12.0},
          {"workshop": "总装", "shift": "夜班", "均值": 20.0}]
    出 = 窗比(基, 比, ["workshop", "shift"], "均值")
    assert len(出) == 2
    # 行序是维度键的**码位序**：`夜`(U+591C) < `白`(U+767D)，所以夜班在前。
    # 不是业务序（白班在前才符合直觉）——本块只承诺「确定可复现」，不承诺好看。
    assert [行["shift"] for 行 in 出] == ["夜班", "白班"]
    按班 = {行["shift"]: 行 for 行 in 出}
    assert 按班["白班"]["差值"] == pytest.approx(2.0)
    assert 按班["夜班"]["差值"] == pytest.approx(0.0)
    assert 按班["夜班"]["变化率"] == pytest.approx(0.0), "0 变化率不是空——真的没变"


# ---------------------------------------------------------------------------
# 二、★ 三种「空」必须分得开（本块的核心决议）
# ---------------------------------------------------------------------------

def test_基期缺键时对齐是缺基期且差值为空不是当0():
    出 = 窗比(_表(("L001", 100.0)), _表(("L001", 110.0), ("L009", 191.0)), 维度, "均值")
    新 = [行 for 行 in 出 if 行["line_id"] == "L009"][0]
    assert 新["对齐"] == "缺基期"
    assert 新["基期值"] is None
    assert 新["比期值"] == 191.0
    assert 新["差值"] is None, "把缺的基期当 0 会算出「从 0 涨到 191」的假异常"
    assert 新["变化率"] is None


def test_比期缺键时对齐是缺比期():
    出 = 窗比(_表(("L001", 100.0), ("L008", 50.0)), _表(("L001", 110.0)), 维度, "均值")
    停 = [行 for 行 in 出 if 行["line_id"] == "L008"][0]
    assert 停["对齐"] == "缺比期"
    assert 停["基期值"] == 50.0
    assert 停["比期值"] is None
    assert 停["差值"] is None


def test_两窗齐但某侧汇总值为空与缺键靠对齐字段区分():
    """★ 与上两条的对照：这一种 `对齐` 是 `两窗齐`。

    若两种都只给一个 `空`，谁也查不出是「这条产线那一窗没有记录」还是
    「有记录但度量列全为空」（`车耗现` 对全空组就返回 `单车电耗均值=空`）。
    """
    出 = 窗比(_表(("L001", None)), _表(("L001", 110.0)), 维度, "均值")
    assert 出[0]["对齐"] == "两窗齐"
    assert 出[0]["基期值"] is None
    assert 出[0]["差值"] is None
    # 缺键那条是 `缺基期`，本条是 `两窗齐`——两种状况没有并成同一个空
    缺 = 窗比([], _表(("L001", 110.0)), 维度, "均值")
    assert 缺[0]["对齐"] == "缺基期"
    assert 缺[0]["对齐"] != 出[0]["对齐"]


def test_分母为0时变化率是空而不是inf():
    出 = 窗比(_表(("L001", 0.0)), _表(("L001", 110.0)), 维度, "均值")
    assert 出[0]["对齐"] == "两窗齐"
    assert 出[0]["差值"] == pytest.approx(110.0), "差值照算——0 是真的 0"
    assert 出[0]["变化率"] is None, "inf 会被下游排序顶成榜首假异常"


def test_基期为负时变化率为空但差值照算():
    出 = 窗比(_表(("L001", -10.0)), _表(("L001", -5.0)), 维度, "均值")
    assert 出[0]["差值"] == pytest.approx(5.0)
    assert 出[0]["变化率"] is None, "负分母下比率符号会翻，把恶化读成好转"


