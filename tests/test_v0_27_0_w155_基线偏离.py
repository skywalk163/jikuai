def test_升幅手算对得上():
    观 = _表(("L001", 125.0))
    基 = _表(("L001", 100.0))
    出 = 基偏(观, 基, 维度, "均值")
    assert 出[0]["对齐"] == "两窗齐"
    assert 出[0]["基线值"] == 100.0
    assert 出[0]["观察值"] == 125.0
    assert 出[0]["偏离"] == pytest.approx(25.0)
    assert 出[0]["升幅"] == pytest.approx(0.25)


def test_升幅是0到1小数不是百分数():
    出 = 基偏(_表(("L002", 191.0953)), _表(("L002", 151.8007)), 维度, "均值")
    assert 出[0]["升幅"] == pytest.approx(0.2589, abs=1e-4)
    assert 出[0]["升幅"] < 1, "若返回 25.89 就是把单位改成了百分数（口径变更须先改 ADR）"


def test_口径不对称_调换两表不是简单变符号():
    """★ 分母换了，所以调换观察表与基线表得到的不是 −升幅。

    这条是 `基线偏离` 与对称的 `窗间对比` 的本质差别，也是「表参数不受类型图守护、
    方案里必须显式写 参数」的理由：接反了不会报错，只会给错数。
    """
    正 = 基偏(_表(("L001", 125.0)), _表(("L001", 100.0)), 维度, "均值")[0]["升幅"]
    反 = 基偏(_表(("L001", 100.0)), _表(("L001", 125.0)), 维度, "均值")[0]["升幅"]
    assert 正 == pytest.approx(0.25)
    assert 反 == pytest.approx(-0.2)
    assert 反 != pytest.approx(-正), "若相等说明实现把分母写成了固定的一侧"


def test_两窗都空返回空表():
    assert 基偏([], [], 维度, "均值") == []


def test_行序按维度键升序且取并集():
    出 = 基偏(_表(("L003", 1.0), ("L001", 1.0)), _表(("L002", 1.0)), 维度, "均值")
    assert [行["line_id"] for 行 in 出] == ["L001", "L002", "L003"]


