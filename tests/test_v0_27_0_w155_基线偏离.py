def test_缺观察时对齐是缺观察():
    出 = 基偏([], _表(("L008", 50.0)), 维度, "均值")
    assert 出[0]["对齐"] == "缺观察"
    assert 出[0]["观察值"] is None
    assert 出[0]["升幅"] is None


def test_两窗齐但值为空与缺键靠对齐字段区分():
    有键值空 = 基偏(_表(("L001", None)), _表(("L001", 100.0)), 维度, "均值")[0]
    缺键 = 基偏(_表(("L001", 1.0)), [], 维度, "均值")[0]
    assert 有键值空["对齐"] == "两窗齐"
    assert 缺键["对齐"] == "缺基线"
    assert 有键值空["升幅"] is None and 缺键["升幅"] is None
    assert 有键值空["对齐"] != 缺键["对齐"], "两种状况并成同一个空就查不出根因"


def test_基线为0时升幅为空而不是inf():
    出 = 基偏(_表(("L001", 100.0)), _表(("L001", 0.0)), 维度, "均值")
    assert 出[0]["偏离"] == pytest.approx(100.0), "偏离照算——0 是真的 0"
    assert 出[0]["升幅"] is None


def test_基线为负时升幅为空但偏离照算():
    出 = 基偏(_表(("L001", -5.0)), _表(("L001", -10.0)), 维度, "均值")
    assert 出[0]["偏离"] == pytest.approx(5.0)
    assert 出[0]["升幅"] is None, "负分母下比率符号会翻，把恶化读成好转"


