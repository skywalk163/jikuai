观察窗 = ("2026-06-10", "2026-06-24")
基线止 = "2026-06-09"


def _读能耗():
    路径 = 数据集 / "fact_energy_usage.csv"
    with 路径.open("r", encoding="utf-8-sig", newline="") as f:
        行表 = list(csv.DictReader(f))
    for 行 in 行表:
        值 = 行["energy_per_vehicle"]
        行["energy_per_vehicle"] = None if 值 in ("", None) else float(值)
    return 行表


@pytest.fixture(scope="module")
def 两窗():
    """观察窗 + 基线窗，各自过 车耗现 汇总到一行一组（一条产线一行）。

    基线 = **观察窗之前的全部日期**（`usage_date < 2026-06-10`）。本块不替调用方
    选基线窗，这里的选择与块 docstring / 块.json 描述里写的那一组数一致。
    """
    表 = _读能耗()
    观 = [行 for 行 in 表 if 观察窗[0] <= 行["usage_date"] <= 观察窗[1]]
    基 = [行 for 行 in 表 if 行["usage_date"] <= 基线止]
    return 车耗现(观, 维度), 车耗现(基, 维度)


@pytest.mark.skipif(not 数据集.is_dir(),
                    reason="赛题/chatbi/数据集/ 不存在（不进 wheel 与 sdist，ADR-40 §7）")
def test_Q_PUB_004_L002升幅约25_9百分号且遥遥领先(两窗):
    观, 基 = 两窗
    出 = 基偏(观, 基, 维度, "单车电耗均值")
    表 = {行["line_id"]: 行 for 行 in 出}
    assert len(表) == 8, "八条产线"
    assert all(行["对齐"] == "两窗齐" for 行 in 出), "两窗产线集合应完全一致"

    l002 = 表["L002"]
    assert l002["基线值"] == pytest.approx(151.8007, abs=1e-3)
    assert l002["观察值"] == pytest.approx(191.0953, abs=1e-3)
    assert l002["升幅"] == pytest.approx(0.2589, abs=1e-3)

    其余 = [行["升幅"] for 线, 行 in 表.items() if 线 != "L002"]
    assert min(其余) == pytest.approx(-0.0379, abs=1e-3)
    assert max(其余) == pytest.approx(0.0315, abs=1e-3)
    assert l002["升幅"] > 8 * max(其余), \
        "L002 的升幅要与本底噪声拉开一个量级，否则「异常」判据就站不住"

    榜 = sorted(出, key=lambda 行: -行["升幅"])
    assert 榜[0]["line_id"] == "L002", "Q_PUB_004 的答案"


@pytest.mark.skipif(not 数据集.is_dir(),
                    reason="赛题/chatbi/数据集/ 不存在（不进 wheel 与 sdist，ADR-40 §7）")
def test_绝对量榜与升幅榜结论不同这不是bug(两窗):
    """★ BACKLOG §12.3 第 5 条的最低成本缓解：把「两个榜不同」钉成断言。

    L006 平时就是耗电大户，它没有「升高」；L002 平时 151、这一段 191，
    它才是异常升高的那条。**谁若把两个榜「对齐」，那是把正确答案改错。**
    """
    观, 基 = 两窗
    横向 = sorted(观, key=lambda 行: -行["单车电耗均值"])
    assert [行["line_id"] for 行 in 横向[:3]] == ["L006", "L005", "L007"]
    assert 横向[0]["单车电耗均值"] == pytest.approx(256.5050, abs=1e-3)
    名次 = [行["line_id"] for 行 in 横向].index("L002") + 1
    assert 名次 == 4, "L002 在横向绝对量榜只排第 4"

    升幅榜 = sorted(基偏(观, 基, 维度, "单车电耗均值"),
                    key=lambda 行: -行["升幅"])
    assert 升幅榜[0]["line_id"] == "L002"
    assert 升幅榜[0]["line_id"] != 横向[0]["line_id"], \
        "两个榜的榜首本来就不同——问「最高」与问「异常升高」不是一个问题"


@pytest.mark.skipif(not 数据集.is_dir(),
                    reason="赛题/chatbi/数据集/ 不存在（不进 wheel 与 sdist，ADR-40 §7）")
def test_换基线窗数值变但结论不变(两窗):
    """本块不替调用方选基线窗——三种基线都指向 L002，但数值不同。

    这条是「基线是业务判断」的证据：把它开成参数会让人以为有个标准基线。
    """
    表 = _读能耗()
    观 = 车耗现([行 for 行 in 表
                 if 观察窗[0] <= 行["usage_date"] <= 观察窗[1]], 维度)
    for 起, 止, 期望 in (("2026-06-01", "2026-06-09", 0.2678),
                        ("2026-05-26", "2026-06-09", 0.2713)):
        基 = 车耗现([行 for 行 in 表 if 起 <= 行["usage_date"] <= 止], 维度)
        出 = 基偏(观, 基, 维度, "单车电耗均值")
        榜 = sorted(出, key=lambda 行: -行["升幅"])
        assert 榜[0]["line_id"] == "L002", (起, 止)
        assert 榜[0]["升幅"] == pytest.approx(期望, abs=1e-3), (起, 止)


