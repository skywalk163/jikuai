def _载背衬(块名):
    路径 = 块根 / 块名 / (块名 + ".py")
    规格 = importlib.util.spec_from_file_location("w155_" + 块名, 路径)
    模块 = importlib.util.module_from_spec(规格)
    规格.loader.exec_module(模块)
    return 模块


基偏 = _载背衬("基线偏离").基偏
车耗现 = _载背衬("单车电耗现成").车耗现

维度 = ["line_id"]


def _表(*对):
    return [{"line_id": 线, "均值": 值} for 线, 值 in 对]


