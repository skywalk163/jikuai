"""v0.27.0 W155 · 制造.基线偏离（导出 `基偏`）的 pytest 断言。

本文件的重心是**两条不许被后人「修正」的实测结论**：

1. **`Q_PUB_004` 的答案是 L002**：观察窗 `2026-06-10..06-24`、基线 = 该窗之前全部
   日期，按 `line_id` 对 `energy_per_vehicle` 取算术平均 →
   L002 `151.8007 → 191.0953` = **+25.89%**，其余七条全在 **−3.79% ~ +3.15%**。
2. **绝对量榜与比率榜结论不同，这不是 bug**（BACKLOG §12.3 第 5 条）：横向绝对量
   降序榜首是 L006（`256.5050`），**L002 只排第 4**。两个榜都写进断言 ——
   后人若发现两榜不一致而去「修正」其中一个，那是把正确答案改错。

自足部分（不碰数据集）覆盖：手算核对、口径不对称、三种空分得开、反例。
真实数据集部分有 skipif：`赛题/` 不进 wheel 与 sdist（ADR-40 §7）。

零第三方依赖，只用标准库 + pytest。
"""

