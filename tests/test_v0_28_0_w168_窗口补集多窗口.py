def _读能耗():
    路径 = 数据集 / "fact_energy_usage.csv"
    with 路径.open("r", encoding="utf-8-sig", newline="") as f:
        行表 = list(csv.DictReader(f))
    for 行 in 行表:
        值 = 行["energy_per_vehicle"]
        行["energy_per_vehicle"] = None if 值 in ("", None) else float(值)
    return 行表


@pytest.fixture(scope="module")
def 能耗():
    return _读能耗()


@需数据集
def test_影子实现与真jk在真实数据上逐行一致(能耗):
    两段 = [[数据集首日, 旧基线止], ["2026-06-25", 数据集末日]]
    assert 截外(能耗, "usage_date", *观察窗) == _截外(能耗, "usage_date", *观察窗)
    assert 截多(能耗, "usage_date", 两段) == _截多(能耗, "usage_date",
                                                   [tuple(段) for 段 in 两段])


@需数据集
def test_截外等于截多切前后两段_两条独立实现同一答案(能耗):
    """★ 两块互证：一个窗口的补集 = 窗前那段 ∪ 窗后那段。

    数据集只覆盖 2026-01-01..06-30 且 `usage_date` 无空值，所以这里两者应**逐行**
    相等；换个有空值的日期列就不成立了（补集不收空值、并集也不收空值，仍相等——
    真正会分叉的是数据集边界之外还有数据的情形）。
    """
    补集 = 截外(能耗, "usage_date", *观察窗)
    两段 = 截多(能耗, "usage_date", [[数据集首日, 旧基线止],
                                     ["2026-06-25", 数据集末日]])
    assert 补集 == 两段
    assert len(补集) == 2656


@需数据集
def test_窗内加补集等于全表_本列恰好无空值(能耗):
    """这一条只在「该列无空值」时成立，断言里连这个前提一起钉住。"""
    assert all(行["usage_date"] not in (None, "") for 行 in 能耗)
    assert len(截期(能耗, "usage_date", *观察窗)) == 240
    assert len(截外(能耗, "usage_date", *观察窗)) == 2656
    assert 240 + 2656 == len(能耗) == 2896


@需数据集
def test_补集比旧基线多出的正是06_25到06_30那6天(能耗):
    """DoD 的那 6 天：旧口径 2560 行 → 新口径 2656 行，多出的 96 行全在这 6 天里。"""
    旧基线 = 截期(能耗, "usage_date", 数据集首日, 旧基线止)
    新基线 = 截外(能耗, "usage_date", *观察窗)
    assert len(旧基线) == 2560
    assert len(新基线) == 2656

    旧键 = {行["energy_id"] for 行 in 旧基线}
    多出 = [行 for 行 in 新基线 if 行["energy_id"] not in 旧键]
    assert len(多出) == 96
    assert {行["usage_date"] for 行 in 多出} == {
        "2026-06-25", "2026-06-26", "2026-06-27",
        "2026-06-28", "2026-06-29", "2026-06-30"}


