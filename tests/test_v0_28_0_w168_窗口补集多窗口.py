def test_形参名全是词法原子():
    """★ W167 被 `赵维度列` 咬过一次：`列` 是动词，形参名会被 lexer 切断，
    调用处静默变成多传一个参数。所以形参名也要逐个验。
    """
    _, 导出原子 = _原子器()
    坏例, 碎片 = 导出原子("赵段列")
    assert 坏例 is False and len(碎片) >= 2, \
        "`赵段列` 应当被判非原子——这就是 W167 那个坑的最小复现"

    for 块名 in ("窗口补集", "多窗口"):
        源 = (块根 / 块名 / (块名 + ".jk")).read_text(encoding="utf-8")
        for 行 in 源.splitlines():
            行 = 行.strip()
            if not 行.startswith("函数 ") or " 接收 " not in 行:
                continue
            形参段 = 行.split(" 接收 ", 1)[1].split("：")[0]
            for 形参 in 形参段.split():
                好, 碎 = 导出原子(形参)
                assert 好 is True, (块名, 形参, 碎)
