@需数据集
def test_Q_PUB_004_新旧基线数值不同但结论同为L002(能耗):
    """**不许为了让数字好看去改 reference。**

    - 旧（W155 在册口径，`usage_date <= 06-09`）：基线 151.8007，升幅 0.258857
    - 新（`截外` 全补集，含 06-25～06-30）：  基线 151.7142，升幅 0.259574

    差 0.000717 ≈ **0.07 个百分点**。两者都以 L002 为榜首，且都与本底噪声拉开
    一个量级。所以这条记档的结论是：**缺口 2 是表达能力缺口，不是 Q_PUB_004 的
    错误来源**——补上它让「基线 = 窗外全部」这句话能直说，但没改答案。

    W155 的 `test_Q_PUB_004_L002升幅约25_9百分号且遥遥领先` 一行没动，
    它记的是旧口径那组数，本来就该与这里的新数不同。
    """
    观 = 车耗现(截期(能耗, "usage_date", *观察窗), 维度)

    旧 = 基偏(观, 车耗现(截期(能耗, "usage_date", 数据集首日, 旧基线止), 维度),
              维度, "单车电耗均值")
    新 = 基偏(观, 车耗现(截外(能耗, "usage_date", *观察窗), 维度),
              维度, "单车电耗均值")

    旧表 = {行["line_id"]: 行 for 行 in 旧}
    新表 = {行["line_id"]: 行 for 行 in 新}
    assert len(旧表) == len(新表) == 8

    assert 旧表["L002"]["基线值"] == pytest.approx(151.8007, abs=1e-3)
    assert 旧表["L002"]["升幅"] == pytest.approx(0.258857, abs=1e-5)
    assert 新表["L002"]["基线值"] == pytest.approx(151.7142, abs=1e-3)
    assert 新表["L002"]["升幅"] == pytest.approx(0.259574, abs=1e-5)

    差 = 新表["L002"]["升幅"] - 旧表["L002"]["升幅"]
    assert 差 == pytest.approx(0.000717, abs=1e-5), \
        "两种算法的差值本身就是记档对象，变了要来改这个数并写清为什么"

    for 名, 表 in (("旧", 旧表), ("新", 新表)):
        榜 = sorted(表.values(), key=lambda 行: -行["升幅"])
        assert 榜[0]["line_id"] == "L002", 名
        其余 = [行["升幅"] for 线, 行 in 表.items() if 线 != "L002"]
        assert 表["L002"]["升幅"] > 8 * max(其余), 名


