def _截外(表, 列, 起, 止):
    """闭区间之外。**空值行既不进窗口也不进补集**——空是未知，不是「在区间外」。"""
    return [行 for 行 in 表
            if 行[列] is not None and not (起 <= 行[列] <= 止)]


def _截多(表, 列, 段清单):
    """多区间并集**去重**，行序沿用原表行序（不按区间先后重排）。"""
    return [行 for 行 in 表
            if 行[列] is not None
            and any(起 <= 行[列] <= 止 for 起, 止 in 段清单)]


