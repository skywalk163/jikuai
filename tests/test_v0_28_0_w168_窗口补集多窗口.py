小表 = [
    {"d": "2026-06-09", "id": "外左"},
    {"d": "2026-06-10", "id": "端左"},
    {"d": "2026-06-17", "id": "中间"},
    {"d": "2026-06-24", "id": "端右"},
    {"d": "2026-06-25", "id": "外右"},
    {"d": None, "id": "空值"},
]


def test_截期与截外不是严格二分_空值行两边都不进():
    """★ 本轮最容易被后人「修正」的一条。

    直觉上 `截期` + `截外` 该等于全表，实际不是：小表 6 行里有 1 行日期为空，
    窗内 3 + 窗外 2 = **5 < 6**。谁把它「修好」成严格二分，就是把
    「空 = 区间外」这个错口径写进块里。
    """
    窗内 = 截期(小表, "d", *观察窗)
    窗外 = 截外(小表, "d", *观察窗)
    assert [行["id"] for 行 in 窗内] == ["端左", "中间", "端右"]
    assert [行["id"] for 行 in 窗外] == ["外左", "外右"]
    assert len(窗内) + len(窗外) == 5
    assert len(小表) == 6, "差的那一行就是空值行"


def test_全区间窗口的补集是空表而不是空值那一行():
    assert 截外(小表, "d", 数据集首日, 数据集末日) == []


def test_截多单区间与截期逐行一致():
    单 = 截多(小表, "d", [list(观察窗)])
    assert 单 == 截期(小表, "d", *观察窗)


def test_截多重叠区间去重且按原表序():
    """重叠区间同一行只收一次；把靠后的区间写在前面也不改变输出行序。

    去重这一条直接对着 §12.3 的 `邻期关联` 膨胀坑：行重复了下游汇总的绝对量
    就凭空变大，而这种错不报错。
    """
    重叠 = 截多(小表, "d", [["2026-06-09", "2026-06-17"],
                            ["2026-06-10", "2026-06-25"]])
    assert [行["id"] for 行 in 重叠] == ["外左", "端左", "中间", "端右", "外右"]

    倒序给 = 截多(小表, "d", [["2026-06-24", "2026-06-25"],
                              ["2026-06-09", "2026-06-09"]])
    assert [行["id"] for 行 in 倒序给] == ["外左", "端右", "外右"], \
        "行序应沿用原表，不按区间先后重排"


def test_截外与截多都不改原表():
    快照 = [dict(行) for 行 in 小表]
    截外(小表, "d", *观察窗)
    截多(小表, "d", [list(观察窗)])
    assert 小表 == 快照


