@需数据集
def test_R1链路实测_只有L002判上升且升幅约25_9百分号(
        读表, 截期, 车耗现, 基偏, 判势):
    """把 R1 方案的七步在 Python 侧原样重跑一遍，钉住报告里的结论。

    这条同时证明「结构比较仍有效」的反面：**绝对水平最高的不是判上升的那条**——
    L006 观察值 ≈ 256 是全场最高，但它相对自身几乎没动，判持平。
    """
    能耗 = 读表(str(数据集 / "fact_energy_usage.csv"))
    观察 = 车耗现(截期(能耗, "usage_date", "2026-06-10", "2026-06-24"), ["line_id"])
    基线 = 车耗现(截期(能耗, "usage_date", "2026-01-01", "2026-06-09"), ["line_id"])
    偏 = 基偏(观察, 基线, ["line_id"], "单车电耗均值")
    参照 = "自身基线窗 2026-01-01～2026-06-09 的单车电耗均值（同产线、口径 A）"
    果 = 判势(偏, "升幅", 参照, 0.05)

    assert len(果) == 8
    按线 = {行["line_id"]: 行 for 行 in 果}
    上升 = sorted(k for k, v in 按线.items() if v["趋势"] == "上升")
    assert 上升 == ["L002"], {k: v["趋势"] for k, v in 按线.items()}
    assert all(v["趋势"] == "持平" for k, v in 按线.items() if k != "L002")

    L002 = 按线["L002"]
    assert abs(L002["升幅"] - 0.2589) < 0.001, L002["升幅"]
    assert abs(L002["基线值"] - 151.80) < 0.01
    assert abs(L002["观察值"] - 191.10) < 0.01

    # 绝对水平榜首 ≠ 升幅榜首
    最高 = max(按线.values(), key=lambda 行: 行["观察值"])
    assert 最高["line_id"] == "L006"
    assert 最高["趋势"] == "持平"

    # 参照系在每一行，一行不落
    assert all(行["参照系"] == 参照 for 行 in 果)


@需数据集
def test_参照系换一段_升幅与判定都会变_所以它必须可见(
        读表, 截期, 车耗现, 基偏, 判势):
    """同一个观察窗、换一个基线窗，L002 的升幅就变了——这就是「参照系必须打进输出」
    的实证理由，不是文档口号。"""
    能耗 = 读表(str(数据集 / "fact_energy_usage.csv"))
    观察 = 车耗现(截期(能耗, "usage_date", "2026-06-10", "2026-06-24"), ["line_id"])

    def 升幅(起, 止):
        基线 = 车耗现(截期(能耗, "usage_date", 起, 止), ["line_id"])
        偏 = 基偏(观察, 基线, ["line_id"], "单车电耗均值")
        果 = 判势(偏, "升幅", "基线窗 %s～%s" % (起, 止), 0.05)
        return {行["line_id"]: 行 for 行 in 果}["L002"]

    甲 = 升幅("2026-01-01", "2026-06-09")
    乙 = 升幅("2026-05-01", "2026-05-31")
    assert 甲["升幅"] != 乙["升幅"]
    assert 甲["参照系"] != 乙["参照系"]
    # 两个参照系下都判上升（结论稳），但**数不同**——报告里必须写清是哪一段
    assert 甲["趋势"] == "上升" and 乙["趋势"] == "上升"


