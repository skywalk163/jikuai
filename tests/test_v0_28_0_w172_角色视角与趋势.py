@需产出
def test_三份方案放在子目录_没把十五份一二四步改脏():
    """`test_v0_27_0_w149_共享类型.py::_收集真实方案` 用 `os.listdir` **不递归**地扫
    `产出/` 与 `产出/留出/` 两层。本轮方案放 `产出/W172-角色视角/`，所以那两个历史
    数字（15 份 / 124 步）一个都不动。这条断言就是那件事的守卫。"""
    份数 = 0
    步数 = 0
    for 根 in (产出根, 产出根 / "留出"):
        if not 根.is_dir():
            continue
        for 名 in sorted(p.name for p in 根.iterdir()):
            if 名.endswith("-方案.json"):
                份数 += 1
                方案 = json.loads((根 / 名).read_text(encoding="utf-8"))
                步数 += len(方案.get("步骤") or [])
    assert 份数 == 15, 份数
    assert 步数 == 124, 步数
    # 反面：本轮三份确实在扫描范围之外
    assert all((视角根 / 名).is_file() for 名 in 三份)


