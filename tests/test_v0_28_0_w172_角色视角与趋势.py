def _载(块名, 导出名):
    """纯 `.jk` 块：过极快运行时按相对路径加载。"""
    import jikuai
    模块 = jikuai.load(f"{块名}/{块名}.jk", base_dir=str(块根))
    return getattr(模块, 导出名)


def _载背衬(块名, 导出名):
    """带 `.py` 背衬的块：直接按文件路径加载背衬，不走 `.jk` 门面
    （门面靠 `蟒:` 桥转导，import 路径在测试环境里不稳）。同 W171 的做法。"""
    路径 = 块根 / 块名 / (块名 + ".py")
    规格 = importlib.util.spec_from_file_location("w172_" + 块名, 路径)
    模块 = importlib.util.module_from_spec(规格)
    规格.loader.exec_module(模块)
    return getattr(模块, 导出名)


