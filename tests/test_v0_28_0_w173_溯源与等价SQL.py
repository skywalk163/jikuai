# -*- coding: utf-8 -*-
"""v0.28.0 W173 · 溯源面板 + 等价 SQL 导出 + 数据质量检查的 pytest 断言。

**要解决的事**：v0.27.0 之前，「这个数是怎么来的」只能靠人去读 `方案.json` 再对着块库
翻 `块.json`。赛题要的可解释性下限是**四要素同时在场**：块名 / 版本 / 口径声明 /
生成的 `.jk` 源码行。`tools/ai-bridge/溯源.py 面板` 把这四样一次性出出来。

**等价 SQL 是给人看的，不是给机器跑的**。本模块最要紧的三条断言都在守这个：

1. `溯源.py` **一行 SQL 都不执行**——源码里不许出现任何 DB-API import（§4）。
2. 没登记等价 SQL 的块**如实说「未登记」+ 给理由，绝不猜一段**（§3）。一段看着像样但
   口径错了的 SQL 比报错糟得多（AGENTS.md §四「会跑通、结果是错的」）。
3. `WITH` 全文**只在每一步都登记时才给**（§2）。半截 SQL 会被误当成「能跑的那份」。

**为什么 `质量体检` 刻意不登记**：它的输出是四元组 `[行数, 空值列与计数, 主键重复数,
外键孤儿行数]`，**不是一张表**，四项互不同构（两项还是字典）。硬写成一条 `SELECT` 会把
它伪装成一行数据，那正是第 2 条要防的事。§3 有断言钉住这个判断，别哪天顺手补上。

**数据质量检查不新增块**：复用既有 `质量体检`（导出 `体检`），交付物是一份可跑方案
（§5）。方案连同溯源产出物放 `赛题/chatbi/产出/W173-溯源与数据质量/`，**刻意放在子
目录**——`产出/` 与 `产出/留出/` 两层被 `test_v0_27_0_w149_共享类型.py` 钉成
「15 份 / 124 步」，混进去会把那两个历史数字改脏（沿用 W167/W172 建子目录的做法）。
§6 有断言守这一点。

数据集缺失时（`赛题/` 不进 wheel 与 sdist，ADR-40 §7）只 skip 需要真实数据的那几条。
"""

