@需产出
def test_两窗对照用的是真实度量列名而不是占位词(溯源):
    """`基线偏离` 的 SQL 必须投影上游那张表的**真实度量列**（本方案是
    `单车电耗均值`，由第 4 个实参 `赵现成列名` 给出）。这里曾经写死过一个占位
    的「度量」——那种 SQL 贴到库里会直接报列不存在，属于「看着像样、其实错」。"""
    导出 = 溯源.等价SQL(溯源.读方案(str(R1方案)))
    基偏 = 导出["对照"][5]
    assert 基偏["块"] == "基线偏离"
    assert "单车电耗均值 AS 基线值" in 基偏["SQL"], 基偏["SQL"]
    assert "单车电耗均值 AS 观察值" in 基偏["SQL"], 基偏["SQL"]
    # `对齐` 是三态，所以必须 FULL OUTER JOIN：内连接会把「只有一侧有」的组丢掉
    assert "FULL OUTER JOIN" in 基偏["SQL"]
    assert "AS 对齐" in 基偏["SQL"]


@需产出
def test_登记的列名与聚合口径逐字照块(溯源):
    """列名不是凭印象写的：`单车电耗现成` 的均值分母是**非空记录数**，
    SQL 侧靠 `AVG` 跳过 NULL 来对齐，不许改写成 `SUM/COUNT(*)`。"""
    导出 = 溯源.等价SQL(溯源.读方案(str(R1方案)))
