@需数据集
@需产出
def test_日报真能跑出来且四段数字与归档逐字一致():
    """交付物必须可复现：现跑一遍，stdout 四行要和归档结果里的四行逐字相等。

    这条同时是「日报不是手写的」的证据——手写的数字对不上现跑的输出。
    """
    环境 = dict(os.environ)
    环境["PYTHONIOENCODING"] = "utf-8"
    环境["PYTHONUTF8"] = "1"
    完 = subprocess.run(
        [sys.executable, "-m", "jikuai.pkg.blocks_cli", "跑",
         str(日报方案), "--json"],
        capture_output=True, cwd=str(仓库根), env=环境,
    )
    assert 完.returncode == 0, 完.stderr.decode("utf-8", "replace")
    出 = json.loads(完.stdout.decode("utf-8"))
    现跑 = 出["执行结果"]["stdout"].rstrip("\n").split("\n")
    assert len(现跑) == 4, 现跑
    归档 = 日报结果.read_text(encoding="utf-8")
    for 行 in 现跑:
        assert 行 in 归档, 行[:60]


@需数据集
@需产出
def test_产量榜首与停线榜首缺陷榜首同为L002而电耗榜首换人():
    """这一天的真实结构：产量最高的线同时停线最久、缺陷最多，但**电耗绝对量榜首
    是 L008 不是 L002**。

    后半句是 ADR-40 §5.5「绝对量 vs 比率排名」在日报里的具体样子——电耗绝对量高
    可能只是因为那条线开得多。把它钉成断言，防后人把四段「统一成一个榜」。
    """
    文 = 日报结果.read_text(encoding="utf-8")
    产量段, 停线段, 缺陷段, 能耗段 = (块 for 块 in _四段(文))
    assert 产量段[0]["line_id"] == "L002" and 产量段[0]["产量"] == 162
    停 = max(停线段, key=lambda 行: 行["停线合计分钟"])
    assert 停["line_id"] == "L002" and 停["停线合计分钟"] == 97
    assert 缺陷段[0]["line_id"] == "L002" and 缺陷段[0]["缺陷数"] == 17
    电 = max(能耗段, key=lambda 行: 行["电耗"])
    assert 电["line_id"] == "L008", "绝对量榜首换人才是 §5.5 的样子"
    assert 电["line_id"] != 产量段[0]["line_id"]


def _四段(文):
    """从归档结果里把四行 Python 字面量还原成对象（`打印` 出的是 repr）。"""
    import ast
    for 行 in 文.split("\n"):
        行 = 行.strip()
        if 行.startswith("[{") and 行.endswith("}]"):
            yield ast.literal_eval(行)


