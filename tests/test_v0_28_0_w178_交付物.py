@需产出
def test_本轮产出物在子目录_十五份一二四步一个都没动():
    """`test_v0_27_0_w149_共享类型.py::_收集真实方案` 用 `os.listdir` **不递归**地扫
    `产出/` 与 `产出/留出/` 两层，只收 `-方案.json`。本轮日报方案放
    `产出/W178-运营日报/`，`交付物清单.md` 虽在根目录但不匹配那个后缀，
    所以两个历史数字一个都不动。这条断言就是那件事的守卫。"""
    份数 = 0
    步数 = 0
    for 根 in (产出根, 产出根 / "留出"):
        if not 根.is_dir():
            continue
        for 名 in sorted(p.name for p in 根.iterdir()):
            if 名.endswith("-方案.json"):
                份数 += 1
                方案 = json.loads((根 / 名).read_text(encoding="utf-8"))
                步数 += len(方案.get("步骤") or [])
    assert 份数 == 15, 份数
    assert 步数 == 124, 步数
    assert 日报方案.is_file()
    assert 清单.is_file() and not 清单.name.endswith("-方案.json")
