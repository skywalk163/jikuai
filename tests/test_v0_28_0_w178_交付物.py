@需产出
@pytest.mark.parametrize("块,分歧点", [
    ("达成率权重", "§5.1"), ("达成率均值", "§5.1"),
    ("缺陷率", "§5.3"),
    ("单车电耗现成", "§5.2/§5.5"), ("单车电耗重算", "§5.2/§5.5"),
])
def test_日报不含任何撞分歧点的块(块, 分歧点):
    """日报是给一群人看的同一张纸，出比率就等于替所有人选了一侧口径。

    要那些数就单独问一句，让 `jk 块 规划` 的 `分歧告警` 逼着显式选（规则 3）。
    这条不是风格偏好——`缺陷率` 那处另一侧口径**本身是错的**（ADR-40 §5.3，
    实测差 57%），日报里出一个错口径比不出更坏。
    """
    方案 = json.loads(日报方案.read_text(encoding="utf-8"))
    块们 = [步["块"] for 步 in 方案["步骤"]]
    assert 块 not in 块们, "%s 撞 ADR-40 %s，日报不出" % (块, 分歧点)


