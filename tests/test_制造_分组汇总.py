import importlib.util
import os

import pytest

_块目录 = os.path.join(
    os.path.dirname(__file__), '..', 'src', 'jikuai', 'stdlib',
    'blocks', '制造', '分组汇总')


def _载入背衬():
    路径 = os.path.join(_块目录, '分组汇总.py')
    spec = importlib.util.spec_from_file_location('_制造_分组汇总背衬', 路径)
    模块 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(模块)
    return 模块


维聚 = _载入背衬().维聚


# ── 描述文本：划清界限断言（把「不是定长切块」钉死）──────────────────────

