# ── 单/多维度分组 ──────────────────────────────────────────────────────

def test_单维度分组():
    表 = [
        {'型': 'M001', '量': 10},
        {'型': 'M002', '量': 5},
        {'型': 'M001', '量': 20},
    ]
    组 = 维聚(表, ['型'], '量')
    assert len(组) == 2
    assert 组[0] == {'型': 'M001', '行数': 2, '非空个数': 2,
                     '求和': 30, '均值': 15.0, '最大': 20, '最小': 10}
    assert 组[1]['型'] == 'M002'
    assert 组[1]['求和'] == 5


def test_多维度分组():
    表 = [
        {'型': 'M001', '班': '白', '量': 3},
        {'型': 'M001', '班': '夜', '量': 4},
        {'型': 'M001', '班': '白', '量': 5},
    ]
    组 = 维聚(表, ['型', '班'], '量')
    assert len(组) == 2
    # 升序：夜(U+591C) < 白(U+767D)
    assert 组[0]['班'] == '夜' and 组[0]['行数'] == 1
    assert 组[1]['班'] == '白' and 组[1]['行数'] == 2 and 组[1]['求和'] == 8


# ── 度量列含空值 ───────────────────────────────────────────────────────

def test_度量列空值_行数不等于非空个数_均值分母用非空个数():
    表 = [
        {'型': 'A', '量': 10},
        {'型': 'A', '量': None},   # 极快 `空` ↔ Python None
        {'型': 'A', '量': 20},
    ]
    组 = 维聚(表, ['型'], '量')[0]
    assert 组['行数'] == 3          # COUNT(*)
    assert 组['非空个数'] == 2       # COUNT(col)，与行数不等
    assert 组['求和'] == 30
    assert 组['均值'] == 15.0        # 30/2，分母是非空个数(2) 而非行数(3)


def test_度量列全组皆空_求和与均值返回空():
    表 = [{'型': 'B', '量': None}, {'型': 'B', '量': None}]
    组 = 维聚(表, ['型'], '量')[0]
    assert 组['行数'] == 2
    assert 组['非空个数'] == 0
    assert 组['求和'] is None       # 「没有数据」≠「合计为零」，不是 0
    assert 组['均值'] is None
    assert 组['最大'] is None and 组['最小'] is None


# ── 分组键含空值：自成一组 + 守恒 ─────────────────────────────────────

def test_分组键空值自成一组_且行数守恒():
    表 = [
        {'型': 'X', '量': 1},
        {'型': None, '量': 2},
        {'型': 'X', '量': 3},
        {'型': None, '量': 4},
    ]
    组 = 维聚(表, ['型'], '量')
    assert len(组) == 2
    # 空键组排最前
    assert 组[0]['型'] is None and 组[0]['行数'] == 2
    assert 组[1]['型'] == 'X' and 组[1]['行数'] == 2
    # 守恒：各组行数之和 == 原表行数（空值若被丢弃这条就会破）
    assert sum(g['行数'] for g in 组) == len(表)


# ── 空表 ───────────────────────────────────────────────────────────────

def test_空表返回空结果():
    assert 维聚([], ['型'], '量') == []


# ── 缺列报错：不静默返回空表 ──────────────────────────────────────────

def test_度量列不存在报错():
    表 = [{'型': 'A', '量': 1}]
    with pytest.raises(ValueError) as e:
        维聚(表, ['型'], '不存在')
    assert '度量列' in str(e.value) and '不存在' in str(e.value)


def test_维度列不存在报错():
    表 = [{'型': 'A', '量': 1}]
    with pytest.raises(ValueError) as e:
        维聚(表, ['没这列'], '量')
    assert '维度列' in str(e.value)


def test_参差表_某行缺列也报错():
    # 只查首行会漏掉这种参差表，导致第 2 行悄悄按空值入组。
    表 = [{'型': 'A', '量': 1}, {'型': 'A'}]
    with pytest.raises(ValueError):
        维聚(表, ['型'], '量')


def test_空维度列报错():
    with pytest.raises(ValueError):
        维聚([{'型': 'A', '量': 1}], [], '量')


def test_维度列与聚合列名撞车报错():
    表 = [{'行数': 'A', '量': 1}]
    with pytest.raises(ValueError) as e:
        维聚(表, ['行数'], '量')
    assert '撞车' in str(e.value)


def test_度量列非空非数值报错():
    表 = [{'型': 'A', '量': '不是数'}]
    with pytest.raises(ValueError) as e:
        维聚(表, ['型'], '量')
    assert '非数值' in str(e.value)


# ── 行序确定 ───────────────────────────────────────────────────────────

def test_行序确定_两次调用完全相同():
    表 = [
        {'型': 'M003', '量': 1},
        {'型': None, '量': 2},
        {'型': 'M001', '量': 3},
        {'型': 'M002', '量': 4},
        {'型': 'M003', '量': 5},
    ]
    甲 = 维聚(表, ['型'], '量')
    乙 = 维聚(表, ['型'], '量')
    assert 甲 == 乙
    # 升序：None 最前，其后字符串升序
    键序 = [g['型'] for g in 甲]
    assert 键序 == [None, 'M001', 'M002', 'M003']


# ── 多聚合量一趟出（不必扫表四次）────────────────────────────────────

def test_一趟遍历同时给出五个聚合量():
    表 = [{'型': 'A', '量': v} for v in (4, 2, 8, 6)]
    组 = 维聚(表, ['型'], '量')[0]
    assert (组['求和'], 组['非空个数'], 组['均值'], 组['最大'], 组['最小']) \
        == (20, 4, 5.0, 8, 2)
