def main():
    idx = json.load(open(索引路径, encoding='utf-8'))
    描述 = {b['名称']: b.get('描述', '') for b in (idx.get('块') or [])}

    out = sys.stdout.buffer
    过 = []
    挂 = []
    for 编号, 块名, 维度, 口径词 in 核查表:
        desc = 描述.get(块名)
        if desc is None:
            标, 桶 = '块不存在?!', 挂
        elif 口径词 in desc:
            标, 桶 = '自报口径 ✓ 规则2可触发', 过
        else:
            标, 桶 = '未自报口径 ✗ 规则2无法触发', 挂
        桶.append((编号, 块名, 维度, 口径词))
        out.write(('%-11s %-8s 维度[%s] 口径词「%s」 %s\n'
                   % (编号, 块名, 维度, 口径词, 标)).encode('utf-8'))
        if desc is not None:
            out.write(('              描述：%s\n' % desc).encode('utf-8'))

    out.write(('\n通过 %d 处 / 挂起 %d 处\n' % (len(过), len(挂))).encode('utf-8'))
    if 挂:
        out.write('\n挂起明细（这些条目上「看描述限定词」规则物理上无法触发）：\n'
                  .encode('utf-8'))
        for 编号, 块名, 维度, 口径词 in 挂:
            out.write(('  %s · %s 块在「%s」维度无口径声明（应补：%s）\n'
                       % (编号, 块名, 维度, 口径词)).encode('utf-8'))
    # 按用例去重统计：一条负例只要有任一兄弟块自报了口径，规则2就有着力点
    有着力点 = {e for e, _, _, _ in 过}
    全部 = {e for e, _, _, _ in 核查表}
    out.write(('\n按用例：%d/%d 条负例至少有一个兄弟块自报了口径；无着力点的用例 %s\n'
               % (len(有着力点), len(全部),
                  sorted(全部 - 有着力点) or '无')).encode('utf-8'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
