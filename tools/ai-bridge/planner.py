# W156 · 上下文包构造器
# ---------------------------------------------------------------------------

def build_context(需求, top=8, 索引路径=None, 语义层路径=None,
                  query_vector=None):
    """问句 → **规划上下文包**（`jk 块 规划` 的出口）。

    Args:
        需求: 自然语言问句（中文）。
        top: 候选数上限。默认 8 而不是 `选` 的 5——上下文包的候选带槽信息，
            多给两三条的 token 代价换 LLM 少猜一次口径，划得来。
        索引路径 / 语义层路径: 测试与第三方块库用；缺省走内置块库。
        query_vector: 给了才走神经检索路径（口径同 `retrieval.retrieve`）。

    Returns:
        `schema.make_context_envelope` 的产物。**出门前自查**一遍
        `validate_context_envelope`，不通过直接抛——规划器吐一个自己都不合法的包
        比不吐更糟（W157 的校验器会拿它当参照，参照错了后面全错）。
    """
    hits = retrieval.retrieve(需求, top, query_vector)
    元表 = _索引表(索引路径)
    if 元表 is None:
        # 见 `_索引表` 的说明：没索引就没槽信息，此时吐包会静默卸掉规则 1。
        raise schema.SchemaError(
            '读不到块索引 %s，规划器拒绝出上下文包。没有 `输入槽` 的候选会让'
            '回填校验器的规则 1 退化成「实参必须是空数组」，等于把防静默错绑的'
            '唯一闸卸掉。请先跑 scripts/generate_block_index.py 或检查部署'
            % (索引路径 or 默认索引路径()))
    导出表 = schema.export_table(索引路径)
    层级表 = schema.level_table(索引路径)
    候选表 = [_候选(h, 元表, 导出表, 层级表) for h in hits]
    命中表 = 语义命中(需求, 语义层路径)
    # W174 语义层直取旁路：**追加**在 top-K 之后，不挤掉任何一条词面候选。
    # 顺序有意如此——读包的人先看到 TF-IDF 认为最相关的，再看到「语义层说这问句
    # 落在这张表上，链路上还会用到这些」。`top` 因此只约束词面那一段，旁路那一段
    # 由语义命中决定条数（实测均值 +7 上下）。这不是偷偷调大 top：调大 top 是让
    # TF-IDF 往下多吐一批，旁路吐的是 TF-IDF 排到 14-95 名、词面永远捞不上来的块。
    候选表 = 候选表 + _语义旁路(
        命中表, 元表, 导出表, 层级表, {c[_F名称] for c in 候选表})
    告警表 = _分歧告警(需求)
    信封 = schema.make_context_envelope(
        需求=需求, 语义命中=命中表, 候选=候选表,
        回填契约=_回填契约(), 拒答建议=_拒答建议(命中表, 候选表),
        分歧告警=告警表 or None)
    errs = schema.validate_context_envelope(信封)
    if errs:
        raise schema.SchemaError(
            '规划器自查未过（这是规划器自己的 bug，不是调用方的）：%s'
            % '；'.join(errs))
    return 信封


