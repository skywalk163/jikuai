# 语义层直取旁路（W174 · ADR-41 §9）
# ---------------------------------------------------------------------------
# **为什么不是 WBS 原文那条**：WBS 写的是「按语义层业务词命中直接把对应块注入候选」。
# 那一档（下称变体 A）实测 `白名单可承载率` 调优 **0.0%** / 留出 **0.0%**，一点没动。
# 根因诊断（`tools/ai-bridge/bench_planner.py` 的明细 + W174 天花板模拟）：K=8 漏掉的
# 块按频次是 `表载入` 20/20、`窗口` 17、`选取` 12、`连接` 5、`取前N` 4、`排序` 3
# ——全是**通用管道块**，它们的 `描述` 里没有任何表名，所以「业务词 → 表 → 描述提到
# 该表的块」这条映射**结构上永远碰不到它们**。缺的不是口径块，是链路骨架。
#
# 有效的是再走**两跳**，且两跳都读块作者**已经写下**的字段，不新建任何手工清单：
#   一跳（口径块）：命中业务词的 `表` 出现在某个制造域块的 `描述` 里。
#   二跳（邻居）  ：该口径块 `块.json` 的 `示例` 里 `从 blocks.X.Y 导入` 点名的块，
#                   以及它 `描述` 里以 `制造/块名` 形式点名的兄弟块。
# 实测（块库 145，`bench_planner.py` 自己的判据：录像方案的块全进候选才算装得下；
# 每格 = 调优 / 留出）：
#   基线 K=8   0.0% / 0.0%（候选 8.0）
#   一跳只做   0.0% / 0.0%（候选 11.6 / 11.2）  ← WBS 原意，证伪
#   两跳全做  60.0% / 60.0%（候选 16.5 / 15.6） ← 本实现。期望块完整命中率同时
#                                                 0.0% → 53.3% / 60.0%
#   对照 K=40 20.0% / 20.0%（候选 40，旁路关）
# 即：默认 K 不动、候选只从 8 涨到 ~16，比把 K 调到 40（候选 ×5）高三倍。**留出档同涨**，
# 不是过拟合。（BACKLOG 原文记的 K=40 = 30.0% 是块库 139 时的数，145 下实测 20.0%——
# 新块进来摊薄排名，所以「调大 top」的收益随库增长反向缩水，旁路不随。）

#
# 另有一档「无条件注入手工挑的 6 块骨架」调优 80% 但留出仍 60%，多出的 20 点全在
# 调优档、而那 6 块名单正是从调优档诊断里挑的 —— 按「只有留出集也涨才算真涨、留出集
# 只当裁判」判为过拟合，**不取**。
#
# 边界：旁路只在**制造域**内做（与语义层作用域一致），只走内置块库；`retrieval.py`
# 一行未改，`jk 块 选` 照旧永不拒答、永远 top-K。

#: 从 `示例` 里抓 `从 blocks.<域>.<块名> 导入`。只取块名，域由索引条目本身决定。
_旁路示例导入 = re.compile(r'从\s+blocks\.[^\s.]+\.([^\s.，。]+)\s+导入')
#: 从 `描述` 里抓 `制造/<块名>` 这种兄弟块点名写法。
_旁路描述兄弟 = re.compile(r'制造/([\u4e00-\u9fffA-Za-z0-9]+)')

#: 旁路注入的候选 `分数` 恒为此值。它**不是** TF-IDF 相关度，也不可与之比较——
#: 这条候选是「语义层判定该问句落在这张表上」进来的，与词面分数没有可比量纲。
_旁路分数 = 0.0


def _块邻居(名称, 元表):
    """一个口径块的邻居块名（`示例` 导入行 ∪ `描述` 里的 `制造/X`）。行序确定。

    `描述` 走索引（一定在），`示例` 要读 `块.json`（索引条目里没有这个字段）。
    读不到 `块.json` 时**只丢掉 `示例` 那一跳**，`描述` 那一跳照旧——把两跳一起
    `except` 掉会让旁路静默退化成一跳，而一跳的实测收益是 0.0%：那样门禁全绿、
    数字也「有」，只是等于没做（W174 首版模拟就栽在这个吞异常上）。
    """
    条目 = 元表.get(名称) or {}
    出 = []

    def _收(块名):
        if (块名 in 元表 and 块名 not in 出
                and '制造' in (元表[块名].get(_I领域) or ())):
            出.append(块名)

    from jikuai.pkg.blocks import BlockError, blocks_root, load_block_metadata
    域 = (条目.get(_I领域) or ['制造'])[0]
    try:
        示例 = load_block_metadata(os.path.join(blocks_root(), 域, 名称)).example
    except (BlockError, OSError):
        # 只兜「块目录读不到」这一种，且**只丢 `示例` 这一跳**。不写成裸 except：
        # 那会把「元数据格式变了」这类真 bug 一起吞成「旁路少注入几块」。
        示例 = ''
    for 块名 in _旁路示例导入.findall(示例 or ''):
        _收(块名)
    for 块名 in _旁路描述兄弟.findall(条目.get(_I描述) or ''):
        _收(块名)
    return 出


def _语义旁路(命中表, 元表, 导出表, 层级表, 已选):
    """语义层命中 → 补注入候选（`路径 = [语义层]`）。见本节头部的实测与取舍。

    `已选` 是已在候选里的块名集合，**就地更新**：去重键与规则 2 白名单同源，
    重复注入同一块会让 `_候选索引` 后写覆盖前写，读包的人看到两条一样的候选。
    """
    表集 = {h.get(_F表) for h in 命中表 if h.get(_F表)}
    if not 表集:
        return []                     # 没有制造域语义命中 ⇒ 旁路整条不启动
    种子 = [名 for 名, 条 in 元表.items()
            if '制造' in (条.get(_I领域) or ())
            and any(表 in (条.get(_I描述) or '') for 表 in 表集)]
    注入 = list(种子)
    for 名 in 种子:
        for 邻 in _块邻居(名, 元表):
            if 邻 not in 注入:
                注入.append(邻)
    出 = []
    for 名 in 注入:
        if 名 in 已选:
            continue
        条 = 元表[名]
        hit = retrieval.Hit(
            score=_旁路分数, name=名,
            domain=(条.get(_I领域) or ['制造'])[0],
            description=条.get(_I描述) or '',
            path=retrieval.PATH_SEMANTIC)
        出.append(_候选(hit, 元表, 导出表, 层级表))
        已选.add(名)
    return 出


