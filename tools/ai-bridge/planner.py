def _cmd上下文(args):
    包 = build_context(args.需求, top=args.top)
    print(json.dumps(包, ensure_ascii=False, indent=2))
    return 0


def _cmd校验(args):
    理由 = validate_filled(_读json(args.回填), _读json(args.上下文包),
                           严格=args.严格)
    if not 理由:
        print('通过')
        return 0
    for r in 理由:
        print('拒：%s' % r, file=sys.stderr)
    return 1


def main(argv=None):
    """命令行入口。返回进程退出码，遵循本仓约定：`0` 成功 / `1` 输入错误。

    两个子命令：`上下文 <需求>` 把上下文包打到 stdout（JSON）；
    `校验 <回填.json> <上下文包.json>` 把拒绝理由打到 stderr 并回 1，通过则回 0。

    异常一律收敛成「一句中文 + 退 1」（W157 review C008/M001，v0.28.0 W176 清账）：
    文件不存在、JSON 语法错、包不合法都是**调用方的输入问题**，吐 traceback 只会让人
    去读 `planner.py` 的行号。`SchemaError` 是 `ValueError` 子类、`JSONDecodeError`
    也是，所以一条 `except (OSError, ValueError)` 盖住三类；`UnicodeEncodeError`
    同样在 `ValueError` 下（v0.27.0 复盘必记单点 1），不会漏。
    """
    p = argparse.ArgumentParser(
        description='规划器：上下文包构造 + 回填硬校验（ADR-41）')
    subs = p.add_subparsers(dest='子命令')
    a = subs.add_parser('上下文', help='问句 → 规划上下文包 JSON')
    a.add_argument('需求')
    a.add_argument('--top', type=int, default=8)
    a.set_defaults(func=_cmd上下文)
    b = subs.add_parser('校验', help='回填响应 + 上下文包 → 拒绝理由')
    b.add_argument('回填')
    b.add_argument('上下文包')
    b.add_argument('--严格', action='store_true')
    b.set_defaults(func=_cmd校验)
    args = p.parse_args(argv)
    if not getattr(args, 'func', None):
        p.print_help()
        return 1
    try:
        return args.func(args)
    except (OSError, ValueError) as e:
        print('错：%s' % e, file=sys.stderr)
        return 1



if __name__ == '__main__':
    sys.exit(main())
