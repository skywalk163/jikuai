_CENT = Decimal("0.01")


def _to_fen(value) -> int:
    """元 → 分。在 Python 侧用 Decimal 精确换算，保证字面量零误差。

    与 evaluator.RMB._quantize 同口径：先经 str 进 Decimal（避开 float 的
    二进制表示误差），再 ROUND_HALF_UP 量化到分。
    """
    dec = value if isinstance(value, Decimal) else Decimal(str(value))
    return int(dec.quantize(_CENT, rounding=ROUND_HALF_UP) * 100)


def _c_double(value: float) -> str:
    """输出 C 能精确还原的 double 字面量（repr 给最短往返表示）。"""
    if value != value:
        return "(0.0/0.0)"
    if value == float("inf"):
        return "(1.0/0.0)"
    if value == float("-inf"):
        return "(-1.0/0.0)"
    text = repr(value)
    if "." not in text and "e" not in text and "E" not in text:
        text += ".0"
    return text


def _c_escape(text: str) -> str:
    """把 Python str 转成 C 字符串字面量内容。

    非 ASCII 一律按 UTF-8 编码后逐字节转成八位十六进制转义（前导反斜杠 x），
    这样生成的 C 不依赖编译器的源字符集设置，gcc -std=c11 与 MSVC 行为一致。
    转义序列后紧跟十六进制字符会被 C 贪婪吞掉，所以每个字节转义后主动断开
    字符串，交由 C 的相邻字面量拼接规则合并。
    """
    out: List[str] = []
    simple = {
        "\\": "\\\\",
        '"': '\\"',
        "\n": "\\n",
        "\r": "\\r",
        "\t": "\\t",
        "\a": "\\a",
        "\b": "\\b",
        "\f": "\\f",
        "\v": "\\v",
        "\0": "\\0",
    }
    for ch in text:
        if ch in simple:
            out.append(simple[ch])
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            for byte in ch.encode("utf-8"):
                out.append('\\x{:02x}" "'.format(byte))
    return "".join(out)


