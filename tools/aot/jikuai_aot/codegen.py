"""极快 AOT · C 中间码生成器（T-M6-A02 · ADR-19）。

把**已通过 subset_gate.check** 的 AST 翻译成可被 gcc -std=c11 编译的 C 源码。
调用方有义务先过门禁；本模块对子集外节点一律抛 CodegenError，而不是「尽力
翻译」——静默产出语义不对的产物比报错糟糕得多。

类型策略（动态 → 静态的降级方案）
--------------------------------
极快是动态类型，C 是静态类型。第一版用 tagged union（见 _C_RUNTIME 里的
JKValue）：所有运算走运行时辅助函数（jk_add / jk_lt / ...），在函数内部按
tag 分派，相当于把解释器的动态派发下沉到 C 层。代价是拿不到静态类型特化的
性能上限，收益是语义与解释器一致、实现量小、可审计。

人民币精度（ADR-19 硬要求）
--------------------------
**绝不用 double 存金额。** JK_RMB 用 long long 存「分」：￥99.90 → 9990。
字面量的「元 → 分」换算在 Python 侧用 Decimal 精确完成，所以字面量零误差。
只有运行时「金额 × 浮点因子」这类混算才会退化到 double 中转，该边界写进了
docs/AOT.md 局限清单。

中文字符串
----------
C 源码里直接写 UTF-8 字节转义（反斜杠 x 加两位十六进制），不依赖编译器的
源字符集推断。Windows 下 main() 开头调用 SetConsoleOutputCP(65001)，保证
控制台按 UTF-8 渲染；重定向到管道/文件时本来就是原始字节，不受影响。

浮点打印
--------
解释器用 Python 的 str(float)，即最短往返表示（repr）。C 的 %g 没有这个
语义，所以运行时用「精度 1..17 逐级尝试 + strtod 往返校验」复现它，并对
整数值浮点补 .0（Python 打印 3.0 而非 3）。
"""

